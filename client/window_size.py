"""Размеры окна: каким оно открывается и в какой миг вырастает.

Живёт отдельно от самого окна, потому что спрашивают эти размеры двое и с
разных сторон: окно — когда открывается, мост — когда мастер дошёл до конца.
Положи их в `client.window`, и мосту пришлось бы ввозить окно, которое ввозит
мост.
"""

from __future__ import annotations

from adapters.platforms import window as platform_window


WIZARD = (640, 620)
"""Окно мастера.

Меньше основного и не тянется вовсе: на экране мастера одна колонка полей, и
растягивать в ней нечего, а на ширине основного окна она расплывается полосой
пустоты.
"""

MAIN = (900, 660)
"""Окно настроенного приложения, оно же наименьшее для него.

Начальный равен наименьшему нарочно: разметка нарисована под эту ширину и ниже
неё переносится и ломается. Расти окно может сколько угодно.
"""


def grow_to_main(window) -> None:
    """Вырастить окно мастера до окна приложения, не сдвинув его середину.

    Рама отпускается первой: окно мастера создано нерастягиваемым, и наименьший
    размер у него — размер мастера. Поезжай оно раньше, система прижала бы его
    обратно, и человек увидел бы приложение в окне мастера.

    Прирост расходится во все стороны поровну. Окно уже стоит там, куда его
    поставил человек, и смотрит он в середину; расти оно вниз и вправо, как
    растёт само, — середина уехала бы из-под взгляда, а на небольшом экране
    правый край ушёл бы за него.
    """
    _unlock_frame(window.native)
    window.move(
        window.x - (MAIN[0] - WIZARD[0]) // 2,
        window.y - (MAIN[1] - WIZARD[1]) // 2,
    )
    window.resize(*MAIN)


def _unlock_frame(form) -> None:
    platform_window.unlock_frame(form, MAIN)
