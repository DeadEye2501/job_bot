// Следствия списка вакансий: подписи строки, цвет оценки и порядок.

import { describe, expect, it } from 'vitest';

import {
  SORTS,
  ago,
  blankVacancy,
  emptyNote,
  pasteLock,
  salaryLabel,
  scoreTone,
  settleHandMade,
  shortAgo,
  shownStack,
  sortKey,
  vacancyLine,
  vacancyNamed,
} from '../state/vacancies.js';

const NOW = new Date('2026-08-14T21:00:00');

describe('пустой список', () => {
  it('пусто при наборе в поиске — говорим, чего именно не нашли', () => {
    // Человек ищет посимвольно и к третьему знаку уже не помнит, что набрал.
    // Надпись без запроса заставляет его смотреть в поле поиска и гадать.
    expect(emptyNote('питон').text).toBe('Ничего не найдено по запросу «питон».');
  });

  it('пусто без набора — зовём включить бота', () => {
    // Два разных положения дел: тут искать нечего, а не «не нашлось», и
    // человеку нужно сказать, чем это чинится.
    expect(emptyNote('').text)
      .toBe('Вакансий пока нет.\nВключите бота в нижнем баре, чтобы начать сбор.');
  });

  it('у пустого поиска и пустого списка разные значки', () => {
    // Значок читается раньше текста: по нему видно, поломка это или просто
    // ничего не нашлось.
    expect(emptyNote('питон').icon).toBe('search_off');
    expect(emptyNote('').icon).toBe('inbox');
  });
});

describe('пилюля зарплаты', () => {
  it('названы обе границы — «от» и «до», единица после числа', () => {
    // Единственный род зарплаты, который пилюля показывает, — названный
    // числами. Слова автора поста («по итогам собеседования») в неё не идут.
    expect(salaryLabel({ salary_min: 1000, salary_max: 2000, salary_currency: '֏' }))
      .toBe('от 1000 до 2000 ֏');
  });

  it('названа одна нижняя — «от»', () => {
    expect(salaryLabel({ salary_min: 1000, salary_max: null, salary_currency: '֏' }))
      .toBe('от 1000 ֏');
  });

  it('названа одна верхняя — «до»', () => {
    expect(salaryLabel({ salary_min: null, salary_max: 2000, salary_currency: '֏' }))
      .toBe('до 2000 ֏');
  });

  it('границы равны — это точная сумма, и предлог ей не нужен', () => {
    expect(salaryLabel({ salary_min: 1500, salary_max: 1500, salary_currency: '֏' }))
      .toBe('1500 ֏');
  });

  it('чисел нет — пилюли нет вовсе', () => {
    // «Зарплата по результатам собеседования» — не число, и показывать в
    // пилюле нечего.
    expect(salaryLabel({ salary_min: null, salary_max: null, salary_currency: null }))
      .toBe('');
  });

  it('единица не опознана — число печатают без значка', () => {
    // Прятать разобранную сумму из-за неизвестного написания валюты хуже, чем
    // показать её без значка.
    expect(salaryLabel({ salary_min: 1500, salary_max: 1500, salary_currency: null }))
      .toBe('1500');
  });
});

describe('строка вакансии', () => {
  it('под названием стоят компания, грейд, зарплата и давность', () => {
    // По ним вакансию узнают в списке, не открывая: четыре слова говорят,
    // стоит ли она того, чтобы её открыть.
    const line = vacancyLine(
      {
        title: 'Python-разработчик',
        company: 'Ромашка',
        grade: 'senior',
        salary_min: 200000,
        salary_max: 200000,
        salary_currency: '₽',
        last_activity_at: '2026-08-14T20:00:00',
      },
      NOW,
    );
    expect(line).toEqual({
      title: 'Python-разработчик',
      company: 'Ромашка',
      grade: 'Senior',
      salary: '200000 ₽',
      when: '1 ч',
    });
  });

  it('пустые половины подписи названы прочерком', () => {
    // Пустое место читалось бы как недогрузившаяся строка, а прочерк говорит
    // «в объявлении этого не было».
    const line = vacancyLine(
      {
        title: '',
        company: '',
        grade: '',
        salary_min: null,
        salary_max: null,
        salary_currency: null,
        last_activity_at: null,
      },
      NOW,
    );
    expect(line).toEqual({
      title: '—', company: '—', grade: '—', salary: '—', when: '—',
    });
  });

  it('давность берут по последнему движению, а не по дате объявления', () => {
    // Порядок в списке идёт по той же метке: разойдись они, свежая сверху
    // строка называла бы себя месячной давностью.
    const line = vacancyLine(
      {
        title: 'x',
        company: 'x',
        grade: '',
        last_activity_at: '2026-08-14T18:00:00',
        created_at: '2026-05-01T10:00:00',
      },
      NOW,
    );
    expect(line.when).toBe('3 ч');
  });
});

describe('давность словом', () => {
  it('меньше минуты — «только что»', () => {
    expect(ago('2026-08-14T20:59:40', NOW)).toBe('только что');
  });

  it('дни, недели и месяцы называются своими словами', () => {
    expect(ago('2026-08-11T21:00:00', NOW)).toBe('3 д');
    expect(ago('2026-07-24T21:00:00', NOW)).toBe('3 нед');
    expect(ago('2026-05-16T21:00:00', NOW)).toBe('3 мес');
  });

  it('без даты — прочерк', () => {
    // Такое приходит от записей, у которых нет ни движения, ни даты
    // объявления: пустое место выглядело бы поломкой.
    expect(ago(null, NOW)).toBe('—');
  });

  it('неразбираемая дата читается как её отсутствие', () => {
    // Считать по ней нечего, а несчитанное лезет наружу числом: «NaN мес» в
    // колонке давности человек читает как поломку всего списка.
    expect(ago('позавчера', NOW)).toBe('—');
  });
});

describe('давность в тесной строке', () => {
  it('минуты и часы сокращены до буквы', () => {
    // Строка мини-списка стоит в узкой панели рядом с названием вакансии:
    // «мин» отнимает у названия три знака на каждой строке.
    expect(shortAgo('2026-08-14T20:30:00', NOW)).toBe('30 м');
    expect(shortAgo('2026-08-14T19:00:00', NOW)).toBe('2 ч');
  });

  it('до двух недель считают днями, дальше — неделями', () => {
    // Список этот читают сверху вниз и по порядку: «13 д» и «2 нед» подряд
    // говорят о давности больше, чем одни недели.
    expect(shortAgo('2026-08-01T21:00:00', NOW)).toBe('13 д');
    expect(shortAgo('2026-07-31T21:00:00', NOW)).toBe('2 нед');
  });

  it('после двух месяцев считают месяцами, после года — годами', () => {
    expect(shortAgo('2026-05-16T21:00:00', NOW)).toBe('3 мес');
    expect(shortAgo('2024-08-14T21:00:00', NOW)).toBe('2 года');
  });

  it('без даты остаётся пусто', () => {
    // Прочерк тут занял бы колонку, которая в узкой строке нужна названию.
    expect(shortAgo(null, NOW)).toBe('');
  });

  it('неразбираемая дата тоже не даёт числа', () => {
    // Голова у обеих лестниц общая, а пустота здесь своя: «NaN лет» рядом с
    // названием вакансии съело бы колонку и соврало бы вдобавок.
    expect(shortAgo('позавчера', NOW)).toBe('');
  });
});

describe('цвет оценки', () => {
  it('оценка ниже порога отбора — плохая', () => {
    // Порог — это черта, по которой бот решает откликаться; строка под ней
    // должна читаться как отвергнутая.
    expect(scoreTone(40, 60)).toBe('bad');
  });

  it('оценка чуть выше порога — сомнительная', () => {
    expect(scoreTone(70, 60)).toBe('warn');
  });

  it('оценка много выше порога — хорошая', () => {
    expect(scoreTone(95, 60)).toBe('good');
  });

  it('без оценки цвета нет вовсе', () => {
    // Неразобранная вакансия оценки не имеет, и красить её было бы враньём.
    expect(scoreTone(null, 60)).toBe('');
  });

  it('без порога цвета нет тоже', () => {
    // До первого ответа моста порог неизвестен, и сравнивать не с чем.
    expect(scoreTone(95, null)).toBe('');
  });
});

describe('порядок списка', () => {
  it('первым стоит тот, в котором список открывается', () => {
    expect(SORTS[0].key).toBe('newest');
  });

  it('у каждого порядка есть подпись', () => {
    // Ключи уезжают на мост, а человек выбирает словами.
    expect(SORTS.every((one) => one.label)).toBe(true);
  });
});

describe('выбор порядка словами', () => {
  it('подпись переводится в ключ, который понимает мост', () => {
    // Выпадающий список работает словами, а мост — ключами: их разбирает
    // `vacancies_list._order_for`, и незнакомый он молча сводит к умолчанию.
    // Уедь подпись в ключ — отбор так же молча вернулся бы к «сначала новые».
    expect(sortKey('Сначала высокие баллы')).toBe('score_desc');
  });

  it('незнакомая подпись сводится к порядку по умолчанию', () => {
    // Так бывает после правки перечня: показать список в неизвестном порядке
    // хуже, чем в том, в котором его открывают.
    expect(sortKey('Чего-то такого')).toBe('newest');
  });
});

describe('стек в строке', () => {
  it('в строку помещаются три пункта, остальные сосчитаны', () => {
    // Строка держится в одну высоту: пятый чип перенёс бы её на второй ряд, и
    // список перестал бы читаться столбцом.
    const stack = [{ name: 'a' }, { name: 'b' }, { name: 'c' }, { name: 'd' }, { name: 'e' }];
    const shown = shownStack(stack);
    expect(shown.chips.map((one) => one.name)).toEqual(['a', 'b', 'c']);
    expect(shown.more).toBe(2);
  });

  it('короткий стек не приписывает себе лишнего', () => {
    // «+0» человек читает как поломку.
    expect(shownStack([{ name: 'a' }]).more).toBe(0);
  });
});

describe('заслон формы заведения вакансии', () => {
  it('над пустой формой кнопка заперта', () => {
    // Мост такую всё равно отобьёт: строка без названия в списке выглядит
    // пустой. Открытая кнопка меняла бы карточку на плашку отказа.
    expect(vacancyNamed(blankVacancy())).toBe(false);
  });

  it('одного названия довольно', () => {
    // Остальное дописывают в карточке: ссылку и стек человек копирует не
    // всегда, а завести найденное надо в тот миг, когда увидел.
    expect(vacancyNamed({ ...blankVacancy(), title: 'Senior Python Developer' })).toBe(true);
  });

  it('пробелы названием не считаются', () => {
    // Пробельное название дошло бы до базы строкой, которую в списке не видно
    // и не найти поиском.
    expect(vacancyNamed({ ...blankVacancy(), title: '   ' })).toBe(false);
  });
});

describe('запор формы заведения вакансии', () => {
  const quiet = { running: false, lockedTip: '' };

  it('во время обхода текст не заводится: его разбирает конвейер на месте прогона', () => {
    expect(pasteLock({ mode: 'text' }, false, { ...quiet, running: true })).toBe('Идёт обход');
  });

  it('без живых систем текст не заводится, и слова — те же, что у кнопок бота', () => {
    expect(pasteLock({ mode: 'text' }, false, { ...quiet, lockedTip: 'Нет модели' })).toBe('Нет модели');
  });

  it('обход старше погасшей лампы: он кончится сам', () => {
    expect(pasteLock({ mode: 'text' }, false, { running: true, lockedTip: 'Нет модели' }))
      .toBe('Идёт обход');
  });

  it('поля без отклика обходу и лампам не мешают: ложатся в базу мимо бота', () => {
    expect(pasteLock({ mode: 'fields' }, false, { running: true, lockedTip: 'Нет модели' })).toBe('');
  });

  it('поля с откликом заперты обходом: передача идёт через место прогона', () => {
    expect(pasteLock({ mode: 'fields' }, true, { ...quiet, running: true })).toBe('Идёт обход');
    expect(pasteLock({ mode: 'fields' }, true, quiet)).toBe('');
  });

  it('текст свободен, когда всё живо и обхода нет', () => {
    expect(pasteLock({ mode: 'text' }, false, quiet)).toBe('');
  });
});

describe('итог ручного заведения', () => {
  /** Черновик, ушедший боту, — каким его держит оболочка. */
  const handedDraft = () => ({ draft: { ...blankVacancy(), raw_text: 'Ищем повара' }, handed: true });

  it('заведено — черновик сброшен, окно никуда не переходит', () => {
    const held = handedDraft();

    expect(settleHandMade(held, { outcome: 'ok', vacancy_id: 6 })).toBe(null);
    expect(held.draft).toEqual(blankVacancy());
  });

  it('повтор — черновик сброшен, переход на существующую', () => {
    const held = handedDraft();

    expect(settleHandMade(held, { outcome: 'duplicate', vacancy_id: 5 })).toBe(5);
    expect(held.draft).toEqual(blankVacancy());
  });

  it('неудача — черновик цел и по-прежнему не стирается закрытием окна', () => {
    // Отказ места прогона приходит вестью раньше ответа на зов, и окно
    // закрывается уже после него: сними оболочка тут отметку «отдано боту», и
    // закрытие стёрло бы набранное.
    for (const outcome of ['llm', 'embed', 'article', undefined]) {
      const held = handedDraft();

      expect(settleHandMade(held, { outcome, vacancy_id: null })).toBe(null);
      expect([held.draft.raw_text, held.handed]).toEqual(['Ищем повара', true]);
    }
  });
});
