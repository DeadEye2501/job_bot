// Следствия набора даты: что уходит в отбор и что видно в поле.

import { describe, expect, it } from 'vitest';

import { asIso, showDate, validDate } from '../state/dates.js';

describe('дата в поле и в отборе', () => {
  it('набранное д.м.г уходит в отбор ISO-датой', () => {
    // Мост ждёт ISO; уйди туда набранный текст, отбор по периоду молча
    // перестал бы работать.
    expect(asIso('14.08.2026')).toBe('2026-08-14');
  });

  it('ISO-дата показывается в поле как д.м.г', () => {
    expect(showDate('2026-08-14')).toBe('14.08.2026');
  });

  it('негодная дата отбивается', () => {
    // Красная рамка вместо тихой отправки мусора на мост: часы иначе
    // перекатывают 32 августа на сентябрь, и отбор идёт не по тем суткам.
    expect(validDate('32.08.2026')).toBe(false);
    expect(validDate('31.02.2026')).toBe(false);
  });

  it('недобранная дата ещё не негодна', () => {
    // Пока набирают, поле не должно краснеть на каждом знаке.
    expect(validDate('14.08.')).toBe(null);
    expect(validDate('')).toBe(null);
  });

  it('целая и существующая дата годна', () => {
    expect(validDate('14.08.2026')).toBe(true);
  });
});
