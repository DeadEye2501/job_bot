// Следствия набора даты: что уходит в отбор и что видно в поле.

import { describe, expect, it } from 'vitest';

import { asIso, dayOf, isoDay, showDate, showStamp, validDate } from '../state/dates.js';

describe('дата в поле и в отборе', () => {
  it('набранное д.м.г уходит в отбор ISO-датой', () => {
    // Мост ждёт ISO; уйди туда набранный текст, отбор по периоду молча
    // перестал бы работать.
    expect(asIso('14.08.2026')).toBe('2026-08-14');
  });

  it('ISO-дата показывается в поле как д.м.г', () => {
    expect(showDate('2026-08-14')).toBe('14.08.2026');
  });

  it('негодная дата отбивается', () => {
    // Красная рамка вместо тихой отправки мусора на мост: часы иначе
    // перекатывают 32 августа на сентябрь, и отбор идёт не по тем суткам.
    expect(validDate('32.08.2026')).toBe(false);
    expect(validDate('31.02.2026')).toBe(false);
  });

  it('недобранная дата ещё не негодна', () => {
    // Пока набирают, поле не должно краснеть на каждом знаке.
    expect(validDate('14.08.')).toBe(null);
    expect(validDate('')).toBe(null);
  });

  it('целая и существующая дата годна', () => {
    expect(validDate('14.08.2026')).toBe(true);
  });
});

describe('дата по числам', () => {
  it('выбранный в календаре день уезжает с ведущими нулями', () => {
    // Мост разбирает ISO по знакам: уедь туда `2026-8-4`, и граница периода
    // не прочиталась бы вовсе.
    expect(isoDay(2026, 8, 4)).toBe('2026-08-04');
  });

  it('ISO-дата разбирается на числа', () => {
    // Календарь открывается на том месяце, что уже выбран: разберись дата в
    // строки, месяц выбирался бы сравнением «08» с восьмёркой.
    expect(dayOf('2026-08-04')).toEqual({ year: 2026, month: 8, day: 4 });
  });
});

describe('метка времени', () => {
  it('день и часы одной строкой', () => {
    // Ею подписан исходный текст объявления: по ней его и находят в канале,
    // а давность словом («3 д») для поиска не годится.
    expect(showStamp('2026-08-14T09:05:00')).toBe('2026-08-14 09:05');
  });

  it('без времени метки нет вовсе', () => {
    // Полночь 1970 года человек прочтёт как сбой часов.
    expect(showStamp(null)).toBe('');
  });
});
