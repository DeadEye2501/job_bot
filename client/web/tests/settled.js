// Ожидание, пока осядут ответы моста и отрисовка.
//
// Живые проверки монтируют компонент и тут же смотрят на разметку, а между
// монтированием и ней стоят и обещания моста, и очередь Svelte. Ждать их
// раздельно нечем: сколько будет обещаний, знает сам компонент.

import { tick } from 'svelte';

// Сколько оборотов ждать. Обещание моста и отрисовка сменяют друг друга, и
// каждая пара стоит оборота. Число взято по самой длинной цепочке из тех, что
// поднимают проверки, — у вкладки опыта их восемь: ожидание общее, и держать
// его надо по длиннейшей. Лишние обороты не стоят ничего.
const TURNS = 8;

/** Дождаться, пока осядут ответы моста и отрисовка. */
export async function settled() {
  for (let i = 0; i < TURNS; i += 1) {
    await tick();
    await new Promise((done) => setTimeout(done, 0));
  }
}
