// Следствия страниц списка: догрузка и перечитывание.

import { describe, expect, it } from 'vitest';

import { appended, detailScrolled, nearBottom, nearTop, refreshLimit } from '../state/paging.js';

describe('дочитывание открытой карточки по прокрутке панели', () => {
  const AT_BOTTOM = { currentTarget: { scrollTop: 1000, clientHeight: 100, scrollHeight: 1100 } };
  const AT_TOP = { currentTarget: { scrollTop: 0, clientHeight: 100, scrollHeight: 5000 } };

  it('у низа панели карточка дочитывает следующую страницу', () => {
    let asked = 0;
    detailScrolled(AT_BOTTOM, { more: () => asked++ });
    expect(asked).toBe(1);
  });

  it('вдали от низа не дочитывает', () => {
    let asked = 0;
    detailScrolled(AT_TOP, { more: () => asked++ });
    expect(asked).toBe(0);
  });

  it('без открытой карточки дочитывать нечего', () => {
    expect(() => detailScrolled(AT_BOTTOM, null)).not.toThrow();
  });
});

describe('догрузка по прокрутке', () => {
  it('следующая страница просится, не доехав до самого низа', () => {
    // Доехавший до низа человек уже упёрся в пустоту и ждёт: страницу надо
    // просить заранее, чтобы список догрузился под ним на ходу.
    expect(nearBottom({ scrollTop: 700, clientHeight: 300, scrollHeight: 1100 })).toBe(true);
  });

  it('в середине списка страницу не просят', () => {
    // Иначе первая же прокрутка на пару строк вытянула бы весь перечень.
    expect(nearBottom({ scrollTop: 100, clientHeight: 300, scrollHeight: 1100 })).toBe(false);
  });

  it('лента писем просит старое, не доехав до самого верха', () => {
    // Переписку листают вверх, к началу разговора: доехавший до края упёрся бы
    // в пустоту вместо продолжения.
    expect(nearTop({ scrollTop: 40 })).toBe(true);
  });

  it('в середине ленты старого не просят', () => {
    expect(nearTop({ scrollTop: 900 })).toBe(false);
  });
});

describe('догрузка следующей страницы', () => {
  it('строка, приехавшая дважды, не удваивается', () => {
    // Пока листали, бот завёл компанию, и перечень сдвинулся: строка с края
    // первой страницы приезжает второй раз и встала бы в списке дважды.
    const shown = [{ id: 1 }, { id: 2 }];
    expect(appended(shown, [{ id: 2 }, { id: 3 }]).map((one) => one.id)).toEqual([1, 2, 3]);
  });
});

describe('перечитывание списка после правки', () => {
  it('перечитывают не меньше, чем уже показано', () => {
    // Иначе догруженные страницы схлопнулись бы до первой: человек правит имя
    // на четвёртой сотне и остаётся с началом списка.
    expect(refreshLimit(120)).toBe(120);
  });

  it('пустой список перечитывают страницей', () => {
    expect(refreshLimit(0)).toBe(50);
  });

  it('список со своей страницей не вырастает от перечитывания', () => {
    // У вакансий страница вдвое с половиной короче общей. Перечитай их общим
    // числом — и после первой же смены статуса список молча вырастает втрое.
    expect(refreshLimit(20, 20)).toBe(20);
  });

  it('длинный список перечитывают не целиком', () => {
    // Пролистанные тысячи строк одним запросом — это ожидание на пустом
    // месте: перечитывание идёт после каждой правки поля.
    expect(refreshLimit(5000)).toBe(200);
  });
});
