// Следствия нижней полосы: что она говорит человеку о состоянии приложения.
//
// Предмет — счёт и слова, а не пиксели: разметка проверяется глазами, а вот
// «все ли системы живы» и «что написать в подписи прогресса» ломаются молча.

import { describe, expect, it } from 'vitest';

import { allAlive, blockedTip, downNames, shouldTurnOff } from '../state/health.js';
import { modeChosen, modeHintAt } from '../state/modes.js';
import { bar, caption, countlessNote, humanText } from '../state/progress.js';

describe('здоровье систем', () => {
  it('живо всё — значит живо каждое из четырёх', () => {
    // Кнопки запуска отпираются только по этому ответу. Согласись он на трёх
    // из четырёх, бот стартовал бы без модели и упал бы на первой вакансии.
    expect(allAlive({ db: true, tg: true, chat: true, embed: true })).toBe(true);
    expect(allAlive({ db: true, tg: true, chat: true, embed: false })).toBe(false);
  });

  it('неспрошенное живым не считается', () => {
    // До первого ответа моста мы не знаем ничего. Прими мы незнание за
    // «живо», кнопки отперлись бы на миг раньше правды — и человек нажал бы.
    expect(allAlive({})).toBe(false);
    expect(allAlive(null)).toBe(false);
  });

  it('упавшие называются человеческими именами и по порядку', () => {
    // Их читают в подсказке на запертой кнопке. Порядок постоянный, чтобы
    // подсказка не перетасовывалась при каждом опросе.
    expect(downNames({ db: true, tg: false, chat: false, embed: true }))
      .toEqual(['TG', 'CHT']);
  });

  it('до первого ответа подсказка говорит про ожидание, а не про поломку', () => {
    // Пустой ответ и упавшая система — разные вещи: первое проходит за секунду
    // после запуска, и пугать человека списком «недоступно всё» незачем.
    expect(blockedTip(null)).toBe('Проверка состояния систем…');
  });

  it('подсказка перечисляет ровно то, что недоступно', () => {
    // По ней человек понимает, что чинить. Соври она — он чинил бы Telegram,
    // глядя на погасшую базу.
    expect(blockedTip({ db: false, tg: true, chat: true, embed: true }))
      .toContain('DB');
  });

  it('система отвалилась — работающего бота гасят', () => {
    // Бот против мёртвой системы крутит обороты впустую и копит отказы, а
    // тумблер в этот миг уже заперт и человек его не выключит.
    expect(shouldTurnOff({ db: true, tg: false, chat: true, embed: true }, 'Full')).toBe(true);
  });

  it('уже выключенного гасить нечем', () => {
    // Часы здоровья бьют каждые пять секунд. Гаси мы выключенного, каждый удар
    // слал бы мосту set_mode заново — а на сломанном мосту это ещё и плашка
    // отказа раз в пять секунд поверх той, по которой человек ищет причину.
    expect(shouldTurnOff({ db: false, tg: false, chat: false, embed: false }, 'Off')).toBe(false);
  });

  it('живо всё — режим не трогают', () => {
    // Иначе окно выключало бы бота само себе на ровном месте.
    expect(shouldTurnOff({ db: true, tg: true, chat: true, embed: true }, 'Full')).toBe(false);
  });
});

/** Нажатие мышью: место на дорожке шириной 300 точек. */
function byMouse(offsetX, current = 'Off') {
  return modeChosen({ detail: 1, offsetX, width: 300 }, current);
}

/** Нажатие с клавиатуры: места у него нет вовсе, `detail` нулевой. */
function byKey(current) {
  return modeChosen({ detail: 0, offsetX: 0, width: 300 }, current);
}

describe('переключатель режима', () => {
  it('нажатие попадает в ту треть, куда метил человек', () => {
    // Положения три, и человек метит в то, которое видит. Съедь границы — он
    // начнёт промахиваться мимо режима, на который смотрит.
    expect(byMouse(10)).toBe('Off');
    expect(byMouse(150)).toBe('DM Only');
    expect(byMouse(290)).toBe('Full');
  });

  it('границы третей принадлежат правой стороне', () => {
    // Ровно на границе выбор обязан быть определённым: иначе одно и то же
    // нажатие давало бы разный режим от округления ширины дорожки.
    expect(byMouse(100)).toBe('DM Only');
    expect(byMouse(200)).toBe('Full');
  });

  it('нажатие мимо дорожки не выбирает ничего', () => {
    // «Ближний край» врал бы: промах поднимал бы выключенного бота, а
    // отправленного письма не вернуть.
    expect(byMouse(-20)).toBe('');
    expect(byMouse(9999)).toBe('');
  });

  it('подсказка называет режим той трети, над которой курсор', () => {
    // Слова у переключателя нет: что включит нажатие, человек узнаёт наведением.
    expect(modeHintAt(10, 300)).toBe('Выключить автоматику');
    expect(modeHintAt(150, 300)).toBe('Только приём сообщений от HR');
    expect(modeHintAt(290, 300)).toBe('Вся автоматика: поиск, отклики, переписка');
    expect(modeHintAt(-20, 300)).toBe('');
  });

  it('перебор по кругу возвращается к началу', () => {
    // Им ходят с клавиатуры: у нажатия по Enter места нет вовсе, и выбирать по
    // месту там нечего. Без перебора с клавиатуры был бы доступен один «Off».
    expect(byKey('Off')).toBe('DM Only');
    expect(byKey('DM Only')).toBe('Full');
    expect(byKey('Full')).toBe('Off');
  });
});

describe('полоса прогресса', () => {
  it('подпись называет обе половины обхода', () => {
    // Каналы и сообщения идут разом, и человек по подписи понимает, где
    // сейчас работа. Пропади половина — полоса двигалась бы необъяснимо.
    expect(caption({ label: 'python jobs', current: 3, total: 10 }, { current: 7, total: 20 }))
      .toBe('python jobs (3/10), Сообщение (7/20)');
  });

  it('канал без имени называется каналом', () => {
    // Имя приходит не всегда — источник мог его не прислать. Пустое место в
    // подписи читалось бы как поломка.
    expect(caption({ label: '', current: 1, total: 2 }, { current: 0, total: 0 }))
      .toBe('Каналы (1/2), Сообщение (—)');
  });

  it('названный канал называется и до того, как узнан его итог', () => {
    // Имя приходит раньше счёта: канал уже взят в работу, и человек по подписи
    // видит, какой именно. Спрячь его до итога — начало обхода выглядело бы
    // так же, как «делать нечего».
    expect(caption({ label: 'канал', current: 0, total: 0 }, { current: 0, total: 0 }))
      .toBe('канал (0/0), Сообщение (—)');
  });

  it('пока не назван ни канал, ни итог, подпись молчит', () => {
    // «0/0» читается как «нечего делать», а не как «считаем», и человек решил
    // бы, что обход завис.
    expect(caption({ label: '', current: 0, total: 0 }, { current: 0, total: 0 }))
      .toBe('…, Сообщение (—)');
  });

  it('прогон одной вакансии без имени стадии называется прогоном', () => {
    // Полосам показать нечего — счёта у прогона нет, — и пустая подпись рядом с
    // бегущими полосами не говорит человеку даже того, что бот занят.
    expect(countlessNote('')).toBe('Прогон вакансии…');
  });

  it('названная стадия прогона говорит за себя', () => {
    expect(countlessNote('Разбор поста')).toBe('Разбор поста');
  });

  it('заполнение не переваливает за край', () => {
    // Счётчик обгоняет итог, когда источник дослал сообщений по ходу. Полоса
    // при этом вылезла бы за свою дорожку.
    expect(bar(15, 10).percent).toBe(100);
    expect(bar(3, 10).percent).toBe(30);
  });

  it('без итога заполнения нет вовсе', () => {
    // Делить на ноль нечем, а показанная наполовину полоса при неизвестном
    // итоге — прямая ложь о том, сколько осталось.
    expect(bar(5, 0).percent).toBe(0);
  });

  it('без итога шкала объявляется неизвестной', () => {
    // По этому признаку полоса перестаёт показывать долю и начинает бежать.
    // Соври он — «идёт, сколько именно неизвестно» стало бы неотличимо от
    // «сделано ноль», и человек решил бы, что обход стоит.
    expect(bar(0, 0).unknown).toBe(true);
    expect(bar(3, 10).unknown).toBe(false);
  });
});

describe('плашка ожидания человека', () => {
  it('называет, что требуется: пройти капчу или войти на сайт', () => {
    expect(humanText({ kind: 'captcha', host: 'site.test' })).toBe('Требуется пройти капчу');
    expect(humanText({ kind: 'login', host: 'site.test' })).toBe('Требуется войти на site.test');
  });
});
