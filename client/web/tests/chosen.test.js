// Следствия набора, который человек собирает нажатиями: что из него уходит,
// когда уходит сам предмет.

import { describe, expect, it } from 'vitest';

import { alone, without } from '../state/chosen.js';

describe('снятое из набора', () => {
  it('снесённый предмет из набора уходит', () => {
    // Иначе отметка переживает саму запись и достаётся следующей с тем же
    // именем: заведённая заново категория открывалась бы свёрнутой.
    expect([...without(new Set(['языки', 'базы']), 'языки')]).toEqual(['базы']);
  });

  it('снятие того, чего в наборе нет, набор не меняет', () => {
    expect([...without(new Set(['языки']), 'базы')]).toEqual(['языки']);
  });

  it('прежний набор остаётся прежним', () => {
    // Руны замечают присваивание, а не правку внутри: правь мы набор на месте,
    // экран не перерисовался бы вовсе.
    const was = new Set(['языки']);

    without(was, 'языки');

    expect([...was]).toEqual(['языки']);
  });
});

describe('одно выбранное из ряда', () => {
  it('нажатое повторно снимается', () => {
    // Грейд в объявлении называют не всегда, и поставленный по ошибке нечем
    // было бы убрать: соседнее значение соврало бы про вакансию не меньше.
    expect(alone('senior', 'senior')).toBe('');
  });

  it('нажатое поверх другого замещает его', () => {
    expect(alone('senior', 'lead')).toBe('lead');
  });
});
