// Договор пункта «в отсев» с теми, кто его ставит.
//
// Пункт стоял тремя дословными копиями — в карточках канала, компании и
// человека, — и различались они только именем зова. Теперь он один, а между
// ним и карточками встало ещё и общее меню: карточка отдаёт зовы меню, меню —
// пункту.
//
// Сторожатся обе половины цепочки: что копий пункта больше нет и что на каждом
// её звене зовы передаются, а не додумываются.

import { describe, expect, it } from 'vitest';

import { markup, placed } from './markup.js';

const SAYS_IT = /Добавить в blacklist|Убрать из blacklist/;

/** Кому эти слова положены: сам пункт, окошко ручного занесения и кнопка на
 *  вкладке отсева. Всем прочим — нет: там это была бы четвёртая копия. */
const ALLOWED_TO_SAY_IT = new Set([
  'components/BlacklistMenuItem.svelte',
  'components/AddBlacklistDialog.svelte',
  'app/BlacklistList.svelte',
]);

/** Постановки самого пункта. */
function usages() {
  return placed('<BlacklistMenuItem');
}

/** Постановки меню карточки: пункт стоит внутри него, и зовы идут через него
 *  насквозь. */
function menus() {
  return placed('<CardActions');
}

describe('пункт «в отсев»', () => {
  it('где-то поставлен — иначе сторожить нечего', () => {
    // Числом мест не меряем: пункт нарочно уходит вглубь, за общее меню, и
    // верный следующий вынос уменьшил бы это число, а не увеличил.
    expect(usages().length).toBeGreaterThan(0);
  });

  it('нигде не нарисован заново', () => {
    // Слова ищутся где угодно в строке, а не в одиночку на своей: в разметке
    // они всегда стоят рядом с тегом, и якорь на всю строку не совпадал ни с
    // одним местом — сторож молчал бы и на четвёртой копии пункта.
    //
    // Трое, кому эти слова положены, названы поимённо: сам пункт, заголовок
    // окошка ручного занесения и кнопка на самой вкладке отсева. Список
    // сверяется целиком, а не «эти пропускаем»: пропади слова у любого из
    // троих — сторож тоже покраснеет, и это верно, кнопка исчезла бы.
    const said = markup()
      .filter(({ text }) => SAYS_IT.test(text))
      .map(({ file }) => file);

    expect(new Set(said)).toEqual(ALLOWED_TO_SAY_IT);
  });

  it('получает положение дел доводом', () => {
    // Иначе пункт полез бы за ним в карточку, а знание во фронте
    // одностороннее: вниз доводами, наверх никак.
    for (const use of usages()) {
      expect(use.tag, use.file).toMatch(/\s(blocked=\{|\{blocked\})/);
    }
  });

  it('получает оба зова и закрывающий зов меню', () => {
    // Оба, а не подходящий: выбор между ними и есть то, что вынесено. Отдай
    // карточка один, выбор вернулся бы в неё — в каждую свой копией.
    // Закрывающий зов затем, что оставшееся открытым окошко перекрывает ту
    // самую строку, которую пункт и поменял.
    for (const use of usages()) {
      expect(use.tag, use.file).toMatch(/\s(onblock=\{|\{onblock\})/);
      expect(use.tag, use.file).toMatch(/\s(onunblock=\{|\{onunblock\})/);
      expect(use.tag, use.file).toMatch(/\s(close=\{|\{close\})/);
    }
  });

  it('меню карточки тоже отдаёт пункту оба зова, а не догадку', () => {
    // Меню встало между карточкой и пунктом, и цепочка длиннее на звено:
    // пропади зов у карточки, пункт молча получил бы пустоту, а человек —
    // нажатие, которое ничего не делает.
    for (const use of menus()) {
      expect(use.tag, use.file).toMatch(/\s(blocked=\{|\{blocked\})/);
      expect(use.tag, use.file).toMatch(/\s(onblock=\{|\{onblock\})/);
      expect(use.tag, use.file).toMatch(/\s(onunblock=\{|\{onunblock\})/);
    }
  });

  it('каждый зов ведёт к своему делу, а не просто написан', () => {
    // Присутствие имён не говорит, куда они ведут: переставь тела местами —
    // и «Убрать из blacklist» заносило бы компанию в отсев, а прогон
    // остался бы зелёным целиком, на обоих языках сразу.
    //
    // Смотрим оба звена: карточки отдают зовы меню, меню — пункту. Возьми мы
    // только одно, второе осталось бы неприкрытым.
    // Годных записей две. Своё тело — тогда смотрим, что внутри. Сквозной
    // проброс `{onblock}` — тогда смотреть не на что и не нужно: перепутать
    // его молча нельзя, для этого пришлось бы написать `onblock={onunblock}`,
    // то есть вернуться к первой записи и попасться на ней же.
    const given = usages().concat(menus());
    expect(given.length).toBeGreaterThan(0);

    for (const use of given) {
      expect(use.tag, use.file).toMatch(/onblock=\{[^}]*\.block\(|\{onblock\}/);
      expect(use.tag, use.file).toMatch(/onunblock=\{[^}]*\.unblock\(|\{onunblock\}/);
    }
  });

  it('меню карточки стоит не в одной карточке', () => {
    expect(new Set(menus().map((use) => use.file)).size).toBeGreaterThan(1);
  });
});