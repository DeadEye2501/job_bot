// Следствия вкладки опыта: даты, период в шапке карточки и её подпись.

import { describe, expect, it } from 'vitest';

import { asIso, showDate } from '../state/dates.js';
import { cardTitle, period } from '../state/experience.js';

describe('дата места работы', () => {
  it('с моста приходит одним видом, а показывается другим', () => {
    // Мост говорит датами вида 2020-03-01, человек читает и набирает
    // 01.03.2020. Покажи ему первое — он решил бы, что поле чужое.
    expect(showDate('2020-03-01')).toBe('01.03.2020');
    expect(showDate(null)).toBe('');
  });

  it('набранное человеком уезжает обратно в вид моста', () => {
    expect(asIso('01.03.2020')).toBe('2020-03-01');
  });

  it('недобранная дата не уезжает вовсе', () => {
    // Человек набирает посимвольно, и «01.03.20» на полпути — не дата.
    // Отправь мы её, мост записал бы двадцатый год нашей эры.
    expect(asIso('01.03.20')).toBe(null);
    expect(asIso('')).toBe(null);
    expect(asIso('чепуха')).toBe(null);
  });
});

describe('период в шапке карточки', () => {
  it('месяц и год с обеих сторон', () => {
    // День в шапке не нужен: места работы человек различает по месяцам, а
    // строка становится вдвое длиннее.
    expect(period('2020-03-01', '2022-07-31')).toBe('03.2020 — 07.2022');
  });

  it('без даты окончания — по настоящее время', () => {
    // Это главное, что читают в шапке: работает человек здесь сейчас или нет.
    expect(period('2020-03-01', null)).toBe('03.2020 — настоящее время');
  });

  it('без даты начала периода нет вовсе', () => {
    // Свежая карточка пуста, и «— настоящее время» без начала выглядело бы
    // обрывком.
    expect(period(null, null)).toBe('');
  });
});

describe('подпись свёрнутой карточки', () => {
  it('называет компанию, должность и период', () => {
    // Карточки свёрнуты, и это всё, по чему человек их различает.
    expect(cardTitle({ company: 'Контур', role: 'Разработчик', start_date: '2020-03-01', end_date: null }))
      .toEqual({ company: 'Контур', role: 'Разработчик', period: '03.2020 — настоящее время' });
  });

  it('безымянная компания названа так прямо', () => {
    // Свежую карточку иначе не отличить от пустого места в списке.
    expect(cardTitle({ company: '', role: '', start_date: null, end_date: null }))
      .toEqual({ company: 'Без названия', role: '', period: '' });
  });
});
