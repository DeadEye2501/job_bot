// Следствия просеивания списка по набранному: что остаётся видно человеку,
// пока он печатает.

import { describe, expect, it } from 'vitest';

import { matching } from '../state/search.js';

describe('просеивание по набранному', () => {
  it('пустой набор оставляет список целым', () => {
    // Подсказчик открывается до первого знака, и пустой он читался бы как
    // «предлагать нечего».
    expect(matching(['Python', 'Go'], '')).toEqual(['Python', 'Go']);
  });

  it('одни пробелы списка не режут', () => {
    // Пробел набирают между словами и стирают последним; список, схлопнувшийся
    // на нём в пустоту, мигал бы под руками.
    expect(matching(['Python', 'Go'], '   ')).toEqual(['Python', 'Go']);
  });

  it('регистр не различается', () => {
    // Человек набирает как придётся, а значения приходят как записаны.
    expect(matching(['Python'], 'PYT')).toEqual(['Python']);
    expect(matching(['PYTHON'], 'pyt')).toEqual(['PYTHON']);
  });

  it('ищется вхождение, а не начало', () => {
    // У локальных поставщиков имя идёт с приставкой через косую черту, и
    // отбор по началу прятал бы модель от того, кто набрал её собственное имя.
    expect(matching(['qwen/qwen3-4b'], 'qwen3')).toEqual(['qwen/qwen3-4b']);
  });

  it('не найденное уходит', () => {
    expect(matching(['Python', 'Go'], 'rust')).toEqual([]);
  });

  it('смотрит туда, куда указано правилом', () => {
    // Строку ищут и по значению, и по причине: причину пишут словами, и по ней
    // вспоминают, за что строка заведена.
    const rows = [
      { value: 'senior', reason: 'слишком высоко' },
      { value: 'junior', reason: 'мимо стека' },
    ];

    const found = matching(rows, 'стека', (one) => `${one.value} ${one.reason}`);

    expect(found.map((one) => one.value)).toEqual(['junior']);
  });
});
