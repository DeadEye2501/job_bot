// Общее у источников — каналов и агрегаторов: числа воронки и общий выключатель.

import { describe, expect, it } from 'vitest';

import { masterToggle, sourceStats } from '../state/sources.js';

describe('статистика источника', () => {
  const STATS = {
    total: 12,
    vacancies_per_day: 1.5,
    fit_percent: 40,
    apply_percent: 25,
    response_percent: null,
  };

  it('источник без собранного показывает пустую статистику', () => {
    // Нули в столбиках читаются как «собрали и ничего не нашли», а пустое
    // состояние говорит «ещё не обходили».
    expect(sourceStats({ ...STATS, total: 0 }).empty).toBe(true);
  });

  it('источник с собранным показывает воронку', () => {
    expect(sourceStats(STATS).empty).toBe(false);
  });

  it('известная доля названа процентом', () => {
    expect(sourceStats(STATS).fit).toBe('40%');
  });

  it('неизвестная доля названа прочерком', () => {
    // Ноль процентов и «не из чего считать» — разные вещи: у источника без
    // откликов доля ответов не ноль, её просто нет.
    expect(sourceStats(STATS).response).toBe('—');
  });
});

describe('общий выключатель над списком источников', () => {
  // Он не сводка строк, а свой выключатель поверх них: строки он не трогает, и
  // выключенный общий не стирает, какие источники были включены.
  it('включённый показан включённым, подпись называет выключение обхода', () => {
    expect(masterToggle(true, 'каналов')).toEqual({
      checked: true,
      title: 'Выключить обход всех каналов',
    });
  });

  it('выключенный показан выключенным, подпись называет включение обхода', () => {
    expect(masterToggle(false, 'агрегаторов')).toEqual({
      checked: false,
      title: 'Включить обход агрегаторов',
    });
  });
});
