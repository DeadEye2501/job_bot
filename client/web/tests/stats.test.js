// Следствия экрана статистики: как читаются числа, сроки и доли.

import { describe, expect, it } from 'vitest';

import {
  PERIODS, convNote, deltaNote, donut, duration, kpiRow, skillRows, sliceTarget,
  statusColumns, weekBars,
} from '../state/stats.js';

describe('срок ответа', () => {
  it('секунды, минуты, часы и дни — каждый своей мерой', () => {
    // Ответы приходят и через минуту, и через неделю. Одна мера на всё
    // означала бы «10080 минут» там, где человек ждёт «7 д».
    expect(duration(45)).toBe('45 с');
    expect(duration(600)).toBe('10 мин');
    expect(duration(7200)).toBe('2 ч');
    expect(duration(172800)).toBe('2 д');
  });

  it('крупная мера договаривает остаток, если он есть', () => {
    // «2 ч» вместо «2 ч 30 мин» занижает вдвое то, чего человек ждал.
    expect(duration(9000)).toBe('2 ч 30 мин');
    expect(duration(180000)).toBe('2 д 2 ч');
  });

  it('ровное значение остатка не поминает', () => {
    expect(duration(7200)).toBe('2 ч');
  });

  it('неизвестный срок отмечен прочерком', () => {
    // Ноль здесь читался бы как «отвечают мгновенно» — прямая ложь про
    // выборку, в которой не ответил никто.
    expect(duration(null)).toBe('—');
  });
});

describe('прирост за срок', () => {
  it('рост назван знаком и подписан сроком', () => {
    // Число без подписи не читается: «+3» за квартал и за сегодня — разные
    // новости.
    expect(deltaNote(3, 'week')).toEqual({ text: '+3 за неделю', tone: 'up' });
  });

  it('убыль показана минусом', () => {
    expect(deltaNote(-2, 'today')).toEqual({ text: '−2 за сегодня', tone: '' });
  });

  it('без изменений — знак равенства, а не пустота', () => {
    // Пустое место читалось бы как «не посчитали».
    expect(deltaNote(0, 'month')).toEqual({ text: '±0 за месяц', tone: '' });
  });

  it('за всё время прироста не бывает', () => {
    // Не с чем сравнивать: это и есть всё время.
    expect(deltaNote(5, 'all')).toBe(null);
    expect(deltaNote(null, 'week')).toBe(null);
  });

  it('сроки перечислены от короткого к длинному', () => {
    // Ими переключают экран, и порядок должен совпадать с тем, как человек их
    // мысленно расставляет.
    expect(PERIODS.map((one) => one.key)).toEqual(['today', 'week', 'month', 'quarter', 'all']);
  });
});

describe('показатели верхнего ряда', () => {
  const answer = {
    total: 40,
    total_period: 5,
    applied_total: 12,
    applied_period: 2,
    in_progress_total: 3,
    offer_total: 1,
    decline_total: 7,
  };

  it('число берётся тем именем, каким его прислал мост', () => {
    // У первого показателя имя без приставки, у остальных с ней. Припиши ей
    // общее правило — счётчик вакансий показывал бы ноль при живой дельте
    // рядом, и человек читал бы «ноль вакансий, но +5 за неделю».
    expect(kpiRow(answer, 'week').map((one) => one.total)).toEqual([40, 12, 3, 1, 7]);
  });

  it('прирост читается своим полем и переводится в слова', () => {
    const shown = kpiRow(answer, 'week');
    expect(shown[0].delta.text).toBe(deltaNote(5, 'week').text);
    expect(shown[1].delta.text).toBe(deltaNote(2, 'week').text);
  });

  it('несчитанное число показывается нулём, а не пустотой', () => {
    // Мост не присылает поля, которого не считал; пустое место в ряду
    // читается как недогрузившийся экран.
    expect(kpiRow({}, 'week').map((one) => one.total)).toEqual([0, 0, 0, 0, 0]);
  });
});

describe('ответы по дням недели', () => {
  it('высота столбца считается от самого высокого дня', () => {
    // Столбцы читают друг относительно друга: посчитай мы долю от суммы,
    // разница между понедельником и пятницей стала бы неразличима.
    const bars = weekBars([1, 2, 4, 0, 0, 0, 0]);

    expect(bars.map((one) => one.percent)).toEqual([25, 50, 100, 0, 0, 0, 0]);
  });

  it('неделя начинается с понедельника', () => {
    expect(weekBars([1, 0, 0, 0, 0, 0, 0])[0].label).toBe('Пн');
    expect(weekBars([0, 0, 0, 0, 0, 0, 1]).at(-1).label).toBe('Вс');
  });

  it('пустая неделя рисуется без столбцов, а не делением на ноль', () => {
    expect(weekBars([0, 0, 0, 0, 0, 0, 0]).every((one) => one.percent === 0)).toBe(true);
  });

  it('суббота и воскресенье помечены выходными', () => {
    // По этому графику решают, когда людям писать: серые выходные говорят, что
    // низкий столбец там — не тишина, а нерабочий день.
    expect(weekBars([1, 1, 1, 1, 1, 1, 1]).map((one) => one.weekend))
      .toEqual([false, false, false, false, false, true, true]);
  });

  it('без единого отклика над столбцами стоят прочерки, а не нули', () => {
    // Ноль читается как «писали, но не ответили»; прочерк говорит правду —
    // писать было не с чего.
    expect(weekBars([0, 0, 0, 0, 0, 0, 0], 0).map((one) => one.note)).toEqual(Array(7).fill('—'));
    expect(weekBars([2, 0, 0, 0, 0, 0, 0], 9).map((one) => one.note)[1]).toBe(0);
  });
});

describe('счётчики статусов', () => {
  it('показаны все одиннадцать статусов, включая нулевые', () => {
    // Ноль у «Офферов» — это новость. Пропусти мы строку, человек прочёл бы
    // список как «оффер ещё не заводили», а не «ни одного не случилось».
    const [moving, over] = statusColumns({ New: 3 });

    expect([...moving, ...over]).toHaveLength(11);
    expect(over.find((one) => one.name === 'Offer').count).toBe(0);
  });

  it('слева те, что ещё двигаются, справа — исходы', () => {
    // Читают их как воронку: пока слева, вакансия жива, справа — всё, отыграла.
    const [moving, over] = statusColumns({});

    expect(moving.map((one) => one.name))
      .toEqual(['New', 'Applied', 'Answered', 'Test', 'Invitation', 'In Progress']);
    expect(over.map((one) => one.name))
      .toEqual(['Offer', 'Decline', 'Ghosting', 'Scam', 'Not Fit']);
  });
});

describe('навыки в вакансиях', () => {
  it('полоса частоты считается от самого частого навыка', () => {
    // Полосы читают друг относительно друга: доля от суммы сделала бы разницу
    // между вторым и третьим навыком неразличимой.
    const rows = skillRows([{ label: 'python', count: 8 }, { label: 'go', count: 2 }]);

    expect(rows.map((one) => one.percent)).toEqual([100, 25]);
  });

  it('первый в колонке идёт без верхней черты', () => {
    // Черта разделяет строки внутри колонки; над первой она читалась бы как
    // граница карточки.
    const rows = skillRows(Array.from({ length: 6 }, (_, at) => ({ label: `s${at}`, count: 1 })));

    expect(rows.map((one) => one.first)).toEqual([true, false, true, false, true, false]);
  });
});

describe('конверсия канала', () => {
  it('несчитанная конверсия названа словом, а не нулём', () => {
    // «0 %» значит «отклики были, ответов нет»; не отправляли вовсе — другая
    // новость, и путать их нельзя.
    expect(convNote(null)).toEqual({ text: 'n/a', percent: 0 });
  });

  it('доля округлена до целых процентов', () => {
    // Дробь в узкой колонке разъезжается, а решают по ней на глаз.
    expect(convNote(39.6)).toEqual({ text: '40%', percent: 39.6 });
  });
});

describe('кольцо статусов', () => {
  it('доли складываются в полный круг', () => {
    // Кольцо читают на глаз: недобранный круг выглядит как потерянные строки.
    const parts = donut({ New: 3, Offer: 1 });

    expect(parts.map((one) => one.percent)).toEqual([75, 25]);
  });

  it('сегменты идут по воронке, а не по тому, как их прислали', () => {
    // Кольцо читают по часовой: «новая → отклик → ответ → …». Придёт ответ
    // моста в другом порядке — и воронка перестанет быть воронкой.
    const parts = donut({ Offer: 1, New: 1, Applied: 1 });

    expect(parts.map((one) => one.name)).toEqual(['New', 'Applied', 'Offer']);
  });

  it('пустая выборка колец не рисует', () => {
    // Нулевой круг рисуется точкой в углу — хуже, чем ничего.
    expect(donut({})).toEqual([]);
    expect(donut({ New: 0 })).toEqual([]);
  });

  it('нулевые статусы в кольцо не попадают', () => {
    // Иначе кольцо копит невидимые сегменты, и подписи под ним расходятся с
    // тем, что видно.
    expect(donut({ New: 2, Offer: 0 }).map((one) => one.name)).toEqual(['New']);
  });
});

describe('переход из статистики в вакансии', () => {
  it('нажатие на строку статуса ведёт в вакансии с этим статусом', () => {
    // Статусы иначе только считают: чтобы посмотреть, что за девять штук, надо
    // идти в вакансии и набирать отбор руками.
    expect([...sliceTarget('In Progress').statuses]).toEqual(['In Progress']);
  });

  it('прежний отбор при переходе снимается целиком', () => {
    // Человек просит «покажи вакансии этого статуса», а не «сузь этим статусом
    // то, что я отбирал час назад»: уцелевший грейд отдал бы ему пустой список.
    const target = sliceTarget('Offer');

    expect([...target.channels]).toEqual([]);
    expect(target.grade).toBe('');
    expect(target.datePreset).toBe('');
    expect(target.scoreMin).toBe('');
  });
});
