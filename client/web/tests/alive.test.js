// Следствия признака жизни экрана: когда пришедший ответ ещё можно класть.

import { describe, expect, it } from 'vitest';

import { living } from '../state/alive.js';

describe('признак жизни экрана', () => {
  it('до ухода экран считается живым', () => {
    // Ответы приходят и до того, как эффект успел завестись: до первого зова
    // моста класть их некуда, но и объявлять экран мёртвым нельзя.
    expect(living().now).toBe(true);
  });

  it('уход с экрана снимает признак', () => {
    // Ответ, доехавший после ухода, писать некуда: разметки нет, а положенное
    // в снесённое состояние всплывёт при следующем заходе поверх свежего.
    const alive = living();
    const settled = alive.mounted();

    settled();

    expect(alive.now).toBe(false);
  });

  it('возвращение на экран признак взводит', () => {
    // Экран открывают, уходят и возвращаются, а объявление живёт столько же,
    // сколько сам компонент: не взведи его заново, вернувшийся экран не
    // положил бы ни одного ответа.
    const alive = living();
    alive.mounted()();

    alive.mounted();

    expect(alive.now).toBe(true);
  });

  it('свой признак у каждого экрана', () => {
    // Общий гасил бы ответы соседа: экраны уходят и возвращаются порознь.
    const here = living();
    const there = living();

    there.mounted()();

    expect(here.now).toBe(true);
  });
});

describe('заход на экран', () => {
  it('зашедший экран читает себя', () => {
    // Без этого чтения экран открывался бы пустым и ждал первой вести моста,
    // которой может не быть вовсе.
    const alive = living();
    let read = 0;

    alive.entered(() => (read += 1));

    expect(read).toBe(1);
  });

  it('на заходе признак взводится', () => {
    // Возвращаются на тот же экран: не взведи признак заново, вернувшийся не
    // положил бы ни одного ответа.
    const alive = living();
    alive.mounted()();

    alive.entered(() => {});

    expect(alive.now).toBe(true);
  });

  it('уход с экрана снимается тем, что заход отдал', () => {
    // Отдаётся снятие затем, что зовут это из эффекта: он и вернёт его экрану.
    const alive = living();

    alive.entered(() => {})();

    expect(alive.now).toBe(false);
  });
});
