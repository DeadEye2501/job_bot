// Следствия экрана журнала: что человек читает в строке и что видит в отборе.
//
// Предмет — время, тон уровня, отбор по пилюлям и слова пустого экрана.
// Разметка проверяется глазами, а вот эти четверо ломаются молча.

import { describe, expect, it } from 'vitest';

import { toggled } from '../state/chosen.js';
import { askDelay, emptyText, levelTone, logTime, mayHide, shown } from '../state/logs.js';

describe('строка журнала', () => {
  it('время показано до миллисекунд', () => {
    // По журналу ищут порядок событий внутри одной секунды: сборщик пишет
    // сотнями за обход, и без долей строки выглядели бы одновременными.
    const at = new Date(2026, 7, 14, 9, 5, 3, 40).getTime() / 1000;

    expect(logTime(at)).toBe('09:05:03.040');
  });

  it('записи без времени не врут временем', () => {
    // Пустое место честнее, чем полночь 1970 года, за которую человек принял
    // бы сбой часов.
    expect(logTime(null)).toBe('');
    expect(logTime(undefined)).toBe('');
  });

  it('CRITICAL показан как ошибка', () => {
    // Окно рисует их одним цветом, и отдельный тон заставлял бы искать
    // разницу, которой человеку не показывают.
    expect(levelTone('CRITICAL')).toBe('error');
    expect(levelTone('ERROR')).toBe('error');
  });

  it('у каждого уровня свой тон, а у незнакомого — отладочный', () => {
    // Незнакомый уровень приходит от чужой библиотеки. Без запасного тона
    // строка осталась бы вовсе без цвета и читалась бы как пропуск.
    expect(levelTone('WARNING')).toBe('warn');
    expect(levelTone('INFO')).toBe('info');
    expect(levelTone('TRACE')).toBe('debug');
  });
});

describe('отбор по уровням', () => {
  const records = [
    { id: 1, level: 'INFO' },
    { id: 2, level: 'ERROR' },
    { id: 3, level: 'CRITICAL' },
    { id: 4, level: 'DEBUG' },
  ];

  it('показывают ровно выбранное', () => {
    // По этим пилюлям человек ищет поломку. Покажи отбор лишнее — он читал бы
    // отладку вперемешку с бедой.
    expect(shown(records, new Set(['INFO'])).map((one) => one.id)).toEqual([1]);
  });

  it('пилюля ошибки накрывает и CRITICAL', () => {
    // Иначе самая тяжёлая запись пряталась бы именно тогда, когда человек
    // отобрал одни ошибки.
    expect(shown(records, new Set(['ERROR'])).map((one) => one.id)).toEqual([2, 3]);
  });

  it('без выбранных уровней не показывают ничего', () => {
    // Погасив все пилюли, человек просит пустой список, а не полный: обратное
    // читалось бы как «отбор сломался».
    expect(shown(records, new Set())).toEqual([]);
  });

  it('нажатие на пилюлю переключает её, не трогая соседей', () => {
    // Отбор собирают из нескольких уровней разом: сбрасывай нажатие соседей,
    // человек не смог бы смотреть ошибки вместе с предупреждениями.
    const after = toggled(new Set(['ERROR', 'INFO']), 'INFO');

    expect([...after]).toEqual(['ERROR']);
    expect([...toggled(after, 'DEBUG')]).toEqual(['ERROR', 'DEBUG']);
  });

  it('переключение отдаёт новый набор, а не правит прежний', () => {
    // Руны Svelte замечают присваивание, а не правку внутри набора: поправь
    // мы прежний, экран не перерисовался бы вовсе — человек жал бы на пилюлю
    // и не видел отклика.
    const before = new Set(['ERROR']);

    expect(toggled(before, 'INFO')).not.toBe(before);
    expect([...before]).toEqual(['ERROR']);
  });

  it('последнюю зажатую пилюлю не гасят', () => {
    // Погашены все — список пуст без всякой видимой причины, и человек читает
    // это как поломку журнала, а не как свой же отбор.
    expect(mayHide(new Set(['ERROR']), 'ERROR')).toBe(false);
    expect(mayHide(new Set(['ERROR', 'INFO']), 'ERROR')).toBe(true);
  });

  it('зажать погашенную можно всегда', () => {
    expect(mayHide(new Set(['ERROR']), 'INFO')).toBe(true);
  });
});

describe('когда перечитывать журнал после вести', () => {
  it('пачку вестей схлопывают в один вопрос', () => {
    // Сборщик пишет сотнями записей за обход, и весть приходит на каждую.
    // Спроси мост на каждую — сотня запросов на один обход.
    expect(askDelay(5000)).toBe(200);
  });

  it('чаще раза в секунду мост не спрашивают', () => {
    // Он на это отвечает отказом, а отказ у нас показывается плашкой: экран
    // журнала под нагрузкой засыпал бы человека плашками вместо записей.
    expect(askDelay(300)).toBe(800);
    expect(askDelay(0)).toBe(1100);
  });

  it('к сроку моста прибавлен запас', () => {
    // Секунду мост считает своими часами, и вопрос, посланный ровно в тысячу
    // миллисекунд, приходит к нему чуть раньше границы — с отказом вместо
    // страницы. Ждём с запасом: 500 мс здесь и есть та сотня сверх секунды.
    expect(askDelay(600)).toBe(500);
  });
});

describe('слова пустого экрана', () => {
  it('до первого ответа моста — про ожидание', () => {
    // Пустой список и неспрошенный журнал — разные вещи, и «логов пока нет»
    // на неспрошенном было бы прямой неправдой.
    expect(emptyText({ loaded: false, total: 0, showing: 0 })).toBe('Загрузка…');
  });

  it('буфер пуст — так и сказано', () => {
    expect(emptyText({ loaded: true, total: 0, showing: 0 })).toBe('Логов пока нет');
  });

  it('записи есть, но отбор их прячет — сказано иначе', () => {
    // Разные причины пустоты требуют разных действий: в первом случае ждать,
    // во втором — отпустить пилюлю. Одна фраза на оба случая заставила бы
    // человека гадать.
    expect(emptyText({ loaded: true, total: 40, showing: 0 })).toBe('Ничего не найдено');
  });

  it('когда есть что показать, слов нет вовсе', () => {
    expect(emptyText({ loaded: true, total: 40, showing: 3 })).toBe('');
  });
});
