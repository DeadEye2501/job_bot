// Следствия вкладки навыков: как они разложены по категориям и что в заголовке.

import { describe, expect, it } from 'vitest';

import { aliasesAfter, countNote, grouped, levelPercent } from '../state/skills.js';
import { plural } from '../state/words.js';

describe('раскладка навыков по категориям', () => {
  it('порядок категорий — по первому появлению', () => {
    // Человек сам расставил их в этом порядке; пересортируй мы по алфавиту,
    // его раскладка рассыпалась бы при каждом открытии вкладки.
    const groups = grouped([
      { name: 'Python', category: 'Языки' },
      { name: 'Docker', category: 'Инфра' },
      { name: 'Go', category: 'Языки' },
    ]);

    expect(groups.map((one) => one.name)).toEqual(['Языки', 'Инфра']);
    expect(groups[0].items.map((one) => one.name)).toEqual(['Python', 'Go']);
  });

  it('навык без категории попадает в общую', () => {
    // Пустая подпись категории читалась бы как поломка списка, а навык без
    // неё приходит из разбора резюме сплошь и рядом.
    const groups = grouped([{ name: 'SQL', category: '' }]);

    expect(groups[0].name).toBe('Общее');
  });

  it('пустой перечень даёт пустую раскладку', () => {
    expect(grouped([])).toEqual([]);
  });
});

describe('уровень навыка', () => {
  it('доля дорожки считается от десяти', () => {
    // По ней рисуется заливка ползунка: соври она — заливка встала бы не там,
    // где написано число рядом.
    expect(levelPercent(10)).toBe(100);
    expect(levelPercent(3)).toBe(30);
  });
});

describe('счёт в заголовке', () => {
  it('число и слово согласованы', () => {
    // «1 категории» человек читает как опечатку и перестаёт верить остальному
    // на экране.
    expect(plural(1, 'категория', 'категории', 'категорий')).toBe('категория');
    expect(plural(3, 'категория', 'категории', 'категорий')).toBe('категории');
    expect(plural(5, 'категория', 'категории', 'категорий')).toBe('категорий');
  });

  it('подростковые числа берут последнюю форму', () => {
    // 11–14 — исключение русского счёта: «11 категории» звучит неверно.
    expect(plural(11, 'категория', 'категории', 'категорий')).toBe('категорий');
    expect(plural(14, 'категория', 'категории', 'категорий')).toBe('категорий');
  });

  it('заголовок называет оба счёта', () => {
    // По ним видно, что вкладка вообще что-то показывает: пустая она выглядит
    // так же, как несохранённая.
    expect(countNote(7, 2)).toBe('7 навыков, 2 категории');
  });

  it('счёт навыков не склоняется', () => {
    // Число навыков меняется на каждой правке строки, и склонённое слово
    // дёргалось бы под курсором; у категорий оно стоит месяцами.
    expect(countNote(1, 1)).toBe('1 навыков, 1 категория');
  });
});

describe('набор синонима', () => {
  it('отменённый набор в перечень не попадает', () => {
    // Escape набранное отменяет: иначе опечатка уезжает в базу отложенной
    // записью, и снимать её приходится крестиком.
    expect(aliasesAfter(['js'], 'JavaScrip', false)).toEqual(['js']);
  });

  it('подтверждённый набор встаёт в конец', () => {
    expect(aliasesAfter(['js'], 'JavaScript', true)).toEqual(['js', 'JavaScript']);
  });

  it('то же слово в другом регистре вторым не встаёт', () => {
    // «NumPy» и «numpy» — одно написание: мост сверяет их без регистра, и пара
    // в перечне значила бы лишнюю строку, которая ничего не находит.
    expect(aliasesAfter(['NumPy'], 'numpy', true)).toEqual(['NumPy']);
  });

  it('пустой набор перечня не трогает', () => {
    expect(aliasesAfter(['js'], '   ', true)).toEqual(['js']);
  });
});
