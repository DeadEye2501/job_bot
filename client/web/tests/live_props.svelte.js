// Свойства компонента, которые меняются по одному — как их меняет живой родитель.
//
// Подставные свойства, какие даёт `@testing-library/svelte`, для этого не
// годятся: там весь набор лежит одним значением, и правка любого свойства
// объявляет изменившимися все разом. Эффект, забывший назвать своей
// зависимостью номер открытой записи, на таком наборе всё равно заводится
// заново — то есть проверка зеленеет на подставке, а не на коде.

/** Заводит набор свойств и способ поменять одно из них.
 *
 * Отдаёт вид с геттером на каждое имя: читающий трогает ровно то свойство,
 * которое назвал, а не весь набор.
 */
export function livingProps(initial) {
  const held = $state({ ...initial });
  const view = {};
  for (const key of Object.keys(initial)) {
    Object.defineProperty(view, key, { get: () => held[key], enumerable: true });
  }
  return [view, (key, value) => (held[key] = value)];
}
