// Следствия раскладки месяца: что видно в сетке календаря и куда ведут стрелки.

import { describe, expect, it } from 'vitest';

import { WEEKDAYS, monthGrid, monthTitle, shiftMonth } from '../state/calendar.js';

describe('сетка месяца', () => {
  it('первое число встаёт под свой день недели', () => {
    // 1 августа 2026 — суббота. Начнись месяц с первой клетки, все числа
    // съехали бы на чужие дни недели, и выбранное не совпало бы с прочитанным.
    expect(monthGrid(2026, 8)[0]).toEqual([null, null, null, null, null, 1, 2]);
  });

  it('неделя начинается с понедельника, а не с воскресенья', () => {
    // 1 марта 2026 — воскресенье, и по-русски оно последнее в неделе.
    expect(monthGrid(2026, 3)[0]).toEqual([null, null, null, null, null, null, 1]);
    expect(WEEKDAYS[6]).toBe('Вс');
  });

  it('в сетке стоят все дни месяца и ни одного лишнего', () => {
    // Февраль високосного года: обрежь сетку по двадцати восьми — выбрать
    // двадцать девятое было бы нечем.
    const days = monthGrid(2024, 2)
      .flat()
      .filter((day) => day !== null);
    expect(days).toEqual(Array.from({ length: 29 }, (_, at) => at + 1));
  });

  it('в сетке всегда шесть недель, какой бы месяц ни показали', () => {
    // Больше шести недель в месяц не укладывается никогда, а меньше — сплошь
    // и рядом: февраль невисокосного года, начавшийся с понедельника, влезает
    // в четыре. Расти и сжиматься по месяцу значит прыгать высотой на каждом
    // перелистывании — вместе со всем, что стоит под календарём.
    expect(monthGrid(2026, 8)).toHaveLength(6);
    expect(monthGrid(2026, 2)).toHaveLength(6);
    expect(monthGrid(2021, 2)).toHaveLength(6);
  });

  it('в каждой неделе семь клеток', () => {
    // Числа стоят колонками под подписями дней недели: неделя короче семи
    // сдвинула бы все, что под ней.
    expect(monthGrid(2026, 8).every((week) => week.length === 7)).toBe(true);
  });
});

describe('шаг по месяцам', () => {
  it('назад из января уводит в декабрь прошлого года', () => {
    expect(shiftMonth(2026, 1, -1)).toEqual({ year: 2025, month: 12 });
  });

  it('вперёд из декабря уводит в январь следующего', () => {
    expect(shiftMonth(2026, 12, 1)).toEqual({ year: 2027, month: 1 });
  });
});

describe('подпись месяца', () => {
  it('называет месяц по-русски вместе с годом', () => {
    expect(monthTitle(2026, 8)).toBe('Август 2026');
  });
});
