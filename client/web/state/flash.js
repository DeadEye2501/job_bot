// Отметка «записано»: загорается по записи и гаснет сама.
//
// Своим модулем, а не в поле заметки: так отзываются три места — заметка
// карточки, значение строки отсева и причина рядом с ним, — а отсчёт у них
// один, и второе его написание разошлось бы с первым молча.

// Сколько горит зелёная рамка записанного. Ровно столько же длится её угасание
// в оформлении: погасшая раньше срока читалась бы как моргание.
const FLASH_MS = 400;

/** Заводит отметку, которая гаснет сама.
 *
 * Второе зажигание подряд отсчёт продлевает, а не гасит: быстрая правка двух
 * полей иначе тушила бы рамку по времени первого, и вторая запись выглядела бы
 * незаписанной.
 */
export function flashing(paint) {
  let timer = null;
  return () => {
    paint(true);
    clearTimeout(timer);
    timer = setTimeout(() => paint(false), FLASH_MS);
  };
}
