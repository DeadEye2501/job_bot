// Ожидание своей вести: кнопка пустила долгую работу и ждёт её итог.
//
// Весть об исходе одна на все долгие работы (`action_finished`), и кто какую
// ждёт, узнаётся по метке пустившей её кнопки. Учёт живёт вне экранов: окно
// заведения закрывается на «пущено», человек уходит из раздела, а итог всё
// равно должен дойти до того, кто его ждёт. Ждущих по метке разводит только
// этот файл; плашку той же вести показывает оболочка сама.

let waiting = $state({});

/** Кто чего ждёт. */
export const awaited = {
  /** Ждать итог работы с меткой `action`; `settle(news)` зовётся с её вестью.
   *  Ставится до зова моста: мгновенный отказ приходит вестью раньше ответа. */
  start(action, settle) {
    waiting = { ...waiting, [action]: settle };
  },

  /** Зов отказал до пуска — ждать нечего. */
  cancel(action) {
    const { [action]: _gone, ...rest } = waiting;
    waiting = rest;
  },

  /** Ждут ли сейчас итога работы с этой меткой. */
  pending(action) {
    return action in waiting;
  },
};

/** Подписать учёт на вести моста; отдаёт отписку.
 *
 * Свежая подписка начинает без ожиданий: окно открылось заново, а работы,
 * пущенные из прошлого, своих вестей сюда уже не пришлют.
 */
export function hearAwaited(events) {
  waiting = {};
  return events.on('action_finished', (news) => {
    const settle = waiting[news.action];
    if (!settle) return;
    awaited.cancel(news.action);
    settle(news);
  });
}
