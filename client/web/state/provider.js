// Разговор с поставщиком моделей: что он отвечает на два наших вопроса.
//
// Своим объявлением, а не в каждом экране: спрашивают поставщика двое —
// настройки и шаг мастера, — и написаны эти разговоры были дословно одинаково.
// Разошлись они молча: в мастере отказ поставщика стал неотличим от пустого
// перечня, и недоступный сервер объявлялся «не вернувшим ни одной модели».
//
// Зов моста приходит доводом: слой состояния про `window.pywebview` не знает
// ничего, а проверить разговор без окна иначе было бы нечем.

/** Спросить у поставщика имена его моделей.
 *
 * Отказ и пустой перечень — разные ответы, и путать их нельзя: первое значит
 * «сервер не отозвался», второе — «сервер поднят, но модели в нём нет», и
 * чинятся они по-разному. Отказ приходит фразой, а не пустотой.
 *
 * Имя модели в вопрос не идёт: перечень читается с адреса и ключа, а имя — как
 * раз то, что в нём ищут.
 */
export async function askModels(call, { kind, base_url, api_key }) {
  try {
    const answer = await call('settings.list_models', { kind, base_url, api_key });
    return { models: answer?.models || [], trouble: '' };
  } catch (refusal) {
    return { models: [], trouble: refusal.message };
  }
}

/** Проверить связь с поставщиком.
 *
 * Отказ поставщика — это и есть исход проверки, и человек читает его фразу там
 * же, где читал бы удачу. Поэтому он возвращается ответом, а не поднимается
 * дальше: общая плашка окна показала бы то же самое и погасла, а искать
 * причину человек будет у поля.
 */
export async function probeModel(call, creds) {
  try {
    const answer = await call('settings.probe_model', creds);
    return {
      ok: true,
      model: answer.model || '',
      latencyMs: answer.latency_ms || 0,
      trouble: '',
    };
  } catch (refusal) {
    return { ok: false, model: '', latencyMs: 0, trouble: refusal.message };
  }
}

/** Спросить у человека файл модели диалогом окна.
 *
 * Закрытый диалог — пустой путь, а не беда: человек передумал. Отказ моста
 * приходит фразой, как у соседей. Нужен мастеру и настройкам, и написанный
 * дважды разошёлся бы в том, что считать «передумал».
 */
export async function pickModelFile(call) {
  try {
    const answer = await call('settings.pick_model_file');
    return { path: answer?.path || '', trouble: '' };
  } catch (refusal) {
    return { path: '', trouble: refusal.message };
  }
}

