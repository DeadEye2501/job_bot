// Заметка в карточке: записать и вернуть полю то, что считается записанным.
//
// Своим объявлением, а не пятью строками в каждой карточке: заметки правят у
// человека и у компании, и написано это было дословно одинаково — вместе с
// семистрочным пояснением, совпавшим побайтно.

/** Предел длины заметки — один на все её места: поле карточки и окно
 *  заведения. В базе длина не ограничена вовсе, и разъедься числа, человек
 *  набирал бы у компании столько, сколько у вакансии уже не помещается. Поля
 *  форм — не заметки: у них свои предметы и свои числа. */
export const NOTES_LIMIT = 2000;

/** Заводит запись заметки.
 *
 * Карточку не перечитываем: человек мог набрать ещё, пока летел вопрос, и
 * пришедшее из базы стёрло бы это. Записанным считаем набранное — этот зов
 * называет только поправленные поля, самой заметки в ответе нет, — а пустая от
 * пробельной здесь не отличается, обе сводятся к пустоте по дороге.
 *
 * Ответ в закрытую карточку не кладётся: панель закрывают, не дожидаясь записи,
 * и сказанное ей всплыло бы над следующей, открытой на её месте.
 *
 * `null` значит «не легло»: поле по нему считает набранное несохранённым, и
 * следующая попытка уедет тем же текстом.
 */
export function cardNotes({ ask, method, payload, alive, onchanged }) {
  return async function saveNotes(id, text) {
    const done = await ask(method, payload(id, text));
    if (!alive() || done === null) return null;
    onchanged();
    return text;
  };
}
