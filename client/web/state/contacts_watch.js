// Заход на вкладку контактов и на карточку источника: прочитать и следить за
// правками.
//
// Своим объявлением, потому что вкладок таких две — люди и компании, — и
// написан этот заход у них байт в байт одинаково. Расходятся такие копии
// молча: забытое снятие подписки оставляет за экраном второго слушателя, и
// каждая весть перечитывает список дважды.
//
// Списки эти правит не только окно: бот заводит людей и компании сам, разбирая
// переписку и объявления. Без подписки вкладка показывала бы снимок той
// минуты, когда её открыли.

/** Заходит на вкладку и отдаёт снятие — его и возвращают из эффекта.
 *
 * Перечитывает по вести не страницей, а показанным: иначе занесение в отсев из
 * карточки схлопывало бы пролистанное до первой страницы.
 */
export function watchContacts(events, list) {
  const deaf = events.on('contacts_lists_changed', () => list.again());
  const settled = list.entered();
  return () => {
    settled();
    deaf();
  };
}

/** Заходит на карточку источника — канала или агрегатора — и отдаёт снятие.
 *
 * `alive` — признак жизни карточки (`alive.js`), `id` — открытый источник.
 * `forget` убирает показанное прежним: панель одна, и его числа под новым
 * именем читались бы как числа нового. `read(id)` читает карточку с её
 * вакансиями — и на заходе, и по вести: обход приносит вакансии, пока карточка
 * открыта, и смотрит прогнавший человек именно на них.
 */
export function watchSourceCard(events, alive, id, { forget, read }) {
  const settled = alive.entered(() => {
    forget();
    read(id);
  });
  const deaf = events.on('vacancies_list_changed', () => read(id));
  return () => {
    settled();
    deaf();
  };
}
