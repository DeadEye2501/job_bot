// Заход на вкладку контактов: прочитать список и следить за его правками.
//
// Своим объявлением, потому что вкладки контактов заходят одинаково, а
// расходятся такие копии молча: забытое снятие подписки оставляет за экраном
// второго слушателя, и каждая весть перечитывает список дважды.
//
// Списки эти правит не только окно: бот заводит записи и заносит их в отсев
// сам, разбирая переписку и объявления. Без подписки вкладка показывала бы
// снимок той минуты, когда её открыли.

/** Заходит на вкладку и отдаёт снятие — его и возвращают из эффекта.
 *
 * Перечитывает по вести не страницей, а показанным: иначе занесение в отсев из
 * карточки схлопывало бы пролистанное до первой страницы.
 */
export function watchContacts(events, list) {
  const deaf = events.on('contacts_lists_changed', () => list.again());
  const settled = list.entered();
  return () => {
    settled();
    deaf();
  };
}
