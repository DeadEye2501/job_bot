// Зов моста, ответ которого ещё нужен: устаревший и пришедший в закрытый экран
// не кладутся никуда.
//
// Своим объявлением, а не четырьмя строками в каждом экране: написаны они были
// девять раз дословно — тот же счёт попыток, тот же взвод, та же тройка
// условий. Расходятся такие копии молча: достаточно забыть в одной из них
// проверку жизни экрана, и ответ ляжет в снесённое состояние.

import { attempts } from './attempts.js';

/** Заводит зов, отбивающий устаревший ответ.
 *
 * Заводится на каждое место, где вопросы обгоняют друг друга: свой у поиска,
 * свой у прокрутки, свой у каждой панели. Общий на экран объявлял бы
 * устаревшим ответ соседнего вопроса — их спрашивают вперемешку.
 *
 * `alive` спрашивают, а не передают значением: экран закрывают, пока ответ в
 * пути, и класть его тогда уже некуда.
 *
 * Сам зов принимается обёрткой, а не именем метода с нагрузкой: мост зовут с
 * разным числом доводов, и «ничего» отличается у него от «ничего не передали».
 *
 * `null` значит «не класть ничего»: отказ моста, ушедший экран и обогнанный
 * ответ на месте различать некому — все трое означают одно. Отказ поэтому и не
 * отбивается своей веткой: мост отвечает на него пустотой, и она уходит
 * зовущему сама, тем же словом, что и два остальных исхода.
 */
export function freshAnswer(alive) {
  const needed = stillNeeded(alive);

  return async function fresh(call) {
    const got = await needed(call);
    return got === null ? null : got.now;
  };
}

/** Заводит тот же зов, но отдающий пришедшее коробкой.
 *
 * Коробка нужна тому, кто различает больше двух исходов: отказ моста — это
 * тоже ответ, и рассказать о нём человеку надо, а вот ушедший экран и
 * обогнанный ответ значат «класть некуда». Пустота здесь — только про эти
 * два; отказ приезжает коробкой с пустотой внутри.
 */
export function stillNeeded(alive) {
  const tries = attempts();

  return async function once(call) {
    const mine = tries.next();
    const now = await call();
    return !alive() || tries.stale(mine) ? null : { now };
  };
}
