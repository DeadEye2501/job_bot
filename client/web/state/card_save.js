// Правка поля карточки: записать и показать то, что легло на самом деле.
//
// Своим объявлением, а не тремя строками в каждой карточке: поля правят у
// человека и у компании, и написано это было дословно одинаково, вплоть до
// пояснения.

/** Заводит запись правки поля.
 *
 * Перечитываем и после отказа: поля правятся на месте, и отклонённое мостом
 * значение — а негодный ник мост отклоняет — осталось бы на экране. Человек
 * читал бы своё, а в базе лежало бы прежнее.
 *
 * Списку говорят только по удаче: не изменилось ничего, и перечитывать его
 * значило бы гонять мост ради того же вида.
 */
export function cardSave({ ask, method, reread, onchanged }) {
  return async function save(payload) {
    const done = await ask(method, payload);
    await reread();
    if (done !== null) onchanged();
  };
}
