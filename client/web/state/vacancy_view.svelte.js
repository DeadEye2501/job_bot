// Отбор и порядок списка вакансий, пережившие уход из раздела.
//
// Своим объявлением, а не полем экрана: разделы оболочка не прячет, а рушит, и
// вместе с экраном вакансий умирало бы выбранное в нём. Человек набирает отбор
// из девяти условий, уходит в карточку компании за одной справкой и
// возвращается к списку, собранному заново с нуля.
//
// Здесь лежит только выбранное человеком. Ни строк, ни страниц, ни открытой
// карточки: строки за время отсутствия успевает подвинуть бот, и показанные из
// памяти, они врали бы о положении дел.

import { blankFilter } from './vacancy_filter.js';
import { SORTS } from './vacancies.js';

let filter = $state(blankFilter());
let sort = $state(SORTS[0].label);

/** Отбор и порядок, какими их оставили в прошлый заход. */
export const vacancyView = {
  get filter() {
    return filter;
  },
  set filter(next) {
    filter = next;
  },
  /** Порядок хранится подписью, а не ключом: подписью его выбирают в меню и
   *  подписью же показывают в подсказке кнопки. */
  get sort() {
    return sort;
  },
  set sort(label) {
    sort = label;
  },
};
