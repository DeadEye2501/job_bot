// Ник записи в Telegram: чем он подписан у нас и по какому адресу открывается.
//
// Своим модулем, а не у людей или каналов: ник есть и у человека, и у канала, а
// пишется он одинаково — второе его написание разошлось бы с первым молча. Так
// и вышло: отсутствие ника называли двумя разными словами в двух соседних
// строках одного списка.

/** Чем подписан ник — или прямое слово о том, что его нет.
 *
 * Отсутствие тут говорящее: такую запись не найти в Telegram по имени. Пустое
 * место читалось бы как недогрузившаяся строка.
 */
export function handleName(username) {
  return username ? `@${username}` : 'без ника';
}

/** Адрес, по которому человека или канал открывают в самом Telegram.
 *
 * Ник, а не номер учётной записи: по номеру Telegram открывает разговор только
 * своим клиентом и не всегда, а ник работает и в окне браузера.
 */
export function telegramHref(username) {
  return `https://t.me/${username}`;
}
