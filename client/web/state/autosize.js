// Высота многострочного поля по набранному в нём.
//
// Своим объявлением, а не двумя строками у каждого поля: так растут три —
// причина в строке отсева, строка достижений и пояснение в ленте вакансии, — и
// написаны они были дословно одинаково. Полос прокрутки у этих полей нет: в
// строке таблицы и в ленте их не разглядеть, а не растянутое поле прячет
// вторую половину набранного.
//
// Соседи по слою объявляют себя чистыми и разметки не знают, а этот трогает
// само поле — как и сторож «нажали мимо» (`outside.js`), который слушает
// документ. Обоих держит здесь одно: правило общее для многих мест, а знать о
// нём должно состояние, не разметка. Считанное и поставленное наружу не уходит
// — из поля берётся его же высота и в него же кладётся.

import { tick as painted } from 'svelte';

/** Подогнать высоту поля под его текст.
 *
 * Сжатие до `auto` перед замером несущее: растянутое поле показывает прежнюю
 * высоту и после того, как текст из него убрали, — стёртый абзац оставил бы
 * после себя дыру во весь свой рост.
 *
 * Поле может объявить предел в строках (`data-lines`): длинный текст тогда
 * прокручивается внутри, а не растягивает форму на весь экран. Растянуть его
 * выше человек может сам, за нижний край.
 */
export function fitHeight(field) {
  field.style.height = 'auto';
  // Высота поля считается с рамкой, а текст меряется без неё: без прибавки
  // поле выходит на ширину рамки ниже текста, и сбоку встаёт прокрутка.
  const border = field.offsetHeight - field.clientHeight || 0;
  field.style.height = `${Math.min(field.scrollHeight, mostHeight(field)) + border}px`;
}

/** Высота поля в объявленный предел строк; предела нет — без ограничения.
 *
 * Высота строки `normal` числом не читается: браузер берёт её около 1.2
 * размера шрифта, и так же считается здесь.
 */
function mostHeight(field) {
  const lines = Number(field.dataset?.lines);
  if (!lines) return Infinity;
  const look = getComputedStyle(field);
  const line = parseFloat(look.lineHeight) || parseFloat(look.fontSize) * 1.2;
  return lines * line + parseFloat(look.paddingTop) + parseFloat(look.paddingBottom);
}

/** Держать высоту поля подогнанной, пока поле живёт: при заведении, на каждый
 *  набор и на смену текста снаружи.
 *
 * Распорядителем, а не парой строк у каждого поля: так растянуты и строка
 * достижений, и пояснение в ленте вакансии. Второй такой же был бы копией —
 * первая уже стоила ленте падения, когда своё объявление у неё уехало, а зов
 * из разметки остался.
 *
 * Довод — сам текст: на его смену срабатывает `update`. Она нужна там, где
 * строки ключены по месту в списке: после удаления соседней в то же поле
 * переезжает чужой текст — длинный в строку, размеренную под короткую, и хвост
 * его не виден вовсе. Ждём при этом отрисовки, потому что `update` идёт раньше,
 * чем новое значение попадёт в поле, и померенное сразу было бы высотой
 * прежнего жильца ячейки.
 */
export function growing(field) {
  const fit = () => fitHeight(field);
  fit();
  field.addEventListener('input', fit);
  return {
    update: () => painted().then(fit),
    destroy: () => field.removeEventListener('input', fit),
  };
}
