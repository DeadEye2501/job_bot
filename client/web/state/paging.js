// Страницы списка: сколько просить за раз, как дописывать и что перечитывать.
//
// Списков, читающих страницами, во фронте несколько — компании, вакансии
// канала, — и правило у них одно на всех. Про предмет списка этот файл не
// знает ничего: строки приходят и уходят как есть.

/** Сколько строк в странице. Столько же по умолчанию отдаёт мост. */
export const PAGE = 50;

/** Сколько строк в странице списка вакансий.
 *
 * Меньше общей: страницы здесь тянет прокрутка, а не нажатие, и каждая строка
 * тяжелее — три этажа со стеком против одной строки контакта.
 */
export const VACANCY_PAGE = 20;

// За сколько до низа просить следующую страницу.
const AHEAD = 150;

/** Пора ли просить следующую страницу.
 *
 * Заранее, а не по упору в дно: доехавший до низа человек уже стоит перед
 * пустотой, и список догружается у него на глазах вместо того, чтобы просто
 * продолжаться.
 */
export function nearBottom({ scrollTop, clientHeight, scrollHeight }) {
  return scrollTop + clientHeight >= scrollHeight - AHEAD;
}

/** Дочитать открытую карточку, когда её панель подошла к концу.
 *
 * Прокручивается панель целиком, вместе с шапкой и числами карточки, — и знает
 * об этой прокрутке список, а не сама карточка. `card` — открытая карточка с
 * `more()` или пусто, пока ничего не открыто.
 */
export function detailScrolled(event, card) {
  if (card !== null && nearBottom(event.currentTarget)) card.more();
}

/** Пора ли просить письма постарее.
 *
 * Переписку листают в другую сторону — вверх, к началу разговора, — и потому
 * порог тут свой, от верхнего края. Ждать упора нельзя по той же причине, что и
 * внизу списка: доехавший до края упирается в пустоту вместо продолжения.
 */
export function nearTop({ scrollTop }) {
  return scrollTop <= AHEAD;
}

// Потолок перечитывания. Пролистанные тысячи строк одним запросом — ожидание
// на ровном месте, а перечитывают список после каждой правки поля.
const RELOAD_MAX = 200;

/** Дописать пришедшую страницу к показанному.
 *
 * Повторы отбрасываются: пока листали, перечень мог сдвинуться — бот заводит
 * компании и собирает вакансии сам, — и строка с края прошлой страницы
 * приезжает второй раз.
 */
export function appended(shown, page) {
  const known = new Set(shown.map((one) => one.id));
  return [...shown, ...page.filter((one) => !known.has(one.id))];
}

/** Сколько строк просить, перечитывая список после правки.
 *
 * Не меньше показанного, но и не больше потолка: страницей догруженное
 * схлопнулось бы до первой, и человек, поправивший имя на четвёртой сотне,
 * остался бы с началом списка. Потолок при этом сильнее: пролиставший тысячу
 * строк получит двести и догрузит остальное сам — ждать тысячу строк на каждую
 * правку поля дороже, чем нажать «показать ещё».
 *
 * Страница — довод: у вакансий она своя, и общим числом перечитанный список из
 * двадцати строк вырос бы вдвое с половиной от одной смены статуса.
 */
export function refreshLimit(shownCount, page = PAGE) {
  return Math.min(RELOAD_MAX, Math.max(page, shownCount));
}
