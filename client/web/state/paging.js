// Страницы списка: сколько просить за раз, как дописывать и что перечитывать.
//
// Списков, читающих страницами, во фронте несколько — компании, вакансии
// канала, — и правило у них одно на всех. Про предмет списка этот файл не
// знает ничего: строки приходят и уходят как есть.

/** Сколько строк в странице. Столько же по умолчанию отдаёт мост. */
export const PAGE = 50;

// Потолок перечитывания. Пролистанные тысячи строк одним запросом — ожидание
// на ровном месте, а перечитывают список после каждой правки поля.
const RELOAD_MAX = 200;

/** Дописать пришедшую страницу к показанному.
 *
 * Повторы отбрасываются: пока листали, перечень мог сдвинуться — бот заводит
 * компании и собирает вакансии сам, — и строка с края прошлой страницы
 * приезжает второй раз.
 */
export function appended(shown, page) {
  const known = new Set(shown.map((one) => one.id));
  return [...shown, ...page.filter((one) => !known.has(one.id))];
}

/** Сколько строк просить, перечитывая список после правки.
 *
 * Не меньше показанного: страницей догруженное схлопнулось бы до первой, и
 * человек, поправивший имя на четвёртой сотне, остался бы с началом списка.
 */
export function refreshLimit(shownCount) {
  return Math.min(RELOAD_MAX, Math.max(PAGE, shownCount));
}
