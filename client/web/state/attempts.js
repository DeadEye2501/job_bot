// Счёт попыток: по нему устаревший ответ узнаётся и отбрасывается.
//
// Про мост не знает ничего — это чистый счётчик, и лежит он здесь именно
// поэтому: слой `api/` знает про `window.pywebview`, а тут знать нечего.

/** Завести свой счёт попыток.
 *
 * Заводится он на каждое место, где запросы обгоняют друг друга, — поиск,
 * прокрутка, переключение вкладок. Общий счётчик на страницу отбрасывал бы
 * ответы соседнего экрана.
 *
 * Начатую работу счёт не останавливает — остановить её со страницы нечем, — а
 * обесценивает её ответ: пришедший последним не считается свежим, если после
 * него успели спросить заново.
 *
 * **Это не про закрытие окна.** Свежим тут считается ровно один запрос, а окно
 * спрашивает мост вперемешку — здоровье, непрочитанное, режим, — и соседний
 * ответ такой счёт объявил бы устаревшим. Уход со страницы оболочка сторожит
 * своим признаком: там гасится всё разом, а не последнее.
 */
export function attempts() {
  let issued = 0;
  let newest = 0;
  return {
    next() {
      issued += 1;
      newest = issued;
      return issued;
    },
    stale(number) {
      return number !== newest;
    },
  };
}
