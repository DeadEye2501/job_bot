// Признак «экран ещё на месте»: класть ли пришедший ответ.
//
// Своим объявлением, а не тремя строками в каждом экране: их два десятка, и
// написаны они были дословно одинаково — поле, взвод в эффекте и снятие в его
// уборщике. Ответы моста доезжают и после ухода с экрана, а класть их тогда уже
// некуда: разметки нет, а положенное в снесённое состояние всплывает при
// следующем заходе поверх свежего.
//
// Это не про устаревший ответ: там свежим считается ровно один запрос, и его
// сторожит свой счёт (`attempts`). Здесь гасится всё разом, а не последнее.

/** Заводит признак жизни экрана. */
export function living() {
  let live = true;

  /** Пометить живым; отдаёт снятие пометки — его и возвращают из эффекта.
   *
   * Взвод нужен потому, что эффект заводится заново: экран открывают, уходят
   * и возвращаются, а объявление живёт столько же, сколько сам компонент.
   */
  function mounted() {
    live = true;
    return () => {
      live = false;
    };
  }

  return {
    /** Жив ли экран сейчас. */
    get now() {
      return live;
    },
    mounted,
    /** Заход на экран целиком: взвести признак, прочитать себя и отдать снятие.
     *
     * Заход этот был написан побайтно одинаково шесть раз — у трёх вкладок
     * анкеты и у трёх шагов мастера. Читают они разное, а заходят одинаково, и
     * разойтись копии могли только пропущенным снятием.
     *
     * Живёт здесь, а не своим файлом: ничего, кроме этого самого признака,
     * заход не трогает — он и есть его взвод со снятием. Зов моста
     * (`state/fresh.js`) вынесен отдельно как раз потому, что сводит признак с
     * посторонним ему счётом попыток.
     */
    entered(read) {
      const settled = mounted();
      read();
      return settled;
    },
  };
}
