// Заведение записи из окна над списком.
//
// Своим объявлением, потому что заведение у всех окон над списками одно: тот
// же черновик с заслоном, тот же порядок гашения окна. Расходятся такие
// копии молча: достаточно забыть в одной из них сброс черновика, и следующее
// окно откроется поверх прошлого набранного.
//
// Отказ моста бывает двух родов, и оба держатся здесь. Обёртка, отвечающая
// пустотой, уже показала его плашкой. Обёртка, бросающая отказ, оставляет его
// окну: у окна об одном поле — адрес канала, сайта, контакт — отказ почти всегда
// опечатка, и объясняют её там же, где набирали.
//
// Про предмет списка здесь не знают ничего: слова приходят обвязкой формы
// (`new_card`), а запись — обёрткой. Обёрткой, а не именем метода моста: имя
// должно быть видно на шве, в самой вкладке, а собранное из кусков не видно
// там вовсе.
//
// Строка отсева заводится не отсюда (`app/BlacklistList.svelte`), хотя порядок
// у неё тот же: род у неё выбирают в самом окне, слово об удаче зависит от
// ответа моста — заведена строка или такая уже была, — а список за ней стоит
// не страничный. Общего осталось бы меньше, чем развилок внутри.

/** Заводит окно заведения.
 *
 * `list.again(answer)` — что сделать по удаче: перечитать список вкладки или
 * положить список, пришедший в ответе моста.
 *
 * `save` отправляет черновик; отказ — пустота (уже показан плашкой) или
 * брошенная ошибка (остаётся в окне, см. `trouble`).
 *
 * `form.done(draft, answer)` — слово по удаче; пустое значит, что об исходе
 * скажет весть.
 *
 * `held` — где лежит черновик: у окон о человеке, компании, канале и контакте
 * он свой и умирает с экраном, у окна вакансии его держит оболочка — набранное
 * должно дожить до итога разбора. `keeps()` — ждут ли итога: тогда закрытое
 * окно черновик не стирает.
 */
export function contactAdding({ list, form, save, say, held = ownDraft(form), keeps = () => false }) {
  let adding = $state(false);
  let saving = $state(false);
  let trouble = $state('');

  const ready = $derived(form.named(held.draft));

  return {
    /** Открыто ли окно заведения. */
    get adding() {
      return adding;
    },
    set adding(open) {
      // Закрытое без записи окно набранного не хранит: следующий заход
      // начинается с чистого черновика, а не с чужой недописанной карточки.
      // Заведённые по дороге чужие записи это не отменяет — они уже легли в
      // базу, и черновик им не хозяин.
      if (!open) {
        if (!keeps()) held.draft = form.blank();
        trouble = '';
      }
      adding = open;
    },
    /** Летит ли сейчас заведение: им заперта кнопка окна. */
    get saving() {
      return saving;
    },
    /** Отказ моста словами, оставленный окну; пусто — отказа нет. */
    get trouble() {
      return trouble;
    },
    /** Набранное в окне заведения. Форму правят на месте её поля; черновик
     *  строкой — у окна об одном поле — заменяется целиком. */
    get draft() {
      return held.draft;
    },
    set draft(value) {
      held.draft = value;
    },
    /** Названа ли карточка хоть чем-нибудь — тем же заслоном, что и на мосту. */
    get ready() {
      return ready;
    },
    /** Завести карточку по набранному.
     *
     * Окно закрываем только по удаче: отказ — это чаще всего занятое имя или
     * опечатка в нике, и набранное человеку ещё пригодится.
     *
     * Список перечитывается показанным, а не страницей: заведение не повод
     * схлопывать пролистанное.
     */
    async create() {
      if (!ready || saving) return;
      saving = true;
      trouble = '';
      let done;
      try {
        done = await save(held.draft);
      } catch (refusal) {
        trouble = refusal.message;
        return;
      } finally {
        saving = false;
      }
      if (done === null) return;
      // Через сеттер, а не мимо него: чистка черновика записана там одна на
      // все выходы из окна, и второе её написание здесь разъехалось бы с ним.
      // Слово по удаче спрашивается у формы, а не берётся полем: у вакансии
      // оно зависит от того, какой стороной её завели, а пустое значит, что
      // об исходе скажет весть. Спрашивается до закрытия окна: закрытие
      // чистит черновик, и спрошенное после относилось бы к пустому.
      const word = form.done(held.draft, done);
      this.adding = false;
      if (word) say(word);
      return list.again(done);
    },
  };
}

/** Черновик, который живёт с самим окном заведения. */
function ownDraft(form) {
  let draft = $state(form.blank());
  return {
    get draft() {
      return draft;
    },
    set draft(value) {
      draft = value;
    },
  };
}
