// Заведение карточки контакта из окна над вкладкой.
//
// Своим объявлением, потому что вкладок таких две — люди и компании, — и
// заведение у них написано дословно одинаково: тот же черновик с заслоном, тот
// же порядок гашения окна. Расходятся такие копии молча: достаточно забыть в
// одной из них сброс черновика, и следующее окно откроется поверх прошлого
// набранного.
//
// Про предмет вкладки здесь не знают ничего: слова приходят обвязкой формы
// (`new_card`), а запись — обёрткой. Обёрткой, а не именем метода моста: имя
// должно быть видно на шве, в самой вкладке, а собранное из кусков не видно
// там вовсе.
//
// Строка отсева заводится не отсюда (`app/BlacklistList.svelte`), хотя порядок
// у неё тот же: род у неё выбирают в самом окне, слово об удаче зависит от
// ответа моста — заведена строка или такая уже была, — а список за ней стоит
// не страничный. Общего осталось бы меньше, чем развилок внутри.

/** Заводит окно заведения карточки.
 *
 * `list` — уже заведённый список этой вкладки: перечитывают его и отсюда,
 * заведя карточку, и сама вкладка по вести о правке.
 *
 * `save` отправляет черновик и отвечает пустотой на отказ — тем же словом,
 * каким отвечает мост.
 */
export function contactAdding({ list, form, save, say }) {
  let adding = $state(false);
  let saving = $state(false);
  let draft = $state(form.blank());

  const ready = $derived(form.named(draft));

  return {
    /** Открыто ли окно заведения. */
    get adding() {
      return adding;
    },
    set adding(open) {
      adding = open;
    },
    /** Летит ли сейчас заведение: им заперта кнопка окна. */
    get saving() {
      return saving;
    },
    /** Набранное в окне заведения. Правится на месте самими полями. */
    get draft() {
      return draft;
    },
    /** Названа ли карточка хоть чем-нибудь — тем же заслоном, что и на мосту. */
    get ready() {
      return ready;
    },
    /** Завести карточку по набранному.
     *
     * Окно закрываем только по удаче: отказ — это чаще всего занятое имя или
     * опечатка в нике, и набранное человеку ещё пригодится.
     *
     * Список перечитывается показанным, а не страницей: заведение не повод
     * схлопывать пролистанное.
     */
    async create() {
      if (!ready) return;
      saving = true;
      const done = await save(draft);
      saving = false;
      if (done === null) return;
      adding = false;
      draft = form.blank();
      say(form.done);
      return list.again();
    },
  };
}
