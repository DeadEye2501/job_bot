// Окно выбора: из чего его строка и когда выбранным можно связывать.
//
// Своим модулем, а не у людей или компаний: окном выбирают и тех и других, а
// правила у него одни — предметного в них нет ничего.

import { atHandle } from './telegram.js';

/** Отперта ли кнопка «Связать».
 *
 * Промах мышью по строке списка не должен менять привязку: выбор строки только
 * помечает её, а связывает отдельная кнопка. Выбор уже привязанного кнопку не
 * отпирает — нажатие переписало бы связь тем же значением и записало в ленту
 * перемену, которой не было.
 */
export function linkReady({ current, chosen }) {
  return chosen !== null && chosen !== undefined && chosen !== current;
}

/** Запись в том виде, в каком её показывает окно выбора.
 *
 * Подпись приходит готовой (`line`), а не собирается здесь: как называется
 * человек и как компания, знают их собственные модули, и второе написание
 * разошлось бы с первым — один и тот же человек читался бы как двое разных.
 *
 * Снимка может не быть вовсе — у компании его нет никогда, — но поле остаётся:
 * строка выбора одна на оба предмета, и разбирать в ней два разных набора полей
 * значило бы держать две строки вместо одной.
 */
export function candidate({ id, icon, avatar = null, line, count, blocked }) {
  return { id, icon, avatar, ...line, count, blocked };
}

/** Как строка называет себя в подсказке: имя, а за ним ник через разделитель.
 *
 * Как зовут саму запись, здесь не решают — это знает её модуль, и он приходит
 * доводом `named`. Тот же запрет записан у соседнего `candidate`: имя
 * человека бывает пустым, и собранное здесь второе написание разошлось бы с
 * первым — безымянный читался бы словом «null».
 *
 * Ник тут несущий, а не украшение: имя человека уникальным не бывает — трое
 * «Ирин» без него дают три одинаковые строки, и выбрать из них нужную нечем.
 * Приписывается он только к имени: у безымянного ник уже стоит **вместо**
 * имени (`people.personName`), и второй раз он повторял бы сам себя.
 *
 * У компании ника нет вовсе, и подпись у неё — одно название.
 */
export function labelOf(row, named) {
  const shown = named(row);
  return row.name && row.telegram_username
    ? `${shown} · ${atHandle(row.telegram_username)}`
    : shown;
}

/** Подписи строк — тому, кто подсказывает набранному.
 *
 * Подсказка работает словами: номер карточки человеку не о чем сравнивать с
 * тем, что он набрал.
 */
export function labels(rows, named) {
  return rows.map((one) => labelOf(one, named));
}

/** Строка, названная так же, как набранное, — без оглядки на регистр.
 *
 * Сверяются два написания, и оба нужны: выбранное в подсказке приходит
 * подписью с ником, а набранное руками — одним именем. Узнавай форма только
 * подпись, набравший знакомое имя завёл бы вторую такую же карточку.
 *
 * Регистр не в счёт нарочно: «nitka» и «Nitka» — одна компания.
 */
export function sameName(rows, typed, named) {
  const needle = typed.trim().toLowerCase();
  return (
    rows.find((one) => labelOf(one, named).toLowerCase() === needle) ??
    rows.find((one) => (one.name ?? '').toLowerCase() === needle && one.name) ??
    null
  );
}
