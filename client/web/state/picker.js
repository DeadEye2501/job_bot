// Окно выбора: из чего его строка и когда выбранным можно связывать.
//
// Своим модулем, а не у людей или компаний: окном выбирают и тех и других, а
// правила у него одни — предметного в них нет ничего.

/** Отперта ли кнопка «Связать».
 *
 * Промах мышью по строке списка не должен менять привязку: выбор строки только
 * помечает её, а связывает отдельная кнопка. Выбор уже привязанного кнопку не
 * отпирает — нажатие переписало бы связь тем же значением и записало в ленту
 * перемену, которой не было.
 */
export function linkReady({ current, chosen }) {
  return chosen !== null && chosen !== undefined && chosen !== current;
}

/** Запись в том виде, в каком её показывает окно выбора.
 *
 * Подпись приходит готовой (`line`), а не собирается здесь: как называется
 * человек и как компания, знают их собственные модули, и второе написание
 * разошлось бы с первым — один и тот же человек читался бы как двое разных.
 *
 * Снимка может не быть вовсе — у компании его нет никогда, — но поле остаётся:
 * строка выбора одна на оба предмета, и разбирать в ней два разных набора полей
 * значило бы держать две строки вместо одной.
 */
export function candidate({ id, icon, avatar = null, line, count, blocked }) {
  return { id, icon, avatar, ...line, count, blocked };
}
