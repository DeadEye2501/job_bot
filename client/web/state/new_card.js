// Заведение новой карточки: чем она зовётся и чем заслонена.
//
// Форма одна, а окон два — «Добавить» в контактах и заведение на ходу из
// подборщика при вакансии, — и это сказано на мосту прямым текстом
// (`client/bridge/hr.py`, `companies.py`). Мостовая половина сведена там в одно
// тело, поля — в общие наборы, заслон пустого имени — в `people.js` и
// `companies.js`. Не сведена была обвязка, и она разъехалась: у человека
// заголовок «Новый человек» против «Новый HR», слово об удаче «Карточка
// заведена» против «Человек заведён», у компании значок `domain_add` против
// `add_business` и подсказка поиска, называвшая одно и то же поле то доменом,
// то сайтом.
//
// Поле у компании ищется одно и то же в обоих окнах — название, сайт и
// написания (`backend/repository/companies_list.py`), — поэтому подсказка тут
// одна и названа по колонкам, а не по тому, как их зовут в разговоре.

import { blankCompany, companyNamed } from './companies.js';
import { blankPerson, named } from './people.js';
import { atHandle } from './telegram.js';
import { blankVacancy, typed, vacancyNamed } from './vacancies.js';

// Окна об одном поле — ник канала, адрес сайта, контакт вакансии: черновик
// строкой, и пустая строка ничего не называет. Отказ моста у них остаётся в
// окне (`contact_adding`): это почти всегда опечатка в набранном.
const ONE_FIELD = { blank: () => '', named: (draft) => Boolean(draft.trim()) };

/** Обвязка формы заведения по роду карточки.
 *
 * `named` держится рядом с `blank` нарочно: пустой черновик и заслон, который
 * решает, что он уже не пустой, — две половины одного правила, и разъехавшись,
 * они дали бы кнопку, открытую над формой, которую мост отобьёт.
 */
export const NEW_CARD = {
  hr: {
    icon: 'person_add',
    title: 'Новый человек',
    busyLabel: 'Завожу…',
    done: () => 'Человек заведён',
    searchHint: 'Поиск по имени, @username...',
    blank: blankPerson,
    named,
  },
  company: {
    icon: 'domain_add',
    title: 'Новая компания',
    busyLabel: 'Завожу…',
    done: () => 'Компания заведена',
    searchHint: 'Поиск по названию, сайту, написаниям...',
    blank: blankCompany,
    named: companyNamed,
  },
  // Подсказки поиска у вакансии нет: поле над её списком подписано своим
  // экраном, а не формой заведения. Пустая строка тут была бы полем без
  // сегодняшнего потребителя.
  vacancy: {
    icon: 'post_add',
    title: 'Новая вакансия',
    busyLabel: 'Завожу…',
    // Слово по удаче зависит от способа: набранные поля ложатся в строку тут
    // же, а вставленный текст только уходит на разбор — и чем тот кончился,
    // скажет весть. Скажи окно «заведена» сразу, на повторе и на молчащей
    // модели человек прочёл бы подтверждение раньше отказа. У полей слово даёт
    // мост — и удаче, и повтору: строки при повторе нет, и сказать «заведена»
    // было бы неправдой.
    done: (draft, answer) => (typed(draft) ? '' : answer.message),
    blank: blankVacancy,
    named: vacancyNamed,
  },
  // Слово по удаче называет то, что ответил мост, а не набранное: ник и адрес
  // он приводит к своему написанию, и человек должен увидеть, что легло.
  channel: {
    ...ONE_FIELD,
    title: 'Добавить канал',
    placeholder: '@username канала или t.me/...',
    hint: 'Название и аватар подгрузятся из Telegram автоматически.',
    done: (_draft, answer) =>
      answer.created
        ? `Канал добавлен: ${atHandle(answer.username)}`
        : `Канал ${atHandle(answer.username)} уже был заведён`,
  },
  aggregator: {
    ...ONE_FIELD,
    title: 'Добавить агрегатор',
    placeholder: 'example.com или https://...',
    hint: 'После добавления войдите на сайт — без входа агрегатор не включить.',
    done: (_draft, answer) =>
      answer.status === 'created'
        ? `Агрегатор добавлен: ${answer.aggregator.host}`
        : `${answer.aggregator.host} уже был заведён`,
  },
  // О контакте слова нет: он сразу появляется в списке карточки.
  contact: {
    ...ONE_FIELD,
    title: 'Добавить контакт',
    placeholder: 'Почта, ссылка или телефон',
    hint: 'Контакт для отклика вне Telegram: почта, страница вакансии, форма или телефон.',
    done: () => '',
  },
};
