// Отметка открытой записи: какую запись открыть, если она пришла со стороны,
// и какую открытую отдать наружу.
//
// Своим объявлением, а не четырьмя строками в каждой вкладке: так открывают
// четыре — каналы, компании, людей и вакансии, — и написаны они были дословно
// одинаково.

import { untrack } from 'svelte';

/** Отметка открытой записи — та же, что ставят соседние экраны; `where` —
 *  где запись живёт (вкладка контактов). Закрытая карточка — пусто. */
export function markOf(id, where = {}) {
  return id === null ? null : { ...where, id };
}

/** Сказать наружу, чья карточка открыта. Зовётся из эффекта, следящего за
 *  открытой записью.
 *
 * Получатель зовётся вне слежения: он запоминает отметку, читая свою память,
 * и прочитанное внутри эффекта стало бы его зависимостью — запись памяти
 * заново заводила бы эффект, и так без конца.
 */
export function tellOpened(id, onchosen) {
  untrack(() => onchosen(id));
}

/** Принять отметку и погасить её.
 *
 * Отметку ставят соседние экраны: воронка каналов в статистике, карточка
 * вакансии, вкладка компании. Без отметки не трогают ничего — вкладку
 * открывают и просто так.
 *
 * Гасится она сразу, а не по закрытии карточки: непогашенная открыла бы её
 * заново, и человек, закрывший карточку, читал бы это как поломку.
 */
export function takeOpened(mark, show, onopened) {
  if (!mark) return;
  show(mark.id);
  onopened();
}
