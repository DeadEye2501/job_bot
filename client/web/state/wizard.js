// Мастер первого запуска: куда он ведёт, что уже пройдено и что не пускает
// дальше.
//
// Чистые функции: пройденное приходит доводом с моста, наружу уходят отметки и
// фразы. Ни моста, ни разметки этот файл не знает.

/** Экраны по порядку. Приветствие и финал — обложки: шага у них нет, и в
 *  строке шагов они ничего не подсвечивают. */
const SCREENS = ['welcome', 'telegram', 'chat', 'embed', 'cv', 'done'];

/** Шаги в строке прогресса. Номер — тот, каким его считает мост
 *  (`wizard.state` отдаёт пройденные номерами). */
const STEPS = [
  { screen: 'telegram', at: 1, label: 'Telegram' },
  { screen: 'chat', at: 2, label: 'LLM' },
  { screen: 'embed', at: 3, label: 'Сравнение' },
  { screen: 'cv', at: 4, label: 'Резюме' },
];

/** Следующий экран мастера или ничего, если это последний. */
export function nextScreen(screen) {
  const at = SCREENS.indexOf(screen);
  return at === SCREENS.length - 1 ? null : SCREENS[at + 1];
}

/** Предыдущий экран или ничего.
 *
 * С финала назад не ведёт: сделанное уже записано, и возвращаться некуда.
 */
export function backScreen(screen) {
  const at = SCREENS.indexOf(screen);
  return at <= 0 || screen === 'done' ? null : SCREENS[at - 1];
}

/** Номер шага у экрана, либо ничего у обложек.
 *
 * По нему мастер отмечает пройденное: экран, с которого ушли вперёд, ложится
 * отметкой в строку шагов.
 */
export function stepAt(screen) {
  return STEPS.find((one) => one.screen === screen)?.at ?? null;
}

/** С какого экрана продолжать мастер, брошенный на середине.
 *
 * Мастер проходят не за один присест, и заново он начинался бы с Telegram —
 * то есть с ещё одного запроса кода подтверждения, о риске которого мастер
 * предупреждает на своей же обложке.
 *
 * Пустое — это первый запуск, и начинается он с обложки: она объясняет, что
 * сейчас спросят и зачем. Пропуск в середине не засчитывается: шаги записаны
 * порознь, и модель бывает сохранена без учётной записи.
 */
export function resumeScreen(completed) {
  if (completed.length === 0) return 'welcome';
  const left = STEPS.find((one) => !completed.includes(one.at));
  // Всё позади, а установка не отмечена законченной: человек закрыл окно, не
  // нажав «Готово». Кнопка финала живёт на последнем шаге — там и стоим.
  return (left ?? STEPS[STEPS.length - 1]).screen;
}

/** Строка шагов: что пройдено, что проходят сейчас, что впереди.
 *
 * Тот, на котором стоят, подсвечен, даже если пройден: человеку сперва нужно
 * найти себя в строке, а уже потом — сколько осталось.
 */
export function stepMarks(completed, screen) {
  return STEPS.map((one) => ({
    label: one.label,
    // На приветствии строка стоит вся погашенная, цифрами: приглушённые
    // галочки вернувшегося читаются как шаги, куда его не пускают.
    mark:
      screen === 'welcome'
        ? ''
        : one.screen === screen
          ? 'active'
          : completed.includes(one.at)
            ? 'done'
            : '',
  }));
}

/** Что мастер предлагает сделать с файлом резюме.
 *
 * Подписи копируются с образца дословно — по ним человек и решает, чем эти три
 * случая различаются. У разбора к подписи дописано своё: сколько ждать и что
 * разобранное стоит перечитать.
 */
export function cvModes() {
  return [
    {
      id: 'parse',
      title: 'Разобрать через LLM и заполнить профиль',
      note:
        'Займёт около минуты. Автоматический разбор может допускать ошибки — ' +
        'проверьте анкету в разделе Профиль.',
      disabled: false,
    },
    {
      id: 'attach',
      title: 'Только прикрепить файл',
      note:
        'Файл сохранится в профиле. Навыки и опыт нужно будет заполнить вручную ' +
        'в разделе Профиль.',
      disabled: false,
    },
    {
      id: 'skip',
      title: 'Пропустить шаг',
      note: 'Резюме можно добавить позже в разделе Профиль.',
      disabled: false,
    },
  ];
}

/** Можно ли закончить шаг резюме.
 *
 * Без файла заканчивать нечем — мастер отправил бы пустой путь, и шаг завершился
 * бы ничем. Отказ от резюме называется прямо, отдельным выбором: так видно, что
 * шаг пропущен нарочно, а не забыт.
 */
export function cvReady({ mode, path }) {
  return mode === 'skip' || !!path;
}
