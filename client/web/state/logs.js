// Записи журнала, переведённые в то, что видно на экране: время, тон, отбор.
//
// Чистые функции: записи приходят доводами, наружу уходят строки и списки.
// Ни моста, ни разметки этот файл не знает.

/** Уровни на пилюлях — от беды к мелочи. Порядок постоянный: по нему человек
 *  метит в нужную пилюлю, не читая подписей.
 *
 *  `id` — то, что приходит в записи с питона; `tone` — имя цвета; значок
 *  лигатурой шрифта. `CRITICAL` своей пилюли не имеет: его накрывает `ERROR`. */
export const LEVELS = [
  { id: 'ERROR', label: 'ERROR', tone: 'error', icon: 'error', atFirst: true },
  { id: 'WARNING', label: 'WARN', tone: 'warn', icon: 'warning', atFirst: true },
  { id: 'INFO', label: 'INFO', tone: 'info', icon: 'info', atFirst: true },
  // Отладка при открытии погашена: в ней идёт поток опроса и разбора
  // оповещений, и с ней экран читается только по счётчику пилюли.
  { id: 'DEBUG', label: 'DEBUG', tone: 'debug', icon: 'bug_report', atFirst: false },
];

/** Пилюли, зажатые при открытии экрана. */
export const AT_FIRST = LEVELS.filter((one) => one.atFirst).map((one) => one.id);

/** Под какой пилюлей стоит запись этого уровня.
 *
 * `CRITICAL` своей пилюли не имеет и считается ошибкой: окно рисует их одним
 * цветом, и отдельная пилюля с единицей заставляла бы искать разницу, которой
 * человеку не показывают. Правило живёт здесь одно на всех — и цвет строки, и
 * отбор спрашивают его же.
 */
function pillOf(level) {
  return level === 'CRITICAL' ? 'ERROR' : level;
}

/** Время записи с долями секунды.
 *
 * До миллисекунд, потому что по журналу ищут порядок событий внутри одной
 * секунды: сборщик пишет сотнями за обход. Записи без времени остаются пустым
 * местом — полночь 1970 года человек принял бы за сбой часов.
 */
export function logTime(epochSec) {
  if (epochSec === null || epochSec === undefined) return '';
  const at = new Date(epochSec * 1000);
  const two = (number) => String(number).padStart(2, '0');
  const three = String(at.getMilliseconds()).padStart(3, '0');
  return `${two(at.getHours())}:${two(at.getMinutes())}:${two(at.getSeconds())}.${three}`;
}

/** Каким цветом показать уровень записи.
 *
 * Цвет берётся у той же пилюли, под которой запись стоит в отборе: разойдись
 * они, красная строка пряталась бы под погашенной жёлтой пилюлей.
 *
 * Незнакомый уровень приходит от чужой библиотеки и получает отладочный тон:
 * без запасного строка осталась бы вовсе без цвета и читалась бы как пропуск.
 */
export function levelTone(level) {
  return LEVELS.find((one) => one.id === pillOf(level))?.tone || 'debug';
}

/** Записи, которые проходят зажатые пилюли. */
export function shown(records, selected) {
  return records.filter((one) => selected.has(pillOf(one.level)));
}

/** Можно ли погасить эту пилюлю: последнюю зажатую не гасят.
 *
 * Погашены все — список пуст без всякой видимой причины, и человек читает это
 * как поломку журнала, а не как свой же отбор.
 */
export function mayHide(selected, id) {
  return !selected.has(id) || selected.size > 1;
}


const HUDDLE_MS = 200;

/** Сколько ждать, прежде чем перечитать журнал после вести о новой записи.
 *
 * Две цены складываются в одно число. Снизу — пачка: сборщик пишет сотнями
 * записей за обход, весть приходит на каждую, и без выдержки экран спросил бы
 * мост сотню раз за один обход.
 *
 * Сверху — сам мост: чаще раза в секунду он на этот вопрос отвечает отказом
 * (`refusals.LOGS_TOO_OFTEN`), а отказ у нас показывается плашкой. Спрашивай
 * экран чаще — и под нагрузкой человек читал бы не журнал, а поток плашек.
 * Сотня миллисекунд сверх секунды — на то, что секунду мост считает своими
 * часами, и посланный ровно в срок вопрос приходит к нему чуть раньше границы.
 */
export function askDelay(sinceLastAskMs) {
  return Math.max(HUDDLE_MS, 1100 - sinceLastAskMs);
}

/** Чем объяснить пустой экран — и объяснять ли вообще.
 *
 * Причины пустоты требуют разных действий: неспрошенного журнала надо
 * подождать, пустой буфер значит «ничего и не было», а спрятанное отбором
 * вернётся отпущенной пилюлей. Одна фраза на все три заставила бы гадать.
 */
export function emptyText({ loaded, total, showing }) {
  if (!loaded) return 'Загрузка…';
  if (showing > 0) return '';
  return total === 0 ? 'Логов пока нет' : 'Ничего не найдено';
}
