// Перечень записей анкеты — мест работы или проектов: что из него уезжает на мост.
//
// Чистые функции: перечень приходит доводом, наружу уходит посылка. Ни моста,
// ни разметки этот файл не знает.

/** Лежит ли запись уже в базе.
 *
 * Номера мало: его даёт мост, а вкладка себя после записи не перечитывает —
 * заведённая в этот заход запись живёт с пустым номером до конца визита, уже
 * будучи записанной. Отметку об уехавшей записи ставит сама вкладка, и без неё
 * опустошённое обязательное поле вычёркивало такую строку из посылки, а мост
 * стирал её молча вместе со всем, что в ней было.
 */
function stored(one) {
  return one.id !== null || Boolean(one.saved);
}

/** Что из перечня уедет на мост — и почему не уедет ничего.
 *
 * Отсеиваются только свежие недозаполненные записи: они ещё не в базе, и
 * пропустить их значит ничего не потерять, — а без отсева одна пустая запись
 * отменяла бы правки всех соседних, заполненных.
 *
 * Уже записанная не отсеивается никогда, чем бы её ни опустошили: мост
 * заменяет перечень целиком, и вычеркнутая из посылки была бы стёрта из базы
 * молча. Про такую говорим сами (`complaint` с её номером) и не отправляем
 * ничего — так номер считается по тому списку, который человек видит, а не по
 * укороченной посылке.
 */
export function recordsGoing(rows, ready, complaint) {
  const going = rows.filter((one) => stored(one) || ready(one));
  const at = going.findIndex((one) => !ready(one));
  if (at === -1) return { going, trouble: '' };
  return { going: [], trouble: complaint(rows.indexOf(going[at]) + 1) };
}
