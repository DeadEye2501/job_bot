// Отложенная запись набранного: когда пора отправлять, а когда молчать.
//
// Своим модулем, а не в карточке: так правятся два разных поля — заметка к
// вакансии и пояснение к переходу, — а правила у них одни, и второе их
// написание разошлось бы с первым молча.

// Пробельное и пустое — одно и то же: мост сводит заметку из пробелов к
// пустоте и отвечает пустотой. Не сравняй мы их здесь, каждая пауза слала бы
// один и тот же вопрос заново, без конца.
function same(one, other) {
  return (one.trim() ? one : '') === (other.trim() ? other : '');
}

/** Заводит отложенную запись поля.
 *
 * Пауза считается от последнего знака: запись на каждый знак послала бы мосту
 * по вопросу на букву, а отсчёт от первого отправлял бы недописанное.
 */
export function autosave({ delay, save }) {
  let timer = null;
  let typing = null;
  let stored = '';

  function stop() {
    if (timer === null) return;
    clearTimeout(timer);
    timer = null;
  }

  function send() {
    if (typing === null || same(typing, stored)) return;
    stored = typing;
    save(typing);
  }

  return {
    /** Что лежит в базе сейчас. Приходит с ответом моста и с перечитанной
     *  карточкой: без него уход из нетронутого поля записал бы то же самое. */
    known(value) {
      stored = value ?? '';
    },
    /** Набранное человеком: уедет, когда он остановится. */
    typed(value) {
      typing = value ?? '';
      stop();
      timer = setTimeout(() => {
        timer = null;
        send();
      }, delay);
    },
    /** Отправить немедленно: человек ушёл из поля или закрыл карточку, и
     *  ждать паузы уже нечего. */
    flush() {
      stop();
      send();
    },
  };
}
