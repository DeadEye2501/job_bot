// Чтение карточки правой панели: свежая запись или слово о беде.
//
// Своим объявлением, а не в каждой карточке: так читают три — человека,
// компании и канала, — и написаны они были дословно одинаково: тот же отбой
// устаревшего, то же слово о неудаче. Расходятся такие копии на мелочи: одна
// не снимает прежнюю беду, и строка отказа висит поверх живых данных.
//
// Сам отбой общий (`fresh.stillNeeded`); здесь только то, чем эти три
// отличаются от прочих читающих, — им мало пустоты, им надо отличить отказ
// моста от ушедшего экрана.

import { stillNeeded } from './fresh.js';

/** Заводит чтение карточки.
 *
 * `trouble` — чем назвать неудачу: «карточку», «компанию» и «канал» человек
 * читает по-разному, и общее слово посылало бы его не туда.
 *
 * `alive` спрашивают, а не передают значением: панель закрывают, пока ответ в
 * пути, и класть его тогда уже некуда.
 *
 * `ask` принимается обёрткой, а не самим доводом: довод читается один раз, при
 * заведении, и подмена его сверху сюда бы не доехала.
 *
 * Показанное отдаётся парой — карточка и слово о беде разом: положи их
 * карточка порознь, третье состояние («ответ негоден, не трогать ничего»)
 * пришлось бы разбирать в каждой из трёх, и одна опять разобрала бы иначе.
 *
 * `show` кладёт эту пару в состояние карточки. Через довод, а не ответом:
 * ответ разбирали три карточки, и разбор был у них дословно один — проверка
 * на негодность и распаковка пары. Своими у них остаются только имена полей,
 * а имя подставить за карточку нельзя.
 */
export function cardRead({ ask, method, trouble, alive, show }) {
  const needed = stillNeeded(alive);

  /** Прочитать карточку и показать прочитанное; негодный ответ не кладётся. */
  return async function read(id) {
    const got = await needed(() => ask(method, id));
    if (got === null) return;
    const now = got.now;
    // Отказ не запирает панель на «Загрузка…»: человеку нужно хотя бы перейти к
    // соседней записи, а плашку он уже увидел.
    //
    // Прежняя беда снимается свежим ответом: строка отказа, оставшаяся поверх
    // живых данных, читается как беда, которой уже нет.
    show(now === null ? { card: null, trouble } : { card: now, trouble: '' });
  };
}
