// Компания, переведённая в то, что видно в списке и в шапке её карточки.
//
// Про страницы этого списка знает сосед `paging.js` — там правило общее для
// всех списков, здесь только про компанию. Люди в карточке компании названы
// `people.js`: имя человека одинаково во всех списках контактов, и второе
// его написание разошлось бы с первым.
//
// Чистые функции: строки моста приходят доводами, наружу уходят строки. Ни
// моста, ни разметки этот файл не знает.

// Начало адреса до двоеточия — то, что притворяется схемой.
const SCHEME = /^([a-z][a-z0-9+.-]*):\/*/i;

/** Чем подписать компанию в списке.
 *
 * Имя — сверху, сайт и алиасы — под ним: по имени компанию узнают, по
 * домену различают. Две «Ромашки» с разными сайтами — разные компании, и без
 * второй строки они неотличимы.
 *
 * Имени может не быть — оно приходит из объявления, — и тогда компания названа
 * номером: показать нечего, но строка должна остаться нажимаемой.
 */
export function companyLine(company) {
  const parts = [];
  if (company.website) parts.push(company.website);
  if (company.aliases.length) parts.push(`алиасы: ${company.aliases.join(', ')}`);
  return {
    name: company.name || `Компания #${company.id}`,
    sub: parts.length ? parts.join(' · ') : 'без сайта',
  };
}

/** Компания в том виде, в каком её показывает окно выбора.
 *
 * Снимка у компании нет вовсе — на его месте всегда значок, — но поле остаётся:
 * строка выбора одна на оба предмета, и разбирать в ней два разных набора полей
 * значило бы держать две строки вместо одной.
 */
export function companyCandidate(company) {
  return {
    id: company.id,
    icon: 'domain',
    avatar: null,
    ...companyLine(company),
    count: company.vacancy_count,
    blocked: company.is_blacklisted,
  };
}

/** Адрес, по которому открывают сайт компании.
 *
 * Домен приходит из чужого объявления, вынутый оттуда моделью, — доверия ему
 * нет. Наружу уходит только http(s): всё прочее, включая `javascript:` и
 * `file:`, переписывается на обычный адрес вместе со своей схемой. Голый домен
 * без схемы система открыла бы как файл рядом со страницей, поэтому схему
 * дописываем и ему.
 */
export function siteHref(website) {
  const text = (website || '').trim();
  if (!text) return null;
  if (/^https?:\/\//i.test(text)) return text;
  const bare = text.replace(/^\/*/, '');
  const scheme = SCHEME.exec(bare);
  // Точка в «схеме» выдаёт порт: у настоящей схемы точек не бывает, а
  // `example.com:8080`, принятый за схему, оставил бы от адреса один порт.
  const rest = scheme !== null && !scheme[1].includes('.') ? bare.slice(scheme[0].length) : bare;
  return `https://${rest}`;
}
