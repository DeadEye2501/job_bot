// Окно «Добавить вакансию»: способы заведения, черновик, правила заявки и
// приём её итога.
//
// Отдельно от строки списка (`vacancies.js`): там вакансия уже заведена и её
// показывают, здесь её только собираются завести.
//
// Чистые функции, кроме приёма итога (`settleHandMade`): он сбрасывает
// черновик в держателе оболочки, потому что держатель и есть то, что окно
// помнит между открытиями.

import { sourceBlock, sourceToggle } from './sources.js';

/** Способы завести вакансию руками: набрать поля самому, отдать боту текст
 * или ссылку на объявление.
 *
 * Значение решает, каким слотом уедет набранное (`NewVacancy`): поля ложатся в
 * строку как есть, текст и ссылка идут в конвейер на разбор. Словом «сторона»
 * на этом экране зовут другое — связь вакансии с компанией и человеком.
 */
export const VACANCY_MODES = [
  { value: 'fields', label: 'Поля' },
  { value: 'text', label: 'Текст' },
  { value: 'link', label: 'Ссылка' },
];

/** Пустой черновик формы заведения вакансии руками.
 *
 * Ключи — те же, что читает мост (`bridge/form_payloads.read_new_vacancy_fields`),
 * кроме служебных: способ заведения и текст вставки колонками не являются и
 * уезжают вторым слотом. Разъедься имена, набранное уехало бы в пустоту, и
 * человек узнал бы об этом только по пустой карточке.
 *
 * Грейд и формат пусты, а не выставлены первым значением ряда: в объявлении
 * их называют не всегда, а подставленный «junior» соврал бы про вакансию и
 * увёл бы её из выдачи по грейду.
 *
 * У компании и человека полей по два: номер карточки уезжает на мост, имя
 * стоит в поле с подсказкой. Одним не обойтись — мост связывает вакансию по
 * номеру, а человек набирает слова, и незнакомое имя номера ещё не имеет.
 */
export function blankVacancy() {
  return {
    // Открыт тот способ, где человек набирает поля сам: он работает и без
    // поднятого бота, а разбор текста без него невозможен вовсе.
    mode: 'fields',
    raw_text: '',
    posted_at: '',
    title: '',
    company_id: null,
    company_name: '',
    hr_id: null,
    hr_name: '',
    source_url: '',
    grade: '',
    remote: '',
    salary_min: '',
    salary_max: '',
    salary_currency: '',
    country: '',
    city: '',
    // Стек двумя половинами: по ним считается балл, и весят они по-разному —
    // требование незнакомого опускает вакансию, названное плюсом не стоит
    // ничего. Одним списком набранное разошлось бы с тем, как считает бот.
    stack_required: [],
    stack_preferred: [],
    description: '',
    notes: '',
  };
}

/** Черновик без служебного — то, что уезжает слотом полей.
 *
 * Способ заведения и текст вставки колонками записи не являются: мост читает
 * нагрузку поимённо и их не возьмёт, но и класть в неё то, чего в записи нет,
 * незачем — читающий нагрузку принял бы их за поля. Знание о том, какие ключи
 * служебные, живёт здесь же, где объявлен сам черновик.
 */
export function vacancyFields({ mode, raw_text, ...fields }) {
  return fields;
}

/** Отдают ли боту текст объявления вместо набранных полей.
 *
 * Сравнения с именами способов — по одному на весь фронт: написанное в каждом
 * месте своей рукой, оно молча переживёт переименование самого способа.
 */
export function isText(draft) {
  return draft.mode === 'text';
}

/** Отдают ли боту ссылку на объявление. Адрес лежит тем же полем черновика,
 *  что «Ссылка на объявление» у полей: вакансия у них одна. */
export function isLink(draft) {
  return draft.mode === 'link';
}

/** Пойдёт ли заявка через бота: текст и ссылку разбирает конвейер, а поля с
 *  откликом отдаются откликателю через место прогона. Поля без отклика ложатся
 *  в базу мимо бота. `handsOver` — видимое положение «Отклик при создании». */
export function viaBot(draft, handsOver) {
  return isText(draft) || isLink(draft) || handsOver;
}

/** Почему вакансию сейчас не завести; пусто — можно.
 *
 * Идущая через бота заявка подчиняется тому же правилу запора, что кнопки бота
 * (`sourceBlock`): ей нужны все системы и свободное место прогона. Мимо бота
 * заводится всегда.
 */
export function pasteLock(draft, handsOver, { running, lockedTip }) {
  if (!viaBot(draft, handsOver)) return '';
  return sourceBlock({ barred: '', running, lock: '', lockedTip });
}

/** Галочка «Отклик при создании»: как её показать и что из неё уходит мосту.
 *
 * Без живых систем она заперта и показана выключенной — заведение текстом
 * всё равно не пойдёт, а включённая обещала бы отклик, которого не будет; мосту
 * уходит видимое положение. Запомненное при этом не стирается: загорятся лампы —
 * галочка вернётся в него. Подсказка — пояснение или причина запора.
 */
export function handsOverToggle(handsOver, lockedTip) {
  const shown = sourceToggle({ active: handsOver, open: !lockedTip, lockTitle: lockedTip }, true);
  return { checked: shown.checked, disabled: shown.disabled, title: shown.title || HANDS_OVER_TITLE };
}

const HANDS_OVER_TITLE = 'Отклик при создании';

/** Принять итог ручного заведения: что с черновиком и куда перейти.
 *
 * Заведено или такая уже есть — набранное больше не нужно, и черновик
 * сбрасывается (`held` — держатель оболочки, `heldMemory().newVacancy`).
 * Неудача его оставляет: человеку есть что поправить и отправить снова.
 * Отметку «отдано боту» здесь не трогают — её снимает окно, которое знает,
 * летит ли ещё ответ на зов. Ответ — номер вакансии, к которой перейти (при
 * повторе), иначе пусто.
 */
export function settleHandMade(held, news) {
  if (news.outcome !== 'ok' && news.outcome !== 'duplicate') return null;
  held.draft = blankVacancy();
  return news.outcome === 'duplicate' ? news.vacancy_id : null;
}

/** Набрано ли то, без чего заводить нечего, — своё у каждого способа.
 *
 * Полям нужно название: им вакансию называют в списке, по нему её ищут, и без
 * него строка выглядит пустой. Тексту нужен сам текст, ссылке — адрес:
 * разбирать пустоту нечем. Правила держит и мост (`vacancies.create`,
 * `create_from_text`); здесь они стоят затем, чтобы окно не отправляло заведомо
 * отказной вопрос.
 */
export function vacancyNamed(draft) {
  if (isText(draft)) return Boolean(draft.raw_text.trim());
  if (isLink(draft)) return Boolean(draft.source_url.trim());
  return Boolean(draft.title.trim());
}
