// Необратимые действия над карточкой контакта: удалить и слить с другой.
//
// Своим объявлением, потому что карточек таких две — человек и компания, — и
// написаны эти два действия у них дословно одинаково: то же окно вопроса, тот
// же выбранный, тот же порядок гашения окон. Расходятся такие копии молча:
// погаси одна из них окно выбора до ответа моста, и отказ отправил бы человека
// искать выбранного заново.
//
// Про предмет карточки здесь не знают ничего: и удаление, и слияние приходят
// обёртками, уже знающими своё имя метода моста.

/** Заводит действия карточки над собой.
 *
 * `id` спрашивают, а не передают значением: панель одна на всю вкладку, и
 * карточку в ней переключают нажатием по соседней строке.
 */
export function cardActions({ id, dropCard, mergeCard }) {
  let asking = $state(null);
  let chosen = $state(null);

  return {
    /** Какое окно вопроса открыто: `'delete'`, `'merge'` или ничего. */
    get asking() {
      return asking;
    },
    set asking(what) {
      asking = what;
    },
    /** Выбранный в окне слияния — тот, в кого сливают. */
    get chosen() {
      return chosen;
    },
    set chosen(row) {
      chosen = row;
    },

    /** Удалить карточку. Окно гасим сразу: решение уже принято. */
    async drop() {
      asking = null;
      await dropCard(id());
    },

    /** Слить эту карточку в выбранную.
     *
     * Окно выбора гасим только по удаче: отказ оставляет выбранного под рукой,
     * а закрытое окно заставило бы искать его заново.
     */
    async merge() {
      const survivor = chosen;
      chosen = null;
      if (await mergeCard({ absorbed_id: id(), survivor_id: survivor.id })) asking = null;
    },
  };
}
