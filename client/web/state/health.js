// Здоровье систем, переведённое в решения: живо ли всё и что сказать человеку.
//
// Чистые функции: ответ моста приходит доводом, наружу уходит счёт и слова.
// Ни моста, ни разметки этот файл не знает.

import { OFF } from './modes.js';

// Таблица лампочек одна на всё: короткое имя под точкой и подсказка при
// наведении. Разложи их по двум файлам — и порядок с именами разойдутся первой
// же правкой.
const LAMPS = [
  ['db', 'DB', 'База данных'],
  ['tg', 'TG', 'Telegram-сессия'],
  ['chat', 'CHT', 'Чат-LLM'],
  ['embed', 'EMB', 'Embedding-LLM'],
];

const WAITING = 'Проверка состояния систем…';

/** Живо ли всё, на чём держится работа бота.
 *
 * По этому ответу отпираются тумблер режима и кнопка прогона, поэтому незнание
 * считается «не живо»: до первого ответа моста мы не знаем ничего, а отпертая
 * на миг раньше правды кнопка пускает обход каналов без модели.
 */
export function allAlive(health) {
  if (!health) return false;
  return LAMPS.every(([key]) => health[key] === true);
}

/** Имена того, что недоступно, — в постоянном порядке.
 *
 * Порядок постоянный нарочно: подсказку читают на запертой кнопке, и
 * перетасовка при каждом опросе делала бы её нечитаемой.
 */
export function downNames(health) {
  return LAMPS.filter(([key]) => !health?.[key]).map(([, name]) => name);
}

/** Чем объяснить человеку запертую кнопку.
 *
 * Пустой ответ и упавшая система — разные вещи: первое проходит за секунду
 * после запуска, и пугать списком «недоступно всё» там незачем.
 */
export function blockedTip(health) {
  if (!health) return WAITING;
  const down = downNames(health);
  if (down.length === 0) return '';
  return `Бот заблокирован: для запуска все системы должны быть доступны. Сейчас недоступно: ${down.join(', ')}.`;
}

/** Пора ли гасить бота: что-то отвалилось, а он ещё работает.
 *
 * Бот, работающий против мёртвой системы, крутит обороты впустую и копит
 * отказы, — а тумблер в этот миг уже заперт, и человек выключить его не может.
 *
 * Уже выключенного не гасят: часы здоровья бьют каждые пять секунд, и каждый
 * удар слал бы мосту одно и то же.
 */
export function shouldTurnOff(health, mode) {
  return !allAlive(health) && mode !== OFF;
}

export { LAMPS };
