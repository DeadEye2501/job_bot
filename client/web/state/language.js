// Язык приложения, полученный от моста.
//
// Своего значения окно не держит: язык задан один раз, на бэкенде
// (`APP_LOCALE` в `backend/domain/language_choice.py`), и приходит слотом
// `system.language` до того, как оболочка что-либо нарисует (`Shell.svelte`).

let locale;

/** Код языка приложения: по нему сортируются имена.
 *
 * Не принятый — ошибка, а не язык системы: сортировка по чужому языку
 * выглядит правильной и ничего не говорит о том, что язык не дошёл. */
export function appLocale() {
  if (locale === undefined) throw new Error('Язык приложения ещё не получен от моста.');
  return locale;
}

/** Принять язык приложения от моста. */
export function holdLocale(code) {
  locale = code;
}
