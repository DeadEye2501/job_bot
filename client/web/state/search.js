// Просеивание списка по набранному в поле поиска.
//
// Чистая функция: список и набранное приходят доводами, наружу уходит список.
// Ни моста, ни разметки этот файл не знает.

/** Что из списка остаётся видно под набранное.
 *
 * Пустое набранное оставляет список целым: поле поиска стоит над уже открытым
 * списком, и до первого знака резать нечего. Одни пробелы — то же самое: их
 * набирают между словами и стирают последними, и схлопнутый на них список
 * мигал бы под руками.
 *
 * Регистр не различается — человек набирает как придётся, а значения приходят
 * как записаны. Вхождением, а не началом строки: имена приходят с приставками
 * («qwen/qwen3-4b», «@ник · компания»), и отбор по началу прятал бы строку от
 * того, кто набирает её собственное имя.
 *
 * `text` называет, где искать: у строки списка полей несколько, и по какому из
 * них её вспоминают, знает не этот файл, а тот, кто её показывает.
 */
export function matching(items, typed, text = (one) => one) {
  const needle = typed.trim().toLowerCase();
  if (!needle) return items;
  return items.filter((one) => text(one).toLowerCase().includes(needle));
}
