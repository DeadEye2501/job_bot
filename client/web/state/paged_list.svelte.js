// Список, читающий себя страницами: чтение, поиск, догрузка и перечитывание.
//
// Своим объявлением, потому что таких списков два — люди и компании, — и
// написаны они были дословно одинаково: те же шесть полей состояния, те же
// четыре действия, тот же счёт попыток. Даже пояснения совпадали слово в
// слово. Расходиться такие копии начинают молча: у третьего списка, вакансий,
// уже появилась строка, которой нет у этих двух.
//
// Про предмет списка здесь не знают ничего: приходят имя метода моста и имя
// поля в ответе, а строки идут насквозь. Список вакансий сюда не сведён
// нарочно — он просит и получает сверх этого своё (порядок, отбор, границы
// оценки), и завёрнутый в общее, он потребовал бы ветвлений внутри.

import { attempts } from '$state/attempts.js';
import { appended, nearBottom, PAGE, refreshLimit } from '$state/paging.js';

/** Заводит список, читающий себя страницами.
 *
 * `ask` — обращение к мосту, `method` — имя метода, `key` — под каким именем
 * строки лежат в ответе. Обращение принимается обёрткой, а не самим доводом:
 * довод читается один раз, при заведении списка, и подмена его сверху сюда бы
 * не доехала.
 */
export function pagedList({ ask, method, key }) {
  let rows = $state([]);
  let hasMore = $state(false);
  let loaded = $state(false);
  let search = $state('');
  let loadingMore = $state(false);

  const tries = attempts();
  let alive = true;

  /** Перечитать список с начала.
   *
   * Потолок шлём всегда: у этих перечней на мосту умолчания нет вовсе, и без
   * потолка они отдали бы всех разом. Потолок при этом довод — перечитывают
   * список и после правки в карточке, где показанного больше страницы.
   */
  async function refresh(limit = PAGE) {
    const mine = tries.next();
    const now = await ask(method, { search, limit, offset: 0 });
    if (now === null || !alive || tries.stale(mine)) return;
    rows = now[key];
    hasMore = now.has_more;
    loaded = true;
  }

  /** Дочитать следующую страницу.
   *
   * Своей попытки не берёт: она объявила бы устаревшим уже идущее перечитывание,
   * а свежее как раз оно — в нём и поиск, и первая страница под него. Вместо
   * счёта сверяется само основание: тот ли поиск и тот ли список, к концу
   * которого страницу дописывают. Перечитывание кладёт другой список, и
   * дописывать доехавшую страницу становится некуда.
   */
  async function more() {
    const asked = search;
    const base = rows;
    const page = await ask(method, { search: asked, limit: PAGE, offset: base.length });
    if (page === null || !alive || search !== asked || rows !== base) return;
    rows = appended(rows, page[key]);
    hasMore = page.has_more;
  }

  return {
    get rows() {
      return rows;
    },
    get hasMore() {
      return hasMore;
    },
    get loaded() {
      return loaded;
    },
    /** Набранное в поиске. Пустой список без него читается как «никого нет», а
     *  с ним — как «по этому запросу никого нет», и это разные вести. */
    get search() {
      return search;
    },

    refresh,

    /** Искать по набранному, начав список заново. */
    find(text) {
      search = text;
      return refresh();
    },

    /** Перечитать, не схлопывая пролистанное.
     *
     * Зовут по вести о правке и после заведения записи: страницей перечитанный
     * список отбросил бы человека, стоящего на четвёртой сотне, в начало.
     */
    again() {
      return refresh(refreshLimit(rows.length));
    },

    /** Дочитать следующую страницу, когда список подошёл к концу.
     *
     * Прокруткой, а не кнопкой: список читают сверху вниз и глазами, а кнопка
     * посреди чтения заставляет целиться в неё мышью.
     */
    scrolled(event) {
      if (!hasMore || loadingMore || !nearBottom(event.currentTarget)) return;
      loadingMore = true;
      return more().finally(() => {
        loadingMore = false;
      });
    },

    /** Пометить список живым; отдаёт снятие пометки.
     *
     * Ответ, доехавший после ухода с вкладки, писать уже некуда: разметки нет,
     * а строки, положенные в снесённое состояние, всплывут при следующем
     * заходе вперемешку со свежими.
     */
    mounted() {
      alive = true;
      return () => {
        alive = false;
      };
    },
  };
}
