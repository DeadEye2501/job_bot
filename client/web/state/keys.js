// Кому из открытых окон достаётся нажатая клавиша и что она значит.
//
// Решение принимается здесь, а окно только зовёт и делает.

// Где Enter делает своё: в многострочном поле переносит строку, на кнопке
// нажимает её. Там окно его не перехватывает.
const OWN_ENTER = new Set(['TEXTAREA', 'BUTTON']);

// Открытые окна снизу вверх. Порядок несущий: последнее открытое и есть то,
// на которое человек сейчас смотрит.
const OPEN = [];

/** Чем нажатая клавиша отзовётся в окне: закрытием, подтверждением или ничем.
 *
 * Enter не подтверждает там, где делает своё: в многострочном поле заметку в
 * два абзаца иначе не набрать, а Enter на «Отмене» подтвердил бы обратное
 * нажатому.
 */
export function modalKey(event) {
  if (event.key === 'Escape') return 'close';
  if (event.key === 'Enter' && !OWN_ENTER.has(event.target?.tagName)) return 'confirm';
  return null;
}

/** Нажали ли на строке-кнопке ту клавишу, которой её нажимают.
 *
 * Строка, собранная на `<div>`, мышью нажимается сама, а с клавиатуры нет:
 * браузер шлёт ей только нажатие клавиши, и переводит его в нажатие строки
 * разметка. Разбор один на все такие строки — восемь копий разошлись бы первой
 * же правкой, и одна строка перестала бы отзываться на клавиатуру молча.
 */
export function pressKey(event) {
  return event.key === 'Enter';
}

/** Просит ли нажатие записать набранное немедленно.
 *
 * Поля с отложенной записью ждут паузы в наборе; Ctrl (или Cmd) с Enter — то
 * же самое, что уйти из поля, только не отрывая рук от клавиатуры.
 */
export function saveKey(event) {
  return event.key === 'Enter' && Boolean(event.ctrlKey || event.metaKey);
}

/** Отметить окно открытым; ответ — снятие отметки при закрытии.
 *
 * Окна встают друг на друга: слияние открывает подборщик поверх карточки, а
 * подтверждение — поверх подборщика. Слушают клавиатуру они все разом, и без
 * этой отметки один Escape закрыл бы всю стопку.
 */
export function opened(window_) {
  OPEN.push(window_);
  return () => {
    const at = OPEN.lastIndexOf(window_);
    if (at !== -1) OPEN.splice(at, 1);
  };
}

/** Отдать нажатие тому окну, которое сейчас наверху.
 *
 * Разбор один на все окна: пять диалогов повторили бы его пятью копиями и
 * разошлись бы первой же правкой.
 */
export function modalPress(event, window_, { close, confirm = null }) {
  if (OPEN.at(-1) !== window_) return;
  // Нажатие, уже разобранное тем, что стоит внутри окна, окну не достаётся:
  // Escape в наборе пилюли отменяет пилюлю, и доехав до окна, он закрыл бы
  // форму целиком — вместе со всем набранным.
  if (event.defaultPrevented) return;
  const said = modalKey(event);
  if (said === 'close') close();
  else if (said === 'confirm' && confirm) {
    // Обычное действие Enter гасится: браузер следом нажал бы то, что под
    // фокусом, — и кнопка, открывшая окно, открыла бы его снова.
    event.preventDefault();
    confirm();
  }
}
