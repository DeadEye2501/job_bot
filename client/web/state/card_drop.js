// Снос записи из правой панели: спросить мост, сказать человеку и закрыть
// панель.
//
// Своим объявлением, а не пятью строками в каждой карточке: так сносят четыре —
// канал, компанию, человека и вакансию, — и написаны они были почти дословно.
// «Почти» и есть довод: канал сносился молча, а три соседа говорили человеку.
// Молчание это разошлось не нарочно, и заметить его на месте было нечем.

/** Заводит снос записи.
 *
 * `note` — чем сказано о сносе: «Канал удалён» и «Вакансия удалена» человек
 * читает как вести о разных предметах, и общее слово посылало бы его гадать.
 *
 * Список зовут прежде закрытия: закройся панель раньше, снесённая строка
 * осталась бы под ней до следующего чтения списка.
 *
 * Отказ не закрывает панель и молчит: плашку об отказе человек уже увидел, а
 * закрытая панель поверх неё читается как «снесено».
 */
export function cardDrop({ ask, method, note, say, onchanged, onclose }) {
  return async function drop(id) {
    const done = await ask(method, id);
    if (done === null) return;
    say(note);
    onchanged();
    onclose();
  };
}
