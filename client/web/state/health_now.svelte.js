// Последний ответ моста о здоровье — общий для всего окна.
//
// Спрашивает его одна нижняя полоса, своими часами, а читают двое: сама полоса
// (лампочки и запертые кнопки) и экран настроек (запомненный замер скорости
// модели в плашке проверки). Спрашивай экран сам — к мосту шли бы двое часов
// с одним вопросом, и ответы у полосы и экрана расходились бы на миг.

let answer = $state(null);

/** Что известно о здоровье сейчас: ответ `system.health` или пусто до первого. */
export const healthNow = {
  get answer() {
    return answer;
  },
};

/** Запомнить свежий ответ моста о здоровье. */
export function keepHealth(fresh) {
  answer = fresh;
}
