// Режимы бота: перечень положений переключателя и выбор по месту нажатия.

/** Три положения слева направо. Порядок несущий: по нему считается, в какую
 *  треть дорожки попало нажатие. */
const MODES = ['Off', 'DM Only', 'Full'];

/** Выключенный режим — своим именем, а не «первым в перечне».
 *
 * Имена приходят с моста строками, и это единственное, которое окно называет
 * само: с него начинается нижняя полоса, пока мост не сказал настоящий.
 * «Первый в перечне» и «выключенный» — разные факты, и однажды они разойдутся.
 */
export const OFF = 'Off';

/** Что включит нажатие в треть дорожки — подсказкой при наведении: слова у
 *  переключателя нет, и режим без неё читается только по цвету бегунка. */
const MODE_HINTS = {
  Off: 'Выключить автоматику',
  'DM Only': 'Только приём сообщений от HR',
  Full: 'Вся автоматика: поиск, отклики, переписка',
};

/** Подсказка для места на дорожке; мимо неё — пусто. Трети те же, что у нажатия. */
export function modeHintAt(offsetX, width) {
  return MODE_HINTS[_modeAt(offsetX, width)] ?? '';
}

/** Какой режим выбрало нажатие: по месту на дорожке, а с клавиатуры — по кругу.
 *
 * Нажатие приходит разобранным — место относительно дорожки, её ширина и
 * `detail` события, — а не самим событием: разметки этот файл не знает, а
 * мерить дорожку умеет только она.
 *
 * Клавиатура узнаётся по `detail`: у нажатия по Enter он нулевой, места нет
 * вовсе, и выбирать по месту там нечего. Не различи мы их, отступ выходил бы
 * отрицательным, и с клавиатуры был бы доступен один «Off».
 *
 * Пустота значит «ничего не выбрано» — нажатие мимо дорожки; чем оно бывает,
 * сказано у `_modeAt`.
 */
export function modeChosen({ detail, offsetX, width }, current) {
  return detail === 0 ? _nextMode(current) : _modeAt(offsetX, width);
}

/** В какую треть дорожки попало нажатие — то и выбрано; мимо дорожки — ничто.
 *
 * Выбор по месту, а не перебором по кругу: положения три, и человек метит в то,
 * которое видит. Перебор заставлял бы его жать дважды, чтобы вернуться на шаг
 * назад.
 *
 * Мимо дорожки не выбрано ничего: «к ближнему краю» или перебор на месте
 * промаха были бы хуже молчания — промах поднимал бы выключенного бота, а
 * отправленного живому человеку письма не вернуть.
 */
function _modeAt(offsetX, width) {
  if (offsetX < 0 || offsetX > width) return '';
  if (offsetX < width / 3) return MODES[0];
  if (offsetX < (width * 2) / 3) return MODES[1];
  return MODES[2];
}

/** Следующее положение по кругу.
 *
 * Им ходят с клавиатуры: у нажатия по Enter места нет вовсе, и выбирать по
 * месту там нечего. Без него с клавиатуры был доступен один «Off» — отступ
 * выходил отрицательным, и до «DM Only» с «Full» было не добраться.
 */
function _nextMode(current) {
  return MODES[(MODES.indexOf(current) + 1) % MODES.length];
}
