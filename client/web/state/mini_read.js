// Чтение по номеру записи, у которого нужное лежит одним полем ответа.
//
// Своим объявлением, а не в каждой карточке: так читают вакансии компании,
// вакансии человека, людей компании и саму карточку вакансии — четыре тела,
// написанные дословно одинаково. Отличаются они именем метода, нагрузкой и
// полем ответа, то есть ровно тем, что и передаётся доводами.
//
// Карточки человека, компании и канала читаются не отсюда (`card_read`): у них
// на неудачу своё слово, и молчаливого «Загрузка…» им мало. Список карточки
// канала не сведён сюда тоже: он листается страницами и просит сверх этого
// своё — потолок и смещение.

import { freshAnswer } from '$state/fresh.js';

/** Заводит чтение по номеру записи.
 *
 * `payload` собирает нагрузку из номера записи: у компании это одно имя поля,
 * у человека другое, и подставить его за карточку нельзя.
 *
 * `show` кладёт пришедшее. Через довод, а не ответом: разбор ответа — проверку
 * на негодность и взятие поля — карточки вели одинаково, и своими у них
 * остаются только имена.
 */
export function miniRead({ ask, alive, method, payload, key, show }) {
  const fresh = freshAnswer(alive);

  /** Прочитать запись; негодный ответ не кладётся никуда. */
  return async function read(id) {
    const now = await fresh(() => ask(method, payload(id)));
    if (now === null) return;
    show(now[key]);
  };
}
