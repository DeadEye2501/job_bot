// Чтение списка, приложенного к карточке правой панели.
//
// Своим объявлением, а не в каждой карточке: так читают вакансии компании,
// вакансии человека и людей компании — три тела, написанные дословно
// одинаково. Отличаются они именем метода, нагрузкой и полем ответа, то есть
// ровно тем, что и передаётся доводами.
//
// Список карточки канала сюда не сведён: он листается страницами и просит
// сверх этого своё — потолок и смещение.

import { freshAnswer } from '$state/fresh.js';

/** Заводит чтение приложенного списка.
 *
 * `payload` собирает нагрузку из номера записи: у компании это одно имя поля,
 * у человека другое, и подставить его за карточку нельзя.
 *
 * `show` кладёт пришедшие строки. Через довод, а не ответом: разбор ответа —
 * проверку на негодность и взятие поля — три карточки вели одинаково, и
 * своими у них остаются только имена.
 */
export function miniRead({ ask, alive, method, payload, key, show }) {
  const fresh = freshAnswer(alive);

  /** Прочитать список; негодный ответ не кладётся никуда. */
  return async function read(id) {
    const now = await fresh(() => ask(method, payload(id)));
    if (now === null) return;
    show(now[key]);
  };
}
