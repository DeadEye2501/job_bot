// Люди, переведённые в то, что видно: имена, подписи, строка кандидата.
//
// Чистые функции: строки моста приходят доводами, наружу уходят строки и
// списки. Ни моста, ни разметки этот файл не знает.

import { candidate } from './picker.js';
import { handleName } from './telegram.js';

// Чем назван человек, которого назвать нечем. Прочерк, а не номер: строка
// стоит среди имён, и «Человек #7» человек принимает за имя. Номер остаётся
// там, где подпись обязана быть однозначной, — в подборщике и в чужой карточке.
const UNNAMED = '— без имени —';

/** Как назвать человека в чужой карточке.
 *
 * Безымянный назван номером: строка должна читаться, а не пустовать.
 */
export function personName(person) {
  return nameOrHandle(person.name, person.telegram_username, `Человек #${person.id}`);
}

/** Чем подписана строка списка непрочитанных переписок.
 *
 * Ник под именем стоит только тогда, когда есть и то и другое: сам по себе он
 * уже стоит на месте имени, и повторённый ниже занимал бы строку впустую.
 *
 * Безымянный назван здесь «HR #N», а не так, как зовёт его карточка: списком
 * над полосой человек выбирает, кому ответить, и номер тут единственное, чем
 * его отличить.
 */
export function unreadLine(row) {
  const handle = row.telegram_username ? `@${row.telegram_username}` : '';
  const name = (row.name || '').trim();
  return {
    name: nameOrHandle(name, row.telegram_username, `HR #${row.hr_id}`),
    sub: name && handle ? handle : '',
  };
}

/** Пустой черновик заведения человека.
 *
 * Своим объявлением, а не литералом у каждой формы: заводят его в трёх местах —
 * вкладка контактов, её же сброс после удачи и подборщик при вакансии, — и
 * поля там одни. Новый набор полей каждый раз: черновик правят на месте, и один
 * на всех принёс бы в следующее окно набранное в прошлом.
 */
export function blankPerson() {
  return { name: '', telegram_username: '', telegram_user_id: '', notes: '' };
}

/** Есть ли чем назвать человека, которого заводят руками.
 *
 * Хоть что-нибудь из трёх: имя, ник или номер учётной записи. Карточка,
 * названная одними заметками, не находится потом ни поиском, ни отправкой —
 * заметки не ссылаются на человека ничем, — и удалять её пришлось бы руками.
 * То же правило держит и мост (`bridge/form_payloads.hr_is_identified`); здесь
 * оно стоит затем, чтобы окно не отправляло заведомо отказной вопрос.
 */
export function named(draft) {
  return Boolean(
    draft.name.trim() || draft.telegram_username.trim() || draft.telegram_user_id.trim(),
  );
}

/** Ник и компания — обе половины подписи, под каким бы видом их ни показывали.
 *
 * Называются они всегда: пустое место читалось бы как недогрузившаяся строка, а
 * «без ника» тут говорящее — такого человека не найти в Telegram по имени, и
 * вспоминать его придётся по компании.
 *
 * Половинами, а не готовой строкой, потому что строка списка красит их порознь:
 * ник одним цветом, компанию другим. Слова при этом одни — собери их разметка
 * сама, один человек читался бы в списке и в подборщике как двое разных.
 */
export function personSub(person) {
  return {
    handle: handleName(person.telegram_username),
    company: person.last_company_name || 'без компании',
  };
}

/** Чем подписать человека в списке.
 *
 * Имя — сверху, ник и компания — под ним. Тёзок в переписке хватает: различают
 * их по нику, а вспоминают по компании, из которой человек писал последний раз.
 */
export function personLine(person) {
  const { handle, company } = personSub(person);
  return { name: personName(person), sub: `${handle} · ${company}` };
}

/** Чем подписан человек в строке списка: подпись и настоящее ли это имя.
 *
 * Ник заменяет имя: строка одна, и места под ник в ней нет. Безымянного зовут
 * прочерком, а по второму ответу подпись глушат серым — иначе прочерк читается
 * как имя.
 */
export function personTitle(person) {
  const named = Boolean(person.name || person.telegram_username);
  return { name: named ? personName(person) : UNNAMED, named };
}

/** Чем подписан человек в шапке своей карточки.
 *
 * Ник тут именем не считается: он стоит своей строкой ниже, и поставленный ещё
 * и сверху читался бы дважды.
 */
export function personHead(person) {
  return { name: person.name || UNNAMED, named: Boolean(person.name) };
}

/** Человек в том виде, в каком его показывает окно выбора.
 *
 * Подпись берётся тем же правилом, что и в списке: один и тот же человек,
 * названный в двух местах по-разному, читается как двое разных. Снимка может
 * не быть вовсе — тогда кружок сам поставит на его место буквы имени.
 */
export function personCandidate(person) {
  return candidate({
    id: person.id,
    icon: 'person',
    avatar: person.avatar ?? null,
    line: personLine(person),
    count: person.vacancy_count,
    blocked: person.is_blacklisted,
  });
}

/** Цепочка запасных имён: имя, за ним ник, за ним переданное последнее слово.
 *
 * Имя приходит из переписки и бывает пустым, ник есть почти всегда — по нему
 * человека и узнают в самом Telegram. Нет ни того ни другого (учётная запись
 * скрыла ник) — остаётся то, чем зовёт безымянного место показа: карточка и
 * список непрочитанных зовут его по-разному.
 */
function nameOrHandle(name, username, unnamed) {
  if (name) return name;
  if (username) return `@${username}`;
  return unnamed;
}
