// Выбранное человеком: наборы, которые он собирает нажатиями, и доля дорожки,
// на которой он ставит число.
//
// Приёмы общие — пилюли журнала, грейды анкеты, порог отбора, уровень навыка, —
// и живут они здесь, а не у первого, кто их завёл.

/** Какую долю дорожки залить под это значение.
 *
 * Зажато с обеих сторон: значение приезжает с моста и могло быть выставлено
 * до того, как предел назначили, — заливка шире дорожки выглядит поломкой, а
 * отрицательная не рисуется вовсе.
 */
export function fillPercent(value, top) {
  return (Math.max(0, Math.min(top, value)) / top) * 100;
}

/** Набор с переключённым значением: было — вычеркнуть, не было — добавить.
 *
 * Новый набор, а не правка прежнего: руны Svelte замечают присваивание, а не
 * правку внутри, и от `set.add` экран не перерисовался бы — человек жал бы и
 * не видел отклика.
 */
export function toggled(set, value) {
  const next = new Set(set);
  if (!next.delete(value)) next.add(value);
  return next;
}

/** Одно выбранное из ряда: нажатое повторно снимается.
 *
 * Парное `toggled`, только там, где значение одно, а не набор: у заводимой
 * руками вакансии грейд и формат по одному. Снимается тем же нажатием, потому
 * что в объявлении их называют не всегда, а поставленное по ошибке иначе
 * нечем убрать — соседнее значение соврало бы про вакансию не меньше.
 */
export function alone(current, value) {
  return current === value ? '' : value;
}

/** Набор без этого значения.
 *
 * Нужен там, где уходит сам предмет, а не отметка на нём: переключением такое
 * не снимешь — отсутствующее оно бы добавило. Отметка, пережившая свою запись,
 * достаётся следующей с тем же именем.
 */
export function without(set, value) {
  const next = new Set(set);
  next.delete(value);
  return next;
}
