// Действие, после которого карточки не остаётся: снос и слияние.
//
// Своим объявлением, а не пятью строками в каждой карточке: так кончают шесть —
// канал, компанию, человека и вакансию сносят, человека и компанию сливают, — и
// написаны они были почти дословно. «Почти» и есть довод: канал сносился молча,
// а соседи говорили человеку. Молчание это разошлось не нарочно, и заметить его
// на месте было нечем.

/** Заводит действие, кончающее карточку.
 *
 * `note` — чем сказано о случившемся: «Канал удалён» и «Карточки слиты» человек
 * читает как вести о разном, и общее слово посылало бы его гадать.
 *
 * Список зовут прежде закрытия: закройся панель раньше, снесённая строка
 * осталась бы под ней до следующего чтения списка.
 *
 * Отказ не закрывает панель и молчит: плашку об отказе человек уже увидел, а
 * закрытая панель поверх неё читается как «сделано».
 *
 * `held(done)` — не кончилось ли дело вопросом вместо действия: агрегатор с
 * откликами мост сперва не сносит, а называет их число. Такой ответ, как и
 * отказ, панель не закрывает.
 *
 * Отвечает, случилось ли: слияние по этому ответу гасит своё окно выбора, а по
 * отказу оставляет его открытым — выбранное в нём ещё нужно.
 */
export function cardFinish({ ask, method, note, say, onchanged, onclose, held = () => false }) {
  return async function finish(payload) {
    const done = await ask(method, payload);
    if (done === null || held(done)) return false;
    say(note);
    onchanged();
    onclose();
    return true;
  };
}
