// Одна летящая запись: набежавшие сводятся к последнему снимку.
//
// Своим объявлением, а не в каждой вкладке анкеты: так записываются три —
// анкета, навыки и места работы, — и все три отправляют перечень целиком.
// Мост заменяет им прежний, поэтому две записи в полёте это две замены, и в
// базе останется та, что доехала второй: снимок, собранный раньше, отменяет
// собранный позже. Правки поля идут чаще, чем ответы моста, и разъезд этот
// человеку не виден вовсе.
//
// Промежуточные снимки не отправляются: перечень уезжает целиком, и последний
// включает в себя все, что были до него.

/** Заводит запись, у которой в полёте не бывает двух снимков.
 *
 * `write` отвечает, а не бросает: отказ моста — обычное дело для анкеты, и все
 * трое зовущих ловят его у себя, каждый своими словами человеку.
 *
 * Отдаёт обещание, которое кончается вместе с отправкой снимка: на нём держится
 * и уход с вкладки — набранное должно успеть уехать.
 *
 * Кончается оно исходом последней уехавшей записи, а не своей: сведённый снимок
 * включает в себя все, что были до него, и «легло ли» — это про него.
 */
export function oneWrite(write) {
  let flying = null;
  let waiting = null;

  async function drain() {
    let answer;
    try {
      while (waiting !== null) {
        const payload = waiting;
        waiting = null;
        answer = await write(payload);
      }
    } finally {
      // И после отказа: недозаполненная анкета отказом и отвечает, а следом
      // человек дописывает поле и записывает снова.
      flying = null;
    }
    return answer;
  }

  return function push(payload) {
    waiting = payload;
    if (flying === null) flying = drain();
    return flying;
  };
}
