// Общее у источников вакансий — каналов и агрегаторов: числа воронки, общий
// выключатель над списком, строчный переключатель под ним и запоры. Правило
// запора (`sourceBlock`) общее для всех ручных действий бота.
//
// Своим файлом, а не частью каналов: агрегатор смотрят так же, как канал, и
// брать общее у соседа значило бы, что правка канала молча меняет агрегатор.
// Слова запоров знает род источника (`channels.js`, `aggregators.js`); здесь —
// их старшинство и то, как запертое и незапертое выглядит.
//
// Чистые функции: строки моста приходят доводами, наружу уходят строки и
// признаки. Ни моста, ни разметки этот файл не знает.

import { RUNNING } from './progress.js';

/** Чем заперто ручное действие бота; пусто — не заперто.
 *
 * Одно правило на кнопки источников, карточки вакансии и окно заведения.
 *
 * Отсев старше всего: обход кончится и лампа зажжётся сами, а запись в отсеве
 * сама не снимется. Дальше идущий обход — место прогона одно, и мост второй
 * прогон не пустит, — потом слова моста о том, чего не хватает, и погасшая
 * лампа. `barred` — слова отсева у этого рода, пусто — источник не в отсеве.
 */
export function sourceBlock({ barred, running, lock, lockedTip }) {
  if (barred) return barred;
  if (running) return RUNNING;
  return lock || lockedTip || '';
}

/** Подпись переключателя, запертого отсевом, — одна у канала и агрегатора.
 *
 * Слово в слово с отказом моста на то же включение (`refusals.py`): человек
 * читает одно и то же, нажал он запертый переключатель или прочёл подсказку.
 */
export const BLOCKED_TITLE = 'В чёрном списке — снимите запись, чтобы включить';

/** Подпись строчного переключателя при выключенном общем.
 *
 * Строчный при этом серый, но не заперт: нажимать его можно, и общий, включённый
 * снова, вернёт ровно то, что в строках стоит. Подпись говорит, почему включённый
 * всё равно серый, — иначе он читался бы поломкой.
 */
export const MASTER_OFF_TITLE = 'Общий выключатель выключен — обход не идёт';

/** Переключатель обхода в строке источника; `enabled` — общий выключатель.
 *
 * `open` — можно ли включить источник: незапертый показан так, как лежит в
 * базе, запертый — выключенным, каким бы он там ни лежал: обход его всё равно
 * пропустит, и включённый переключатель обещал бы работу, которой не будет.
 * `lockTitle` — чем заперт, словами рода.
 *
 * Приглушены все причины молчания, включая выключенный общий; своё положение
 * строка при нём держит — к нему общий и вернётся. Подпись только у запертого
 * и при выключенном общем: у остальных она объясняла бы то, что и так видно.
 */
export function sourceToggle({ active, open, lockTitle }, enabled) {
  const checked = active && open;
  return {
    checked,
    disabled: !open,
    dim: !checked || !enabled,
    muted: !enabled,
    title: open ? (enabled ? '' : MASTER_OFF_TITLE) : lockTitle,
  };
}

/** Общий выключатель над списком источников — каналов или агрегаторов.
 *
 * Не сводка строк, а свой выключатель поверх них: выключенный, он гасит обход
 * всех источников вида, но строк не трогает — включённый снова, он возвращает
 * ровно те, что были включены, и вспоминать их человеку не приходится.
 * `what` — чьих: «каналов», «агрегаторов».
 */
export function masterToggle(enabled, what) {
  return {
    checked: enabled,
    title: enabled ? `Выключить обход всех ${what}` : `Включить обход ${what}`,
  };
}

/** Числа источника: доли словом и признак того, что считать ещё нечего.
 *
 * Пустая статистика названа словами, а не нулями в столбиках: ноль читается
 * как «собрали и ничего не нашли», а источник, который ещё не обходили, об этом
 * и должен сказать.
 *
 * Доля, которой нет, — прочерк, а не ноль: у источника без откликов доля
 * ответов не нулевая, её просто не из чего считать.
 */
export function sourceStats(stats) {
  return {
    empty: !stats.total,
    fit: share(stats.fit_percent),
    apply: share(stats.apply_percent),
    response: share(stats.response_percent),
  };
}

/** Доля в процентах; неизвестная — прочерком, ноль читался бы как значение. */
export function share(percent) {
  return percent === null || percent === undefined ? '—' : `${percent}%`;
}
