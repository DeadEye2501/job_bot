// Чем зовут запись, которую назвать нечем, и как подпись отличает такую
// запись от названной.
//
// Одним объявлением на всех, потому что слово это стоит в одних и тех же
// списках рядом: у канала, у компании и у вакансии в чужой карточке.
// Написанное порознь, оно расходится, и одна и та же безымянная запись
// читается в двух строках одного списка по-разному.
//
// Прочерк, а не номер: строка стоит среди названий, и «Компания #7» человек
// принимает за название. Номер остаётся там, где подпись обязана быть
// однозначной, — в подборщике.
//
// Человек зовётся иначе (`people.js`): у него нет названия, у него имя, и
// довод, почему слово другое, записан там же.

/** Чем подписана запись без названия. Показывают её приглушённой
 *  (`styles/unnamed.css`) — так видно, что это не название, а его отсутствие. */
export const UNNAMED = '— без названия —';

/** Подпись записи и настоящее ли это имя: по второму ответу подпись глушат.
 *
 * `missing` — чем звать безымянную; у человека слово своё (`people.js`).
 */
export function titled(name, missing = UNNAMED) {
  return { name: name || missing, named: Boolean(name) };
}
