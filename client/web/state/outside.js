// Закрытие всплывающего окошка нажатием мимо него.
//
// Своим объявлением, а не в каждом окошке: их семь — меню карточки,
// выпадающий список, календарь, два перечня, поле с подсказкой и выбор
// статуса, — и правило у них одно. Семь копий значат, что найденную однажды
// поправку придётся вносить семь раз, и одна копия её не получит.
//
// Тонкость, ради которой это и стоит держать в одном месте: «мимо» считается
// по узлу-обёртке, а не по самой панели. Кнопка, которой окошко открывают,
// панели не принадлежит — она её сосед. Считай панель своим узлом, и тот самый
// щелчок, что её открыл, дошёл бы всплытием до документа, где сторож уже
// висит, был бы сочтён «мимо» и закрыл окошко обратно. Снаружи это выглядит
// как не нажимающаяся кнопка.

/** Ставит сторожа «нажали мимо» и отдаёт его снятие.
 *
 * Отдаётся снятие затем, что зовут это из эффекта: он и вернёт его окну.
 *
 * Узла может ещё не быть — разметка привязывает его после первого показа, — и
 * до тех пор мимо не нажимают ни разу: окошка на экране нет.
 */
export function closeOnClickAway(node, close) {
  const away = (event) => {
    const root = node();
    if (root !== null && root !== undefined && !root.contains(event.target)) {
      close();
    }
  };
  document.addEventListener('click', away);
  return () => document.removeEventListener('click', away);
}

/** Тот же сторож, но живущий, только пока окошко открыто.
 *
 * Обвязка вокруг сторожа была написана девятью одинаковыми эффектами: тот же
 * заслон по признаку показа, тот же зов, тот же возврат снятия. Закрытому
 * окошку сторож не нужен — висел бы на документе всё время жизни экрана и
 * отзывался бы на каждое нажатие мимо.
 */
export function whileOpen(open, node, close) {
  if (!open) return undefined;
  return closeOnClickAway(node, close);
}
