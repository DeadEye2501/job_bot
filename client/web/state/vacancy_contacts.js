// Контакты вакансии, кроме Telegram-HR: куда ведёт нажатие на контакт.
//
// Чистые функции: значение контакта приходит доводом, наружу уходит адрес,
// который откроет система. Ни моста, ни разметки этот файл не знает.

import { siteHref } from './site.js';

// Схемы, с которыми контакт открывается как есть: письмо, звонок, Telegram.
// Ссылки на страницы идут через `siteHref` — там и http(s), и голый домен, и
// чужая схема, переписанная на обычный адрес.
const KEPT_RE = /^(mailto|tel|tg):/i;
const EMAIL_RE = /^[^\s@/]+@[^\s@/]+\.[^\s@/]+$/;
const PHONE_RE = /^\+?[\d\s()-]{6,}$/;

/** Адрес, по которому система откроет контакт: страницу, письмо или звонок.
 *
 * Вида контакта база не хранит — почту, телефон и ссылку видно по самому
 * значению, — и ссылку разбор кладёт так, как она написана в объявлении:
 * часто без схемы.
 */
export function contactHref(value) {
  const text = value.trim();
  if (KEPT_RE.test(text)) return text;
  if (EMAIL_RE.test(text)) return `mailto:${text}`;
  if (PHONE_RE.test(text)) return `tel:${text.replace(/[^\d+]/g, '')}`;
  return siteHref(text);
}
