// Цикл живых событий: спрашивает мост о новом и разводит его по подписавшимся.
//
// Своего ответа у этих вестей нет — страница о них не спрашивала, — и другого
// способа узнать про них у неё тоже нет: питон в браузер не лезет. Поэтому
// спрашивает она сама, а вопрос ждёт на той стороне.

const AFTER_TROUBLE_MS = 2000;

/** Слушатель вестей поверх зова, который спрашивает мост «что нового после N».
 *
 * Зов приходит доводом, а не берётся отсюда: так цикл проверяется без окна и
 * без моста вовсе, а другого способа его проверить нет — он бесконечен по
 * устройству.
 */
export function listener(ask) {
  const heard = new Map();
  // Пусто значит «номера ещё нет»: страница только открылась, и спрашивает она
  // с этого мига, а не с начала кольца. Спроси она с нуля — мост отдал бы всё
  // накопленное, и окно мигнуло бы плашками часовой давности как свежими.
  let seen = null;
  let alive = true;

  /** Подписаться на род вести; возвращает, чем отписаться.
   *
   * Отписка обязательна там, где экран уходит: оставленная подписка рисует в
   * разметку, которой уже нет, и держит её от уборки.
   *
   * Род `missed` — не весть бэкенда, а наша: им цикл говорит, что часть
   * случившегося выпала из кольца и её уже не будет. Кто по вести
   * подрисовывает, тот по потере перечитывает всё заново.
   */
  function on(kind, hear) {
    if (!heard.has(kind)) heard.set(kind, new Set());
    heard.get(kind).add(hear);
    return () => heard.get(kind)?.delete(hear);
  }

  /** Крутиться, пока очередь не закроется вместе с окном.
   *
   * Сорвавшийся вопрос цикла не убивает: один отказ моста — не повод замолчать
   * навсегда. Переждать при этом надо, иначе отказ, приходящий сразу, закрутил
   * бы цикл вхолостую на полной скорости.
   */
  async function run() {
    while (alive) {
      const news = await asked();
      // Проверяем ещё раз: вопрос ждёт на той стороне до двадцати пяти секунд, и
      // страница успевает уйти, пока он висит. Раздать её слушателям пачку,
      // пришедшую после ухода, значит рисовать в разметку, которой уже нет.
      if (news === null || !alive) continue;
      deliver(news);
      if (news.closed) return;
    }
  }

  /** Спросить мост, пережив его отказ. Пусто значит «спросим ещё раз».
   *
   * Переждать при этом надо: отказ, приходящий сразу, закрутил бы цикл
   * вхолостую на полной скорости — а приходит он именно так, когда моста уже
   * нет вовсе.
   */
  async function asked() {
    try {
      return await ask(seen);
    } catch (trouble) {
      console.warn('события: вопрос не прошёл', trouble);
      await pause(AFTER_TROUBLE_MS);
      return null;
    }
  }

  /** Раздать пачку подписавшимся, двигая отметку виденного.
   *
   * Отметка двигается по счёту моста, а не по последней вести: ответ по сроку
   * приходит пустым, и по вестям она застыла бы — а следующий вопрос снова
   * просил бы «с этого мига», теряя всё, что легло между ответом и вопросом.
   *
   * Потеря объявляется до самих вестей: по ней экран перечитывает всё заново,
   * и пришедшие следом вести лягут уже поверх свежего.
   */
  function deliver(news) {
    seen = news.at;
    if (news.missed) tell('missed', {});
    for (const one of news.events) tell(one.kind, one.payload);
  }

  /** Больше не спрашивать. Идущий вопрос при этом доживёт свой срок: отменить
   * его со страницы нечем, а ответ на него просто некому будет разбирать. */
  function stop() {
    alive = false;
  }

  function tell(kind, payload) {
    for (const hear of heard.get(kind) ?? []) {
      try {
        hear(payload);
      } catch (trouble) {
        // Упавший слушатель не должен уносить с собой соседей по роду: они
        // рисуют разные части экрана, и беда одного не делает других
        // неверными.
        console.error(`события: слушатель ${kind} упал`, trouble);
      }
    }
  }

  return { on, run, stop };
}

function pause(ms) {
  return new Promise((done) => setTimeout(done, ms));
}
