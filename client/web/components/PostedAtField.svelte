<script>
  // Дата публикации объявления: подпись и поле с сеткой месяца.
  //
  // Своим объявлением, потому что стоит она на обеих сторонах формы заведения
  // — и там, где поля набирают руками, и там, где вставляют текст. Написанные
  // порознь, две подписи разъехались бы молча, а человек читает их одну за
  // другой, переключая сторону нажатием.
  //
  // Из текста объявления дату не достать: у поста канала её знает Telegram, а
  // у объявления с биржи — только тот, кто его нашёл. Поэтому её и набирают.
  //
  // `up` — раскрыть сетку вверх; просит та сторона, под чьим полем места нет.
  //
  // Черновик правится на месте: он приходит своим объектом от того, кто его
  // потом и отправит.
  import DatePicker from './DatePicker.svelte';

  let { draft, up = false } = $props();
</script>

<div class="captioned-field">
  <div class="field-caption">Опубликовано:</div>
  <DatePicker value={draft.posted_at} {up} onpick={(iso) => (draft.posted_at = iso)} />
</div>
