<script>
  // Окно, которое что-то спрашивает: заголовок, содержимое и две кнопки.
  //
  // Общая рама для спрашивающих окон: так заводят человека, компанию и
  // вакансию — из списков контактов, из карточки вакансии, где связывать
  // оказалось не с кем, и над списком вакансий. Своё у каждого только то, что
  // внутри.
  //
  // Рама и прокрутка — общие с подборщиком (`narrow` в `modal.css`, тело в
  // `scroll-body.css`): полей в форме вакансии вдесятеро больше, чем у
  // человека, и в низком окне они не помещаются вовсе. Своей высоты и своей
  // прокрутки здесь нет нарочно — вторая такая пара разошлась бы с первой.
  //
  // `extra` — своё имя вида поверх общего: почему оно нужно форме вакансии,
  // сказано у самого правила (`modal.css`).
  //
  // `ready` — набрано ли то, без чего заводить нечего. Пока не набрано, кнопка
  // заперта: нажавший её иначе получает плашку отказа вместо карточки, и чего
  // не хватило — узнаёт уже из неё.
  //
  // `busy` — летит ли уже ответ моста. Второе нажатие ушло бы в начатую работу
  // и завело бы вторую карточку: сторожа на одинаковое имя нет ни в базе, ни на
  // мосту. Подпись на это время говорит, что работа идёт, — запертая кнопка без
  // объяснения читается как поломка.
  import ModalFoot from './ModalFoot.svelte';
  import ModalHead from './ModalHead.svelte';
  import ModalShell from './ModalShell.svelte';

  // Содержимое переименовано при разборе доводов: внутри рамы своё место для
  // разметки тоже зовётся `children`, и одно имя закрыло бы другое.
  let {
    icon,
    extra = '',
    title,
    confirmLabel,
    busyLabel,
    busy,
    ready,
    onconfirm,
    oncancel,
    children: inside,
  } = $props();
</script>

<!-- Окно берёт на себя Escape, но не Enter: в нём набирают заметки в несколько
     строк, и подтверждение по Enter обрывало бы заведение на первом же
     переводе строки. -->
<ModalShell extra="narrow {extra}" onclose={oncancel}>
  {#snippet children()}
    <!-- Шапка общая с прочими окнами, но без крестика: закрывают это окно
         «Отменой», и второй выход из него человек не просил. -->
    <ModalHead {icon} {title} />

    <div class="modal-body">
      {@render inside()}
    </div>

    <ModalFoot
      label={confirmLabel}
      {busyLabel}
      {busy}
      {ready}
      {oncancel}
      {onconfirm}
    />
  {/snippet}
</ModalShell>
