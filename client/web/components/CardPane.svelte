<script>
  // Правая панель, пока карточки ещё нет: слово о беде, ожидание или само
  // содержимое.
  //
  // Своим объявлением, а не тремя строками в каждой карточке: так открываются
  // человек, компания и канал, и разъехавшись, они по-разному отвечали бы на
  // одно и то же — на неотданную мостом карточку.
  //
  // Беда старше ожидания: отказ уже показан плашкой, и «Загрузка…» поверх него
  // читалась бы как «сейчас придёт».
  let { trouble, ready, children } = $props();
</script>

{#if trouble}
  <div class="empty-note cnt-detail-empty">{trouble}</div>
{:else if !ready}
  <div class="empty-note cnt-detail-empty">Загрузка…</div>
{:else}
  {@render children()}
{/if}
