<script>
  // Вторая сторона заведения: человек приносит текст объявления, а поля из
  // него достаёт конвейер — тем же разбором, каким читает пост канала.
  //
  // Своим объявлением рядом с полями вакансии, а не веткой внутри них: у форм
  // общего только черновик, и набор полей здесь ровно один — сам текст.
  //
  // Сетка календаря раскрывается вверх: поле стоит в самом низу окна, и вниз
  // ей некуда. Зачем дату вообще набирают, сказано у самого поля.
  //
  // Черновик правится на месте: он приходит своим объектом от того, кто его
  // потом и отправит.
  import PostedAtField from './PostedAtField.svelte';

  let { draft } = $props();
</script>

<textarea
  class="textarea grown"
  placeholder="Текст объявления"
  bind:value={draft.raw_text}
></textarea>

