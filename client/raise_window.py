"""Договор двух копий приложения о том, чьё окно показать человеку.

Работать второй копии не даёт замок (`backend/single_instance`), а объяснить ей
человеку нечего: в боевой сборке нет ни консоли, ни потока ошибок, и второе
нажатие на ярлык выглядело бы как «ничего не произошло». Поэтому вместо
объяснения вторая копия просит первую показать своё окно и уходит.

Разговор идёт по локальному сокету, и подключиться удаётся только к копии,
которая уже слушает. Слушать она начинает, когда окно есть, — до этого мига
поднимать нечего, и просьба пропадает. Щель эта настоящая: первая копия успевает
за неё проверить хранилище ключей и обновить схему базы. Человеку она видна как
«нажал второй раз, пока первое окно ещё не открылось» — и закрывается сама, как
только окно откроется.
"""

import hashlib
import logging
import sys

from PySide6.QtNetwork import QLocalServer, QLocalSocket

from config import APP_NAME, get_data_dir

logger = logging.getLogger(__name__)

# Столько ждём ответа на подключение. Секунда — с запасом: сокет локальный, и
# отвечает на нём живой процесс, а не сеть. На Windows это не потолок, а
# пожелание: подключение к занятому каналу система держит своим сроком, и он
# длиннее. Терпимо — ждёт при этом копия, которой всё равно предстоит уйти.
CONNECT_TIMEOUT_MS = 1000

# «Разрешаю кому угодно выйти на передний план» для Windows. Без этого система
# отклоняет чужой `SetForegroundWindow`, и окно первой копии только мигает в
# панели задач: право на передний план принадлежит той копии, поверх которой
# человек нажал ярлык, и передать его надо явно.
_ASFW_ANY = -1


def socket_name() -> str:
    """Имя сокета — своё у каждого каталога данных.

    Общее имя на машину развело бы замок и разговор: замок покаталожный, и две
    копии над разными каталогами он пускает нарочно. С общим именем они дрались
    бы за него — одна не смогла бы слушать вовсе.

    Каталог берётся отпечатком, а не как есть: в имя сокета не всякий путь
    годится — там есть и пробелы, и двоеточия, и предел длины.
    """
    home = hashlib.sha1(str(get_data_dir()).encode("utf-8")).hexdigest()[:12]
    return f"{APP_NAME}-{home}"


def listen(window, name: str | None = None) -> QLocalServer:
    """Слушать просьбы других копий и выводить по ним окно вперёд.

    Имя приходит доводом ради сторожей: боевой зов у объявления один и берёт
    умолчание, а двум сторожам в одном процессе нужны разные имена — иначе они
    слышали бы окна друг друга.

    Занятое имя снимается только после того, как занять его не вышло. Снимать
    сразу нельзя: вне Windows сокет остаётся файлом, и безусловный снос отобрал
    бы его у живой копии — той самой, которая на просьбы и отвечает. На Windows
    снос не пригождается вовсе: под одним именем система держит сколько угодно
    слушателей, и `listen` там не отказывает никогда.

    Сервер отдаётся наружу, потому что жив он ровно столько, сколько на него
    ссылаются: брось ответ — и слушать станет некому.
    """
    name = name or socket_name()
    server = QLocalServer()
    server.newConnection.connect(lambda: _bring_forward(server, window))
    if not server.listen(name):
        QLocalServer.removeServer(name)
        if not server.listen(name):
            logger.warning(
                "raise_window: не слушаем %s (%s)", name, server.errorString()
            )
    return server


def _bring_forward(server: QLocalServer, window) -> None:
    """Показать окно человеку, который нажал ярлык второй раз.

    Свёрнутое сперва разворачивается: поднимать свёрнутое бесполезно, оно так
    и останется в панели задач. Фокус берётся отдельно от подъёма — без него
    окно всплывёт, а ввод останется у той программы, поверх которой нажали.
    """
    conn = server.nextPendingConnection()
    if conn is not None:
        conn.disconnectFromServer()
        # Принятые подключения принадлежат серверу и живут до его смерти:
        # без этого каждый второй запуск оставлял бы за собой по объекту.
        conn.deleteLater()
    if window.isMinimized():
        window.showNormal()
    window.raise_()
    window.activateWindow()


def _let_the_other_copy_come_forward() -> None:
    """Отдать право на передний план — иначе окно первой копии только мигнёт.

    Только Windows: на прочих системах права переднего плана так не устроены,
    и отдавать нечего.
    """
    if sys.platform != "win32":
        return
    import ctypes

    try:
        ctypes.windll.user32.AllowSetForegroundWindow(_ASFW_ANY)
    except (AttributeError, OSError):
        logger.exception("raise_window: не отдать право на передний план")


def ask_to_raise(name: str | None = None) -> bool:
    """Попросить уже открытую копию показать своё окно; сказать, дошло ли.

    Отказ значит «слушать некому»: первая копия ещё не дошла до окна либо уже
    его закрыла, а замок отпустить не успела. Зовущему он сегодня ничего не
    меняет — уйти ему в любом случае, — и нужен сторожам, которые иначе не
    отличили бы переданную просьбу от потерянной.
    """
    name = name or socket_name()
    _let_the_other_copy_come_forward()
    client = QLocalSocket()
    client.connectToServer(name)
    if not client.waitForConnected(CONNECT_TIMEOUT_MS):
        return False
    client.disconnectFromServer()
    return True
