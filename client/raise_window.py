"""Договор двух копий приложения о том, чьё окно показать человеку.

Работать второй копии не даёт замок (`backend/single_instance`), а объяснить ей
человеку нечего: в боевой сборке нет ни консоли, ни потока ошибок, и второе
нажатие на ярлык выглядело бы как «ничего не произошло». Поэтому вместо
объяснения вторая копия просит первую показать своё окно и уходит.

Разговор идёт по петлевому сокету (`127.0.0.1`), и подключиться удаётся только
к копии, которая уже слушает. Слушать она начинает, когда окно есть, — до этого
мига поднимать нечего, и просьба пропадает. Щель эта настоящая: первая копия
успевает за неё проверить хранилище ключей и обновить схему базы. Человеку она
видна как «нажал второй раз, пока первое окно ещё не открылось» — и закрывается
сама, как только окно откроется.

Взят именно `socket` из стандартной библиотеки, а не именованный канал и не
`multiprocessing.connection`. Именованных сокетов на все системы не выходит:
`AF_UNIX` в сборке Python под Windows нет вовсе, а `AF_PIPE` есть только там, и
любой из них потребовал бы двух разных путей вместо одного.
`multiprocessing.connection` эту развилку прячет, но приносит свой срок
ожидания подключения — двадцать секунд, которых зовущему не задать, — а ждёт
всё это время человек, нажавший ярлык. Петлевой сокет одинаков везде, срок
ожидания на нём наш, и наружу машины он не выходит.

Платой за это выбран порт вместо имени: адрес у сокета числовой, и имя в него
не положить. Порт выводится из имени, поэтому остаётся покаталожным, как и
замок, — но занять его до нас может кто угодно. Поэтому имя всё равно
произносится вслух: зовущий говорит его в сокет, слушающий отвечает только на
своё, и чужой на нашем порту за открытую копию не сойдёт.
"""

import hashlib
import logging
import socket
import socketserver
import sys
import threading

from config import APP_NAME, get_data_dir

logger = logging.getLogger(__name__)

LOOPBACK = "127.0.0.1"

# Столько ждём ответа на подключение. Секунда — с запасом: сокет петлевой, и
# отвечает на нём живой процесс, а не сеть. Тем же сроком ограничено и чтение
# приветствия на слушающей стороне: подключившийся молча не должен занимать
# слушателя дольше, чем занял бы его настоящий зовущий.
CONNECT_TIMEOUT_S = 1.0

# Порт берётся из частного диапазона, но ниже эфемерного: случайные порты
# система раздаёт из 49152–65535 (Windows) и 32768–60999 (Linux), и попасть в
# них значило бы делить порт с кем попало при каждом втором запуске.
_PORT_FIRST = 20000
_PORT_COUNT = 10000

# Чем слушающий отвечает на своё имя. Ответ нужен затем же, зачем приветствие:
# без него «дозвонился» значило бы всего лишь «на порту кто-то есть».
_ACK = b"1"

# «Разрешаю кому угодно выйти на передний план» для Windows. Без этого система
# отклоняет чужой запрос на передний план, и окно первой копии только мигает в
# панели задач: право на передний план принадлежит той копии, поверх которой
# человек нажал ярлык, и передать его надо явно.
_ASFW_ANY = -1


def socket_name() -> str:
    """Имя сокета — своё у каждого каталога данных.

    Общее имя на машину развело бы замок и разговор: замок покаталожный, и две
    копии над разными каталогами он пускает нарочно. С общим именем они дрались
    бы за него — одна не смогла бы слушать вовсе.

    Каталог берётся отпечатком, а не как есть: в имя сокета не всякий путь
    годится — там есть и пробелы, и двоеточия, и предел длины.
    """
    home = hashlib.sha1(str(get_data_dir()).encode("utf-8")).hexdigest()[:12]
    return f"{APP_NAME}-{home}"


def port_of(name: str) -> int:
    """Порт, на котором слушают под этим именем.

    Выводится из имени, потому что разговор покаталожный, а адреса у петлевого
    сокета числовые: разным именам нужны разные порты, иначе просьба к одной
    копии поднимала бы окно другой.
    """
    digest = hashlib.sha1(name.encode("utf-8")).digest()
    return _PORT_FIRST + int.from_bytes(digest[:4], "big") % _PORT_COUNT


class _RaiseHandler(socketserver.StreamRequestHandler):
    """Одно подключение: выслушать имя и, если оно наше, вывести окно вперёд."""

    timeout = CONNECT_TIMEOUT_S

    def handle(self) -> None:
        greeting = self.server.greeting
        try:
            said = self.rfile.read(len(greeting))
            if said != greeting:
                logger.warning("raise_window: подключение не нашим именем (%r)", said)
                return
            _bring_forward(self.server.window)
            # Ответ идёт последним: «передал» должно значить «показал», иначе
            # зовущий уходил бы с обещанием окна, которого не поднимали.
            self.wfile.write(_ACK)
        # Широко нарочно: обрыв подключения приходит `OSError`, а подъём окна
        # отвечает своей породой — pywebview ждёт показа окна и по сроку бросает
        # `WebViewException`. Ловить её по имени значило бы ввозить сюда
        # библиотеку окна ради одного `except`; а не поймать — уронить поток
        # слушателя, после чего вторую копию не услышит уже никто.
        except Exception:
            logger.exception("raise_window: просьба не доведена")


class _RaiseServer(socketserver.ThreadingTCPServer):
    """Слушатель просьб на порту одного имени.

    Ждёт подключений своим потоком: главный занят циклом окна. Каждое
    подключение обслуживается ещё одним потоком, и это не запас на нагрузку —
    подключений тут одно на нажатие ярлыка. Довод в другом: подъём окна у
    pywebview ждёт, пока окно покажется, и до первого показа ждёт двадцать
    секунд. На одном потоке эти двадцать секунд глохли бы для всех, кто
    постучится следом, — а стучится человек, уже нажавший ярлык дважды.

    Порт освобождается системой не сразу, и вне Windows брошенный умершей
    копией порт не дал бы занять себя следующему запуску — там это лечится
    `SO_REUSEADDR`. На Windows тот же флаг разрешает встать на живой чужой
    сокет: две копии над одним каталогом обе считали бы себя слушающими, а
    просьбы доставались бы одной из них наугад. Поэтому флаг — только не там.
    """

    allow_reuse_address = sys.platform != "win32"

    def __init__(self, window, name: str) -> None:
        self.window = window
        self.greeting = name.encode("utf-8")
        super().__init__((LOOPBACK, port_of(name)), _RaiseHandler)
        self._thread = threading.Thread(target=self.serve_forever, daemon=True)
        self._thread.start()

    def close(self) -> None:
        """Перестать слушать: остановить свой поток и отпустить порт."""
        self.shutdown()
        self.server_close()


def listen(window, name: str | None = None) -> _RaiseServer | None:
    """Слушать просьбы других копий и выводить по ним окно вперёд.

    Имя приходит доводом ради сторожей: боевой зов у объявления один и берёт
    умолчание, а двум сторожам в одном процессе нужны разные имена — иначе они
    слышали бы окна друг друга.

    Занятый порт — не беда, а всё та же вторая копия: работать ей не дал замок,
    и слушать ей незачем. Отдаётся слушатель наружу, чтобы зовущий мог его
    погасить; ничего не вышло — отдавать нечего.
    """
    name = name or socket_name()
    try:
        return _RaiseServer(window, name)
    except OSError as error:
        logger.warning("raise_window: не слушаем %s (%s)", name, error)
        return None


def _bring_forward(window) -> None:
    """Показать окно человеку, который нажал ярлык второй раз.

    Разворачивается без разбора, свёрнуто окно или нет: спросить об этом
    pywebview нечем — состояние окна он держит у себя и наружу не отдаёт, — а
    поднимать свёрнутое бесполезно, оно так и останется в панели задач.

    `show()` не только показывает, но и забирает фокус: без фокуса окно
    всплыло бы, а ввод остался у той программы, поверх которой нажали.
    """
    window.restore()
    window.show()


def _let_the_other_copy_come_forward() -> None:
    """Отдать право на передний план — иначе окно первой копии только мигнёт.

    Только Windows: на прочих системах права переднего плана так не устроены,
    и отдавать нечего.
    """
    if sys.platform != "win32":
        return
    import ctypes

    try:
        ctypes.windll.user32.AllowSetForegroundWindow(_ASFW_ANY)
    except (AttributeError, OSError):
        logger.exception("raise_window: не отдать право на передний план")


def ask_to_raise(name: str | None = None) -> bool:
    """Попросить уже открытую копию показать своё окно; сказать, дошло ли.

    Отказ значит «слушать некому»: первая копия ещё не дошла до окна либо уже
    его закрыла, а замок отпустить не успела. Зовущему он сегодня ничего не
    меняет — уйти ему в любом случае, — и нужен сторожам, которые иначе не
    отличили бы переданную просьбу от потерянной.
    """
    name = name or socket_name()
    _let_the_other_copy_come_forward()
    greeting = name.encode("utf-8")
    try:
        with socket.create_connection((LOOPBACK, port_of(name)), CONNECT_TIMEOUT_S) as sock:
            sock.sendall(greeting)
            return sock.recv(len(_ACK)) == _ACK
    except OSError as error:
        logger.debug("raise_window: некому передать просьбу по %s (%s)", name, error)
        return False
