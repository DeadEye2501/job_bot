"""Живое хозяйство окна: мотор, сессии, настройки и поднятый под ними бот.

Домены поверхности не держат ничего своего — они берут отсюда. Бот здесь по
той же причине, по какой он не может лежать в домене: он рождается и умирает
вместе с окном, а домен, взявший его копию, держал бы вчерашнего.

Пока поверхностей две, хозяйство у них одно: заводит его `MainApi`, а
переехавшие домены собираются поверх того же самого. Двух хозяйств быть не
должно — бот в них разъехался бы, и половина поверхности отвечала бы «бот ещё
не готов» при живом боте.
"""

from __future__ import annotations

from client.bridge.events import Events


class Hub:
    """То, из чего собран домен: мотор, сессии, настройки, бот, события.

    Три поля приходят доводами, пять заводятся пустыми и наполняются по ходу
    жизни окна: бот и его работа рождаются при входе в учётную запись, вход в
    Telegram живёт между тремя своими шагами, ник запоминается после первого
    удачного вопроса. Заводит их окно — оно одно умеет поднимать бота, — а
    правит и окно, и домен настроек: выход из учётной записи гасит и бота, и
    вход, и запомненный ник, и это его дело, а не окна.
    """

    def __init__(self, runner, session_factory, rs) -> None:
        self.runner = runner
        self.session_factory = session_factory
        self.rs = rs
        self.events = Events()
        self.bot = None
        self.bot_task = None
        self.login = None
        # Бот поднимается секундами — Pyrogram читает сеанс и соединяется, — а
        # экран настроек спрашивает ник сразу. Запомненный переживает эти
        # секунды и несколько запросов подряд.
        self.username_cache = ""
