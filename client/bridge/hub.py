"""Живое хозяйство окна: то, из чего собран каждый домен поверхности.

Домены поверхности не держат ничего своего — они берут отсюда. Бот здесь по
той же причине, по какой он не может лежать в домене: он рождается и умирает
вместе с окном, а домен, взявший его копию, держал бы вчерашнего.

Хозяйство одно на всю поверхность: заводит его `lifespan.start`, а домены
собираются поверх того же самого. Двух хозяйств быть не должно — бот в них
разъехался бы, и половина поверхности отвечала бы «бот ещё не готов» при живом
боте.
"""

from __future__ import annotations

from client.bridge.events import Events


class Hub:
    """То, из чего собран домен: мотор, сессии, настройки, бот, события, движок.

    Доводами приходят три поля — мотор, фабрика сессий и настройки; очередь
    событий заводится тут же, своя на хозяйство. Остальные наполняются по
    ходу жизни окна: бот и его работа рождаются при входе в учётную запись,
    движок и вход кладёт `lifespan.start`, само окно кладёт `window.run_ui`,
    подписка на журнал ставится вместе с первым его открытием, ник запоминается
    после первого удачного вопроса.

    Правит их и подъём, и домен настроек: выход из учётной записи гасит и бота,
    и вход, и запомненный ник, и это дело настроек, а не окна.
    """

    def __init__(self, runner, session_factory, rs) -> None:
        self.runner = runner
        self.session_factory = session_factory
        self.rs = rs
        self.events = Events()
        self.bot = None
        self.bot_task = None
        # Движок нужен сносу: не закрыв его, файл базы не удалить — Windows
        # держит открытый. Фабрика сессий его прячет, и доставать оттуда
        # значило бы читать её служебные доводы.
        self.engine = None
        # Кто и когда смотрит журнал. Признак общий на окно: приёмник записей
        # в буфере один на процесс, и держать его признак у себя значило бы,
        # что подписка зависит от того, кого собрали последним.
        self.watching_logs = False
        self.login = None
        # Само окно. Нужно одному делу — диалогу выбора файла: он у окна, а не
        # у моста, и со страницы до него не дотянуться никак. Кладёт его сюда
        # `window.run_ui` сразу после того, как окно поднято.
        self.window = None
        # Бот поднимается секундами — Pyrogram читает сеанс и соединяется, — а
        # экран настроек спрашивает ник сразу. Запомненный переживает эти
        # секунды и несколько запросов подряд.
        self.username_cache = ""
        # Последний замер скорости каждой модели, в миллисекундах. Общий у двух
        # доменов: снимает его здоровье на подключении (`system`), а нажатая
        # проверка сохранённой модели (`llm`) кладёт сюда же свежий — иначе
        # плашка настроек после ухода с экрана вернулась бы к старому числу.
        self.model_ms: dict[str, int | None] = {"chat": None, "embed": None}
