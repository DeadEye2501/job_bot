"""Запрос списка, прочитанный из нагрузки окна: сколько, откуда и что искать.

Четыре экрана просят строки одинаково — сколько и с какого места, — и пока
каждый слот читал эти поля сам, написания разъехались: умолчание потолка, чем
читается целое и режется ли потолок вовсе.

Что делать с пришедшим, решает окно и только окно: дописать к показанному или
заменить его целиком, оно знает по тому, зачем спросило, — мосту про это не
говорят вовсе.

Жалоба на негодную нагрузку живёт рядом, в `payload.py`: там про то, что
сказать в журнал, здесь про то, что прочитать.
"""

from __future__ import annotations

from dataclasses import dataclass

from backend.incoming import int_or_none, text_or_none


_CEILING = 200
"""Больше этого мост за раз не отдаёт.

Такое же число стоит на другой стороне — `RELOAD_MAX` в
`client/web/state/paging.js`: перечитывая список после правки поля, окно просит
не больше показанного, но и не больше двухсот. То есть в потолок оно упирается
не по недосмотру, а по устройству — у пролиставшего тысячу строк перечитывание
просит ровно двести.

Совпадение при этом молчаливое: числа объявлены порознь и связаны только этим
абзацем. Свести их в одно негде — питон и страница живут разными языками, — а
разъехавшись, они дадут не поломку, а тихую недостачу: окно просит двести,
мост отдаёт сто, и человек считает, что список кончился.
"""


@dataclass(frozen=True)
class Page:
    """Чего окно просит у списка и чем узнает свой ответ."""

    limit: int | None
    offset: int


def read_search(payload) -> str | None:
    """Строка поиска из нагрузки; негодная нагрузка значит «не искали».

    Не-объект сводится к пустоте, а не роняет разбор: поиск — дело окна, и
    испорченная нагрузка не должна отнимать у человека весь перечень.
    """
    payload = payload if isinstance(payload, dict) else {}
    return text_or_none(payload.get("search"))


def read_page(
    payload,
    *,
    default_limit: int | None = None,
) -> Page:
    """Страница из нагрузки окна.

    Потолок стоит на границе, а не у запроса: отбор дочитывает строки питоном,
    и негодная нагрузка с запросом на миллион строк прошла бы его целиком.
    Листают окном по десяткам, а вот перечитывание после правки поля просит
    ровно потолок — см. `_CEILING`.

    Умолчание потолка — довод, и это след прежних четырёх написаний, а не
    предметное различие: у людей и вакансий пропущенный потолок значит
    «сколько есть», у компаний и вакансий канала — полсотни. Свести его
    вслепую нельзя, потому что видно оно только на негодной нагрузке — окно
    потолок шлёт всегда, — а ответ поменялся бы сразу на четырёх экранах.

    Порядкового знака здесь нет вовсе: окно его не слало и обратно не читало.
    Устаревший ответ оно отбрасывает своим счётом попыток (`attempts()` в
    `client/web/state/attempts.js`) — это и есть единственное место, где такое
    решается, и мост в нём не участвует.
    """
    payload = payload if isinstance(payload, dict) else {}
    limit = int_or_none(payload.get("limit"))
    if limit is None:
        limit = default_limit
    if limit is not None and limit > _CEILING:
        limit = _CEILING
    return Page(
        limit=limit,
        offset=int_or_none(payload.get("offset")) or 0,
    )
