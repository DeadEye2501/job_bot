"""Страница списка, прочитанная из нагрузки окна.

Четыре экрана просят строки одинаково — сколько, с какого места, что сделать
с пришедшим и каким по счёту был запрос, — и пока каждый слот читал эти поля
сам, написания разъехались по пяти признакам сразу: умолчание потолка, набор
режимов, просеивание порядкового знака, чем читается целое и режется ли
потолок вовсе.

Жалоба на негодную нагрузку живёт рядом, в `payload.py`: там про то, что
сказать в журнал, здесь про то, что прочитать.
"""

from __future__ import annotations

from dataclasses import dataclass

from backend.incoming import int_or_none


LIST_MODES = ("replace", "append", "refresh")

_CEILING = 200


@dataclass(frozen=True)
class Page:
    """Чего окно просит у списка и чем узнает свой ответ."""

    limit: int | None
    offset: int
    mode: str
    epoch: int | None


def read_mode(payload: dict, modes: tuple[str, ...]) -> str:
    """Режим из нагрузки: незнакомый сводится к первому из набора.

    По этому слову окно решает, дописать пришедшее к показанному или заменить
    показанное целиком, и опечатку оно истолкует как замену — уже догруженное
    пропадёт с экрана. Поэтому эхом обратно едет только то, что окно назвать
    и могло.

    Набор берётся доводом, а не берётся отсюда: у списка страниц он свой
    («заменить», «дописать», «обновить»), у вакансий канала обновления нет
    вовсе, а у переписки набор и вовсе о другом — свежие сообщения против
    older.
    """
    mode = str(payload.get("mode") or modes[0])
    return mode if mode in modes else modes[0]


def read_page(
    payload: dict,
    *,
    default_limit: int | None = None,
    modes: tuple[str, ...] = LIST_MODES,
) -> Page:
    """Страница из нагрузки окна.

    Потолок стоит на границе, а не у запроса: отбор дочитывает строки питоном,
    и негодная нагрузка с запросом на миллион строк прошла бы его целиком.
    Окно просит десятками — у каждого экрана свой размер страницы, и все они
    много меньше потолка, так что человеку он невидим.

    Умолчание потолка — довод, и это след прежних четырёх написаний, а не
    предметное различие: у людей и вакансий пропущенный потолок значит
    «сколько есть», у компаний и вакансий канала — полсотни. Свести его
    вслепую нельзя, потому что видно оно только на негодной нагрузке — окно
    потолок шлёт всегда, — а ответ поменялся бы сразу на четырёх экранах.

    Порядковый знак просеивается тем же чтением целого, что и остальные числа:
    окно узнаёт свой ответ сравнением с числом, и вернувшаяся строка не
    совпала бы с ним никогда — ответ выглядел бы устаревшим и был бы отброшен.
    """
    limit = int_or_none(payload.get("limit"))
    if limit is None:
        limit = default_limit
    if limit is not None and limit > _CEILING:
        limit = _CEILING
    return Page(
        limit=limit,
        offset=int_or_none(payload.get("offset")) or 0,
        mode=read_mode(payload, modes),
        epoch=int_or_none(payload.get("epoch")),
    )
