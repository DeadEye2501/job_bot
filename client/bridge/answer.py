"""Единый конверт ответа окну — от исхода работы до ответа зовущему.

Отправок две, и разводит их длина работы. `reply` отдаёт исход значением, как
его ждёт pywebview, — им отвечает всё, что кончается за один взгляд человека.
`launched` отвечает «работа пущена» сразу, а исход её уезжает вестью в очередь:
так отвечают обход каналов, прогон канала, прогон вакансии и отправка отклика,
где работа идёт минутами, и держать ради неё зов значило бы держать и окно.

**Пишет отсюда и в журнал.** Негодная нагрузка и сорвавшаяся работа уезжают
окну коротким словом, а трассировка к ним остаётся здесь: показывать её
человеку незачем, а разбирать беду потом больше нечем. Трассировку сорвавшейся
работы пишет `reply` сама; про негодную нагрузку пишет `payload`, у которого
своя забота — не пустить секрет из нагрузки в файл журнала.
"""

from __future__ import annotations

import asyncio
import logging
from concurrent.futures import CancelledError
from typing import Any, Callable, Coroutine

from backend.incoming import int_or_none
from client.bridge.events import Events
from client.bridge.payload import _log_invalid_payload
from client.bridge.refusals import NO_BOT
from client.bridge.runner import AsyncRunner


logger = logging.getLogger(__name__)


class Denied(Exception):
    """Отказ, случившийся уже внутри работы: строки нет, имя занято.

    До мотора такое отвечается прямо, `denied`; изнутри работы отвечать нечем —
    возврат там занят исходом, — и отказ поднимается сюда броском. Ловит его
    `reply` и складывает тот же конверт.
    """

    def __init__(self, reason: str, **extra: Any) -> None:
        super().__init__(reason)
        self.reason = reason
        self.extra = extra


def denied(reason: str, **extra: Any) -> dict:
    """Отказ по делу: предмета нет, имя занято, поле пустое.

    Род один на все такие отказы, а различает их фраза: она и есть то, что
    человек прочтёт, и живёт она в `refusals`. Заводить род на каждую фразу
    незачем — окно показывает их одной плашкой и по роду не ветвится.
    """
    return {"fail": "denied", "detail": reason, **extra}


def bad_fields(where: str, error: Exception, **extra: Any) -> dict:
    """Нагрузка не разобралась: жалоба в журнал без секретов, отказ окну.

    Три эти строки стояли своим телом в каждом слоте, читающем нагрузку, — на
    сорока восьми местах. Разъезжались они молча: чей-то слот забывал жалобу, и
    беда пропадала целиком.

    Имя места приставкой домена называют там, где оно столкнулось: пять имён —
    `update`, `create`, `merge`, `merge_picker`, `vacancies` — есть у двух и
    трёх доменов сразу, и без приставки запись в журнале не сказала бы, чей
    экран прислал негодное. Остальные двадцать два имени по мосту уникальны, и
    приставка к ним ничего не добавила бы.

    Поля рядом с отказом — имя действия и номер строки — до экрана сегодня не
    доходят вовсе: `bridge.js` разворачивает конверт и оставляет от него одну
    фразу. Задуманы они были под откат отметки, поставленной заранее, но ни
    один экран так не делает — и пока не делает, дальше журнала они не едут.
    """
    _log_invalid_payload(where, error)
    return {"fail": "fields", "detail": f"Неверные поля: {error}", **extra}


BAD_PAYLOAD = (AttributeError, ValueError, TypeError, KeyError)
"""Породы бед, означающие негодную нагрузку окна, а не сбой моста.

Одним объявлением на весь мост: то же решение стояло своим кортежем в двух
десятках слотов, и написания разошлись — три набора, пять написаний, две пары
из которых различались только порядком членов. Разъезд молчаливый: на чём
именно споткнётся чтение, зависит от того, каким движением слот берёт поле, и
слот, поймавший не ту породу, отвечает окну поломкой вместо `bad_fields`.

Почему четыре. `KeyError` — поля нет вовсе; `TypeError` — не-объект вместо
нагрузки или не-число там, где ждали число; `ValueError` — число, которое не
разбирается; `AttributeError` — не-объект, у которого спросили `get`. Все
четыре означают одно: пришло не то, и говорить об этом надо окну, а не падать.
"""


def asked_id(payload: dict, key: str, slot: str) -> tuple:
    """Номер предмета из нагрузки, а при негодной — готовый отказ окну.

    Двумя значениями, а не броском: жалоба в журнал должна нести саму беду —
    имя пропавшего поля из `KeyError` в неё попадает, а значение нет, — и
    собрать её умеет только `bad_fields`, который живёт здесь же.

    Одно объявление на весь мост: то же чтение стояло своим телом у трёх кнопок
    вакансии, у обеих карточек контакта и в правке полей, и написания у них
    начали расходиться перехватываемыми породами.
    """
    try:
        return int(payload[key]), None
    except BAD_PAYLOAD as e:
        return None, bad_fields(slot, e)


def read_toggle(payload: dict, id_key: str, flag_key: str, slot: str) -> tuple:
    """Номер строки и её новое положение из нагрузки тумблера, а при негодной — готовый отказ.

    Тремя значениями, как `asked_id`: номер, признак и отказ окну либо пустота.
    Оба поля обязательны, но читаются «сколько смогли»: негодное или
    пропущенное становится пустотой, а прочитанная половина уезжает в отказ
    под теми же ключами — окно по ней возвращает на место тот тумблер,
    который человек нажал, и не трогает соседние. Отказ собирается здесь, а не
    у зовущего: эхо — часть отказа, и слот, собирающий его сам, может его
    потерять.

    Признак читается как есть: окно шлёт его булевым, а всё, что доедет иным,
    значит «включить» ровно тогда, когда это значит истину.
    """
    row_id = None
    flag = None
    try:
        raw_flag = payload.get(flag_key)
        row_id = int_or_none(payload.get(id_key))
        flag = None if raw_flag is None else bool(raw_flag)
        if row_id is None or flag is None:
            raise KeyError(f"{id_key} / {flag_key}")
    except BAD_PAYLOAD as e:
        return row_id, flag, bad_fields(
            slot, e, action="set_active", **{id_key: row_id, flag_key: flag}
        )
    return row_id, flag, None


def reply(runner: AsyncRunner, coro: Coroutine[Any, Any, Any]) -> dict:
    """Сделать работу на моторе и вернуть её исход зовущему одним конвертом.

    Зовут отсюда из потока канала, а работа идёт на моторе, поэтому ждём мы
    здесь, а не там: pywebview отдаёт странице то, что вернул метод.

    Исход бывает четырёх родов, и все четыре — ответ. Молчания не бывает ни при
    каком: прежний канал на сорвавшейся работе просто не присылал сигнала, и
    окно оставалось со спиннером навсегда.

    **Отмена тоже отвечает.** Ответа ждёт зов, и промолчать значит держать его
    впустую.

    Своего срока у ожидания нет. Назначенный однажды, он врал: работа длиннее
    срока доходила до конца, а окно к тому времени уже объявляло её неудачей.
    Долгую работу отвечают не сроком, а `launched` — она и не ждёт вовсе.

    Звать это из потока самого мотора нельзя: работа, которой мы ждём, идёт в
    нём же, и ждать её значит запереть его насовсем. Сегодня оттуда никто и не
    зовёт — там обратные вызовы бота, они кладут событие в очередь.
    """
    try:
        return {"ok": runner.submit(coro).result()}
    except Denied as e:
        return denied(e.reason, **e.extra)
    except (CancelledError, asyncio.CancelledError):
        return {"fail": "cancelled"}
    except Exception as e:
        logger.exception(
            "bridge: unexpected error in coroutine %s",
            getattr(coro, "__qualname__", "?"),
        )
        return {"fail": "broken", "detail": f"{type(e).__name__}: {e}"}


def launched(
    hub, work: Callable[[], Coroutine[Any, Any, str]],
    refusals: dict[str, str], done: str, **started: Any,
) -> dict:
    """Пустить долгую работу на мотор и ответить, не дожидаясь её конца.

    Так отвечают кнопки, за которыми работа идёт минутами — обход каналов,
    прогон канала и вакансии, отправка отклика, приём вставленного
    объявления: ждать их значит держать зов, а с ним и окно. Ответ говорит одно — работа пущена;
    чем она кончилась, окно узнаёт вестью `action_finished`.

    **Пущенное отвечает всегда.** Ответ вести складывается здесь, а не в самой
    работе: сорвись работа броском, весть, написанная после её зова, ушла бы
    вместе с ним, и человек остался бы с «отправляется» навсегда — ровно с той
    бедой, ради которой вести и заведены.

    Работа принимается вызываемым, а не готовой корутиной: на погашенном
    моторе её никто не станет ждать, и она осталась бы висеть неисполненной.

    Собирающий обязан держать `runner` и `events` — оба берутся из хозяйства
    окна, и другого хозяйства у моста нет.
    """
    async def report() -> None:
        try:
            status = await work()
        except (CancelledError, asyncio.CancelledError):
            logger.info("bridge: launched job cancelled")
            raise
        except Exception:
            logger.exception("bridge: launched job failed")
            status = "error"
        finished(hub.events, status, refusals, done)

    try:
        hub.runner.submit(report())
    except Exception as e:
        logger.exception("bridge: launched job could not start")
        return {"fail": "broken", "detail": f"{type(e).__name__}: {e}"}
    return {"ok": {"started": True, **started}}


def launched_on_bot(
    hub, start: Callable[[Any], Coroutine[Any, Any, str]],
    refusals: dict[str, str], done: str, **started: Any,
) -> dict:
    """Долгая работа бота: без поднятого бота — отказ словами про бота, иначе `launched`.

    Бота поднимают после входа в Telegram, а кнопки рисуют всегда: молчание на
    такое нажатие оставило бы кнопку нажатой навсегда. Отказ несёт те же метки,
    что и ответ «пущено», — окно узнаёт по ним, о чём речь.
    """
    bot = hub.bot
    if bot is None:
        return denied(NO_BOT, **started)
    return launched(hub, lambda: start(bot), refusals, done, **started)


def finished(events: Events, status: str, refusals: dict[str, str], done: str) -> None:
    """Сказать окну, чем кончилась пущенная работа.

    Пара к `launched`: ответ на зов сказал только «пущено», и всё остальное
    человек узнаёт отсюда — вестью, которую оболочка показывает плашкой.

    Незнакомый исход берёт общую фразу набора — потому у каждого набора и
    обязан быть ключ `error`: исходы заводит бэкенд, и новый появляется там
    раньше, чем перевод к нему здесь, а промолчи мы, человек остался бы без
    ответа вовсе.
    """
    ok = status == "ok"
    events.add(
        "action_finished",
        {
            "message": done if ok else refusals.get(status, refusals["error"]),
            "danger": not ok,
        },
    )
