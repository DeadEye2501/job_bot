"""Живые события окна: копит случившееся с номерами и отдаёт всё новее названного.

Родов случившегося десять, и большая часть рождается в потоке мотора — обход,
прогресс, письмо, отметка о прочтении, правки списков, — а `progress_update` ещё
и вспышками по десяткам. Прежний канал доставлял это сигналом Qt; здесь окно
спрашивает само, а запрос ждёт появления нового или срока. Из питона в браузер
при этом не лезет никто, и вопрос о том, из какого потока это законно, не встаёт
вовсе.

Кольцо ограничено: страница, ушедшая на перезагрузку посреди обхода, вернётся не
сразу, а прогресс за это время нашлёт десятки сообщений. Выпавшее из кольца
названо потерей в ответе — неполная картина, выданная за полную, оставила бы
экран врать до следующей правки руками.

Соседи по слою — `runner` (поток, в котором ждёт запрос) и `answer` (конверт, в
котором ответ уезжает окну). Ближайшее по делу — кольцо журнала
`backend/log_buffer.py`: там тоже словари под замком и монотонный номер, но
номер лежит в записи для показа, срез берётся с хвоста, а ждать появления нового
кольцо не умеет и не должно — страницу журнала спрашивают по кнопке. Сводить
их поэтому нечего: совпадает приём, а не предмет.
"""

from __future__ import annotations

import asyncio
import logging
import threading
from collections import deque


logger = logging.getLogger(__name__)

KEEP_EVENTS = 500
"""Сколько случившегося кольцо помнит.

Величина назначена от худшего: вспышка прогресса за один обход — это сотни
сообщений, а страница, ушедшая на перезагрузку, возвращается через секунды.
Пятьсот переживают такую вспышку целиком; выпавшее сверх того не теряется
молча — ответ называет потерю отдельным полем.
"""
WAIT_SECONDS = 25.0
"""Сколько ждущий запрос ждёт нового, прежде чем ответить пустотой.

Замерено слайсом А3, и опасение не подтвердилось: зовы pywebview разбирает
каждый на своём потоке — двенадцать секундных разом уложились в секунду, — так
что ждущий запрос не занимает собой очередь и не мешает остальным. Своего срока
у библиотеки нет: зов длиной 28 секунд дошёл целым.

Четверть минуты — наш выбор между двумя ценами: реже ходит запрос — дешевле, но
дольше живёт закрытая страница, которой уже никто не ответит.
"""


class Events:
    """Очередь случившегося: кладут из любого потока, забирают по номеру."""

    def __init__(self, keep: int = KEEP_EVENTS) -> None:
        self._items: deque[dict] = deque(maxlen=keep)
        self._lock = threading.Lock()
        self._counter = 0
        self._dropped = 0
        self._waiters: list[tuple[asyncio.AbstractEventLoop, asyncio.Future]] = []
        self._closed = False

    def add(self, kind: str, payload: dict | None = None) -> None:
        """Записать случившееся и разбудить всех, кто ждёт нового."""
        with self._lock:
            self._counter += 1
            # Что выпало из кольца, считается, а не вычитывается из него: кольцо
            # о выпавшем не помнит, а пустое ещё и не отдало бы первую запись.
            self._dropped = max(0, self._counter - self._items.maxlen)
            self._items.append({"n": self._counter, "kind": kind, "payload": payload or {}})
            waiters, self._waiters = self._waiters, []
        _wake(waiters)

    async def take(self, after: int | None, timeout: float = WAIT_SECONDS) -> dict:
        """Всё, что новее названного номера; пусто — ждать до срока.

        **Номера нет — значит «с этого мига».** Так спрашивает страница,
        открывшаяся или перезагрузившаяся только что: своего номера у неё ещё
        нет. Прочти мы пустоту как ноль, ей уехало бы всё кольцо, и окно
        мигнуло бы плашками часовой давности как свежими.

        Проверка и запись в очередь ждущих идут под одним замком: между ними
        событие успело бы лечь незамеченным, и запрос ждал бы до срока при уже
        готовом ответе.

        **Закрытая очередь называет себя закрытой.** Страница спрашивает в
        вечном цикле — ответ пришёл, задаёт следующий вопрос, — и без этого
        признака закрытая очередь была бы неотличима от тишины: цикл крутился
        бы вхолостую до самой смерти окна, заводя на каждый оборот новый запрос
        к мосту, которого уже нет.
        """
        loop = asyncio.get_running_loop()
        waiter = loop.create_future()
        with self._lock:
            if after is None:
                after = self._counter
            answer = self._since(after)
            if answer["events"] or answer["missed"] or self._closed:
                return answer
            self._waiters.append((loop, waiter))
        try:
            # `wait`, а не `wait_for`: тишина за отведённый срок — обычный ход, и
            # отвечать на неё исключением, чтобы тут же его проглотить, незачем.
            await asyncio.wait([waiter], timeout=timeout)
        finally:
            # Отмена задачи при остановке мотора проносит `CancelledError` мимо
            # этой строки, и ждущий остался бы в очереди навсегда.
            with self._lock:
                self._waiters = [one for one in self._waiters if one[1] is not waiter]
        with self._lock:
            return self._since(after)

    def close(self) -> None:
        """Окно закрывают: отпустить ждущих сразу, не дожидаясь их сроков."""
        with self._lock:
            self._closed = True
            waiters, self._waiters = self._waiters, []
        _wake(waiters)

    def _since(self, after: int) -> dict:
        """Зовётся под замком: обход кольца и его же правка иначе разойдутся.

        Нынешний номер едет в каждом ответе, даже пустом: им страница двигает
        свою отметку. По последней вести двигать нельзя — ответ по сроку
        приходит без вестей вовсе, и отметка застыла бы, а следующий вопрос
        снова просил бы «с этого мига». Всё, что легло между ответом и
        вопросом, пропадало бы молча, и `missed` при этом молчал бы тоже.
        """
        return {
            "at": self._counter,
            "events": [one for one in self._items if one["n"] > after],
            "missed": after < self._dropped,
            "closed": self._closed,
        }


def _wake(waiters: list[tuple[asyncio.AbstractEventLoop, asyncio.Future]]) -> None:
    for loop, waiter in waiters:
        try:
            loop.call_soon_threadsafe(_finish, waiter)
        except RuntimeError:
            logger.debug("ждущий не разбужен: его цикл уже закрыт")


def _finish(waiter: asyncio.Future) -> None:
    if not waiter.done():
        waiter.set_result(None)
