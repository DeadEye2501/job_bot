"""Просьбы окна к рабочему столу: открыть названное тем, чем открывает система.

Дорог наружу две, и заслоны у них разные. Ссылку разбирают по схеме — она и
решает, чем система откроет адрес. Вложение переписки — по расширению и по
тому, лежит ли оно в каталоге медиа: имя файла называет собеседник.

Заслон стоит здесь потому, что после передачи спрашивать уже не у кого:
`startfile` исполняет отданное молча и об исходе рассказывает только тем, что
не бросил.
"""

from __future__ import annotations

import logging
import os

from client.bridge.answer import denied
from client.bridge.media import media_file
from client.bridge.refusals import (
    ATTACHMENT_MISSING,
    ATTACHMENT_NOT_OPENABLE,
    ATTACHMENT_NOT_OPENED,
    LINK_SCHEME_UNKNOWN,
)


logger = logging.getLogger(__name__)

_LINK_SCHEMES = frozenset({"http", "https", "tg"})
"""Схемы, по которым ссылку отдают системе.

Всё остальное система тоже откроет, только не браузером: `file:` запустит то,
на что указывает путь, а адрес в карточке набирает человек или приносит
объявление.

Сегодня все четыре кнопки шлют `https`: адрес объявления собирается им
(`backend/flows/ingest.py:105`), ссылки на канал и на переписку — тоже, а
набранный руками сайт компании приводит к нему `siteHref`. `tg:` назван планом
и производителя в коде не имеет.
"""

_OPENABLE_SUFFIXES = frozenset({
    ".bmp", ".gif", ".jpeg", ".jpg", ".png", ".webp",
    ".csv", ".pdf", ".txt",
    ".docx", ".odp", ".ods", ".odt", ".pptx", ".xlsx",
})
"""Чем позволено открыть присланное вложение.

Перечнем позволенного, а не запретов: запрет пришлось бы дописывать под каждое
новое расширение, которым исполняется программа, — а их десятки, и `.pdf.exe`
среди них не последний по неожиданности.

Скачивает бот **любой** документ, поэтому перечень не только запирает опасное,
но и оставляет без кнопки безобидное: `.zip`, `.log`, `.heic` не откроются
никак. Это принятая цена, а не недосмотр.

Старых `.doc`, `.xls`, `.ppt` и `.rtf` здесь нет нарочно. Скачанное Pyrogram
приходит без метки зоны, и Office открывает такое мимо защищённого просмотра —
то есть исполняет макрос присланного собеседником файла сразу. У `.docx` и
соседей по перечню макросов не бывает вовсе: они живут в `.docm`/`.xlsm`.
"""


def _scheme_of(url: str) -> str:
    """Схема адреса — то, что стоит до первого двоеточия.

    Адреса без двоеточия схемы не имеют вовсе: `example.com/a` система открыла
    бы как путь на диске, а не как сайт.
    """
    return url.split(":", 1)[0].lower() if ":" in url else ""


def open_in_system(target: str) -> bool:
    """Отдать путь или ссылку тому, чем система их открывает, и сказать, дошло ли.

    Без Qt: переехавшим доменам он недоступен, а дело у этой просьбы то же
    самое. `startfile` есть только на Windows — под неё приложение и
    собирается; на чужой системе его нет вовсе, и это тот же исход «не
    смогли», потому `AttributeError` ловится рядом с `OSError`. **Этой ветки не
    исполняет ни один сторож** и не может: прогон идёт на Windows, где
    `startfile` есть, а подменять его отсутствие значило бы сторожить
    подмену, а не систему.

    Ответ нужен зовущему: «открыли» и «не смогли» человек различает только по
    нашему слову — окна-то он не увидит.
    """
    try:
        os.startfile(target)
    except (AttributeError, OSError):
        logger.exception("не удалось открыть системой: %s", target)
        return False
    return True


class Desktop:
    """Просьба к рабочему столу, какую страница делает чужими руками.

    Примесь к `System`; просьб в ней две — ссылка и вложение переписки. Третья,
    буфер обмена, не переехала и не переедет: написана она была на Qt, а
    страница в WebView2 кладёт текст в буфер сама (`navigator.clipboard`) —
    мост ей для этого не нужен.

    `_hub` этой примеси не нужен вовсе — единственная в мосте, кому не нужен:
    ни базы, ни бота, ни мотора здесь нет, просьба уходит системе и
    возвращается тут же.
    """

    def open_url(self, url: str) -> dict:
        """Отдать ссылку тому, чем система её открывает.

        Ведут они на объявление в канале и на переписку с человеком в
        Telegram. Ответ пустой, но он есть: открывает ссылку не мост, а
        система, и «открыли» от «не смогли» человек отличит только по нашему
        слову.

        Работы для мотора здесь нет вовсе — просьба уходит системе и
        возвращается тут же, — поэтому ответ складывается на месте.
        """
        if not isinstance(url, str) or not url:
            # Ссылка в карточке бывает пустой: источник её не прислал. Уйди
            # пустое в оболочку, открылось бы окно браузера ни на чём, и
            # человек решил бы, что приложение сломалось. Не-строка сюда же:
            # прежде её приводил канал, а теперь нагрузка едет как есть.
            return denied("Ссылка пуста.")
        # Схема отрезается от самой строки, а не разбирается `urlsplit`:
        # разборщик выбрасывает из адреса управляющие знаки и пробелы, и
        # `java\nscript:` доехало бы до него безобидным именем схемы, а системе
        # мы отдаём строку как есть — то есть проверяли бы не то, что отдаём.
        if _scheme_of(url) not in _LINK_SCHEMES:
            return denied(LINK_SCHEME_UNKNOWN)
        if not open_in_system(url):
            # Ссылку обратно не кладём: она у страницы и так одна — та, по
            # которой только что нажали.
            return denied("Не удалось открыть ссылку.")
        return {"ok": {"url": url}}

    def open_attachment(self, url: str) -> dict:
        """Открыть присланный файл тем, чем система открывает такие файлы.

        Адрес приезжает тот же, каким окно показывает вложение в ленте, — и
        приезжает он снаружи: заслон каталога стоит здесь, а не в раздаче,
        которая этого зова не видит.

        Своим слотом, а не через `open_url`: у ссылки и у файла общее только
        то, что оба уходят системе. Разбирать их одной дорогой значило бы
        пускать по ней и схемы, и расширения — а годного пересечения у этих
        двух перечней нет вовсе.
        """
        target = media_file(url)
        if target is None or not target.is_file():
            # Скачивает бот не всё: строка о письме в базе остаётся, а файла
            # под ней нет. Сюда же путь, ведущий вне каталога медиа.
            return denied(ATTACHMENT_MISSING)
        if target.suffix.lower() not in _OPENABLE_SUFFIXES:
            logger.warning("вложение не той породы, открывать не стали: %s", target.name)
            return denied(ATTACHMENT_NOT_OPENABLE)
        if not open_in_system(str(target)):
            return denied(ATTACHMENT_NOT_OPENED)
        return {"ok": {}}
