def agent_refusals(table: dict, chat) -> dict:
    """Набор отказов работы агента с подсказкой доступности на миг нажатия.

    Спрашивается на каждом нажатии, а не однажды: поставщика чата и браузер
    человек меняет без перезапуска (`current_refusal`).
    """
    return {**table, "locked": current_refusal(chat) or ""}
