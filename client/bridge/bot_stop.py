"""Остановка бота: попросить и дождаться.

Останавливают его четыре дороги — закрытие окна, выход из учётной записи,
снос данных и повторный вход, — и все ходят одними шагами: отменить текущий
обход, попросить остановиться, дождаться работы с ограниченным сроком, а не
дождавшись — сказать об этом в журнал. Ждут по-разному: повторный вход зовёт
это из самого мотора и уходит не дожидаясь — ожидание заперло бы мотор.

Порознь эти шаги разъехались по всему, чем могли: срок был пять секунд у
одного и десять у двоих, ожидание синхронным у одного и через
`asyncio.wait_for` у двоих, а отмена обхода у сноса завёрнута в свой перехват,
у соседей — нет.

Своим модулем, а не в `runner.py`: тот про то, где живут корутины, а здесь про
то, как бот умирает.
"""

from __future__ import annotations

import asyncio
import logging
from collections.abc import Awaitable, Callable
from concurrent.futures import Future


logger = logging.getLogger(__name__)

STOP_TIMEOUT_S = 10.0
"""Сколько ждать бота там, где человек ждёт ответа, а не окна.

Выход из учётной записи и снос данных отвечают окну сами, и им важнее
дождаться: остановившийся бот отпускает файл сеанса, который снос сейчас
удалит. Закрытие окна ждёт меньше и свой срок называет само — там на
застывшее окно смотрит человек.
"""


async def stop_bot(
    bot,
    bot_task: Future | None,
    asking: Callable[[], Awaitable[None]] | None = None,
    timeout: float = STOP_TIMEOUT_S,
) -> None:
    """Попросить бота остановиться и дождаться его работы.

    `asking` — чем именно просят: у выхода из учётной записи это
    `log_out_session`, который сперва отзывает ключ на сервере; у остальных
    его нет, и зовётся обычный `request_stop`. Это первое предметное различие
    трёх дорог, второе — срок.

    **Просьба не глотается.** Не отозвался ключ на сервере — выход из учётной
    записи обязан сказать об этом окну, иначе человек считает себя вышедшим,
    а сеанс жив. Кому беда безразлична — тот и перехватывает: снос данных идёт
    дальше при любом исходе, и это записано у него.

    Ожидание, наоборот, беду глотает и пишет в журнал: зависший обход не
    отменяет ни выхода, ни сноса, ни закрытия окна, а след его нужен —
    другого не останется.
    """
    if bot is not None:
        bot.cancel_current_poll()
        if asking is not None:
            await asking()
        else:
            bot.request_stop()
    if bot_task is None:
        return
    try:
        await asyncio.wait_for(asyncio.wrap_future(bot_task), timeout)
    except asyncio.TimeoutError:
        logger.warning("stop_bot: bot did not stop within %ss", timeout)
    except Exception:
        logger.exception("stop_bot: bot task raised")
