"""Сказать человеку о беде, когда своего окна ещё нет.

Отличается от `window.py` тем, что работает до него и без него: между взятием
замка и открытием окна стоят проверка хранилища ключей, обновление схемы,
подъём базы и чтение настроек — и любая из этих работ может отказать.

Сказать об этом иначе нечем. В оконной сборке нет ни консоли, ни потока ошибок:
`sys.stderr` там равен `None`, `print` уходит на `sys.stdout`, который тоже
`None`, и молча ничего не делает. Человек жмёт ярлык, и не происходит ничего —
столько раз, сколько он нажмёт. Догадаться заглянуть в `%APPDATA%\\JobBot\\jobbot.log`
может только тот, кто писал приложение.

Окно системы для этого и годится: оно не требует ни поднятого приложения, ни
консоли, и человек его видит.
"""

from adapters.platforms import window as platform_window
import logging


logger = logging.getLogger(__name__)


def show_trouble(text: str) -> None:
    """Показать беду окном системы.

    Своя беда здесь гасится записью: это последняя дорога к человеку, и упасть
    на ней значит не сказать ему вовсе ничего — а зовущий в этот миг уже
    выходит и перехватить нас не может.
    """
    try:
        platform_window.show_trouble(text)
    except Exception:
        logger.exception("не вышло показать беду окном системы: %s", text)
