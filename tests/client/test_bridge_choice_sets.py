"""Следствия отбора значений из закрытых наборов при чтении форм окна.

Окно шлёт выбранное человеком галочками — списком, в порядке нажатий и с чем
угодно внутри. Порядок нажатий доходит до языковой модели: из этой же колонки
собирается строка блока анкеты («офис, гибрид»), и разный порядок дал бы разные
запросы на одну и ту же анкету — а ответ модели зависит от текста запроса.

Своим сторожем это накрывается здесь, а не в бэкенде, потому что приводит
список к порядку та сторона, которая читает нагрузку окна.
"""

from backend.domain.taxonomy import GRADES, WORK_FORMATS
from client.bridge import _filter_set


def test_the_declared_order_wins_over_the_order_of_clicks():
    """Порядок берётся из объявления, а не из того, как человек нажимал.

    Иначе одна и та же анкета уходила бы в модель разными строками — «офис,
    гибрид» и «гибрид, офис», — и ответы на неё расходились бы без единой
    правки самой анкеты.
    """
    assert _filter_set(["hybrid", "office"], WORK_FORMATS) == ["office", "hybrid"]
    assert _filter_set(["senior", "junior"], GRADES) == ["junior", "senior"]


def test_a_value_outside_the_set_does_not_reach_the_column():
    """Незнакомое значение отбрасывается, а не ложится в колонку.

    Нагрузку составляет не наш код: в списке приходит и опечатка, и число, и
    вовсе не список. Колонка же читается как закрытый набор — по ней анкета
    сравнивается с разобранной вакансией.
    """
    assert _filter_set(["office", "космос", 42], WORK_FORMATS) == ["office"]
    assert _filter_set("office", WORK_FORMATS) == []
