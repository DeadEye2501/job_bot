"""Рост окна в тот миг, когда мастер закончен.

Самой рамы здесь нет — отпускает её `_unlock_frame`, а тому нужны живая форма
WinForms и настоящий рабочий стол. Подменён он целиком: предмет тут не рама, а
куда и на сколько уезжает окно, когда её отпустили.
"""

from client import window_size


def test_the_window_grows_evenly_around_its_own_centre(growing_window):
    """Приросшие точки расходятся во все стороны поровну.

    Мастер уже стоит там, куда его поставил человек, и смотрит он в середину
    окна. Вырасти окно вниз и вправо, как растёт оно само, — середина уехала
    бы из-под взгляда, а на маленьком экране правый край ушёл бы за него.
    """
    window_size.grow_to_main(growing_window)

    # Числами, а не разностью постоянных: сверка величины с собой прошла бы и
    # на окне, которое никуда не переехало.
    assert ("переехало", 400 - 130, 300 - 20) in growing_window.done
    assert ("выросло", 900, 660) in growing_window.done


def test_the_frame_is_let_go_before_the_window_moves(growing_window):
    """Рама отпускается раньше, чем окно поехало.

    Окно мастера создано нерастягиваемым, и наименьший размер у него — размер
    мастера. Поезжай оно первым, система прижала бы его обратно к прежней
    рамке, и человек увидел бы приложение в окне мастера.
    """
    window_size.grow_to_main(growing_window)

    assert growing_window.done[0] == ("рама отпущена",)
