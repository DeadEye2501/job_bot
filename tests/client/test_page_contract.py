"""Шов имён: сходятся ли имена, которыми страница зовёт мост, с самим мостом.

Расходятся они молча и в обе стороны. Переименуй метод в питоне — страница
позовёт несуществующее и покажет плашку беды там, где всё было исправно;
переименуй на странице — метод моста останется без зовущего, и заметит это
только тот, кто однажды откроет тот экран.

Ни линтер, ни сборка этого не ловят: с одной стороны питон, с другой строка в
JavaScript, и между ними нет ничего, кроме уговора.

**У самого поиска есть свои сторожа.** Ищет он строками, и первое же изменение
формы зова — новая обёртка, переносы, кавычки, псевдоним вместо имени — сделало
бы его слепым: имён он не нашёл бы вовсе и промолчал бы, будто всё сходится.
Поэтому рядом стоят проверки на заведомо известных образцах — по одной на каждую
форму зова.

**Слепота тут дороже отсутствия.** Пустой прогон видно сразу, а зелёный сторож,
не смотрящий никуда, закрывает собой вопрос: имена после него не сверит уже
никто.
"""

import re
from pathlib import Path

import pytest


WEB = Path(__file__).resolve().parents[2] / "client" / "web"

# Имя моста пишется на странице внутри зова обёртки: `call('домен.метод')` или
# `ask('домен.метод')`. Обёрток две, и вторая — не мелочь: через неё идёт
# большинство зовов оболочки, потому что она показывает отказ плашкой.
#
# **Заведёшь третью — впиши её сюда.** Иначе её зовы выпадут из шва молча, а
# молчание здесь читается как «всё сходится».
CALLING = re.compile(r"""\b(?:call|ask)\(\s*['"]([a-z_]+)\.([a-z_]+)['"]""")

SOURCES = ("*.js", "*.svelte")

# Слои, где живёт страница. Перечислены поимённо, а не «всё, кроме сборки»:
# иначе в выборку попадают собственные проверки страницы и привезённое, и шов
# начинает сторожить их, а не её — покрытие выглядит толще, чем есть, а
# выдуманное имя в проверке красит шов на пустом месте.
LAYERS = ("api", "app", "components", "state")


def _sources() -> list[Path]:
    """Исходники страницы: боевые слои и точка входа."""
    found = [one for one in WEB.glob("*.js") if one.name == "main.js"]
    for layer in LAYERS:
        for pattern in SOURCES:
            found += list((WEB / layer).rglob(pattern))
    return found


def _called(text: str) -> set[tuple[str, str]]:
    return {(domain, method) for domain, method in CALLING.findall(text)}


def test_there_are_sources_to_look_at_in_the_first_place():
    """Исходники страницы вообще нашлись.

    Сторож ниже разложен по файлам, и пустая выборка прошла бы зелёной, ничего
    не проверив: съехавший путь, переименованная папка, изменившееся
    расширение — любое из этого сделало бы шов немым, а прогон при этом
    остался бы прежним.
    """
    assert _sources(), f"в {WEB} не нашлось ни одного исходника страницы"


def test_the_search_finds_a_call_it_is_shown():
    """Сам поиск умеет находить: иначе он молчал бы, а мы читали бы это как «сходится».

    Заведомый образец, а не настоящий исходник: настоящий однажды окажется
    пустым — экраны ещё не написаны, — и сторож ниже станет зелен ни на чём.
    """
    found = _called("const answer = await call('system.health');")

    assert found == {("system", "health")}


def test_the_search_sees_the_calls_made_through_the_shell_wrapper():
    """И находит зов, написанный через обёртку оболочки.

    Обёрток на странице две: `call` из `api/bridge.js` и `ask` в самой
    оболочке, которая показывает отказ плашкой. Через вторую идёт большинство
    зовов, и поиск, знающий только первую, молчал бы про них — а молчание тут
    неотличимо от «всё сходится».
    """
    found = _called("await ask('system.set_mode', chosen);")

    assert found == {("system", "set_mode")}


def test_the_search_does_not_invent_calls_out_of_thin_air():
    """И не находит того, чего нет: слепой поиск ловится первым сторожем, а
    болтливый — этим. Найди он лишнее, шов краснел бы на ровном месте, и его
    отключили бы целиком.
    """
    assert _called("api.system.health(); // так на странице не зовут") == set()


@pytest.mark.parametrize("source", _sources(), ids=lambda p: p.name)
def test_every_name_the_page_calls_exists_on_the_bridge(source, api):
    """Каждое имя, которым страница зовёт мост, у моста есть.

    Проверяется по собранной поверхности, а не по исходнику питона: страница
    зовёт `api.<домен>.<метод>`, и pywebview обходит именно поля собранного
    дерева — опечатка в имени поля видна только так.
    """
    for domain, method in _called(source.read_text(encoding="utf-8")):
        assert hasattr(api, domain), f"{source.name}: у моста нет домена {domain}"
        assert hasattr(getattr(api, domain), method), (
            f"{source.name}: у домена {domain} нет метода {method}"
        )


