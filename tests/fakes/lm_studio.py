"""Пустое соединение с языковой моделью — для сборок, что до неё не ходят.

От `tests/fakes/llm.py` отличается тем, что клиента здесь нет вовсе: там
поднимается настоящий httpx поверх подставного транспорта, чтобы проверить
заголовки и разбор ответа, а сборке бота и конвейера довольно помнить адрес и
то, что соединение закрыли. Нужен обоим, поэтому живёт не у кого-то одного.
"""


class LmClient:
    """Заглушка соединения с языковой моделью: помнит адрес и закрытие."""

    def __init__(self, base_url: str) -> None:
        self.base_url = base_url
        self.closed = 0

    async def aclose(self) -> None:
        self.closed += 1
