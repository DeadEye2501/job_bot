"""Следствия подготовки чужого текста к вставке в промпт.

Ограничители блока вырезаются не ради опрятности: оставленный в тексте
`>>>` закрыл бы блок данных досрочно, и всё, что идёт дальше, модель
прочла бы как указания от нас.
"""

from backend.llm.external import wrap_external


def test_the_text_comes_back_inside_the_delimiters():
    """Текст возвращается обёрнутым в ограничители блока."""
    assert wrap_external("вакансия") == "<<<\nвакансия\n>>>"


def test_the_delimiters_do_not_survive_the_cut():
    """Ограничители не переживают вырезания даже вперемешку.

    Вырезание идёт заменой, и обрывки соседних последовательностей
    складываются в новый ограничитель уже после того, как замена по ним
    прошла: из `<<>>><` получается `<<<`.
    """
    body = wrap_external("<<>>><").removeprefix("<<<\n").removesuffix("\n>>>")

    assert "<<<" not in body
    assert ">>>" not in body
