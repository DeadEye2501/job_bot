"""Подставной разбор объявления, складывающий зовы в переданный список.

Своим объявлением, а не в каждом файле проверок: разбор подменяют три предмета
— приём поста, подбор недоразобранного и прогон заново, — и подменяют
одинаково. Три тела разъезжались бы по умолчанию `allow_delete`, а именно оно в
этих проверках и есть предмет: проверка про запрет зеленела бы на подделке.

Список приходит доводом, а не заводится здесь: у прогона заново в тот же список
ложится отметка о перечитанных настройках, и порядок этих записей он и
проверяет.
"""

from backend.flows import parse as parse_mod


def parse_into(monkeypatch, calls: list, *, done=True) -> None:
    """Подменить разбор: зов ложится четвёркой, ответ берётся у `done`.

    Четвёркой, а не тем, что нужно каждому: номер, текст, ник канала и
    разрешение на удаление — всё, чем разбор отличается от зова к зову.

    `done` бывает и обёрткой: прогону заново нужно менять ответ разбора уже
    после того, как подделка поставлена.
    """

    async def parse(pipeline, vacancy_id, text, username, allow_delete=True):
        calls.append((vacancy_id, text, username, allow_delete))
        return done() if callable(done) else done

    monkeypatch.setattr(parse_mod, "parse_and_update_vacancy", parse)
