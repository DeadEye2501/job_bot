"""Статья Telegraph: сходить по адресу и достать из страницы её текст.

Объявления в каналах сплошь и рядом умещают в пост одну шапку, а всё
остальное выносят в статью — «ПОСМОТРЕТЬ», ссылка, и там уже требования,
условия и способ отклика. Разбирать в таком объявлении без статьи нечего.

Страница разбирается по тегу `article`, а не поиском по строке: Telegraph
кладёт в него статью целиком, вместе с заголовком, и это переживает
перевёрстку, от которой поиск по именам стилей рассыпается.
"""

import logging
import re

import httpx
from bs4 import BeautifulSoup

logger = logging.getLogger(__name__)

# Адрес статьи: «https://telegra.ph/ключ». Ключ обязателен: без него это
# корень сайта, статьи за ним нет никогда.
#
# Хвост адреса кончается не на чём попало. Закрывающая скобка в него не
# входит — за подписью ссылки адрес дописывают именно в скобках
# (см. `extract_post_text`). Точка и запятая — тоже: адрес, набранный в тексте
# словами, кончается точкой конца предложения, и утащенная в адрес точка ведёт
# в никуда.
#
# Адреса залитых на Telegraph картинок («telegra.ph/file/…») отсюда не
# вычитаются, хотя статьями и не являются: тега статьи в ответе нет, и такой
# адрес честно отдаёт пустоту, ничего не портя. Ловить их отдельным правилом
# значило бы завести ветку под случай, которого в постах ещё не встречалось.
ARTICLE_URL_RE = re.compile(
    r"https?://telegra\.ph/[^\s)\]]*[^\s)\].,;:!?…»\"']"
)

# Своё время ожидания, не общее с языковой моделью: там ждут работы, здесь —
# отдачи страницы, и минуты ожидания чужого сайта задержали бы весь обход
# каналов.
FETCH_TIMEOUT_SEC = 20.0

_USER_AGENT = "Mozilla/5.0 (compatible; JobBot/1.0)"


def make_client() -> httpx.AsyncClient:
    """Клиент к Telegraph. Переходы разрешены: короткие адреса ведут через них."""
    return httpx.AsyncClient(
        timeout=FETCH_TIMEOUT_SEC,
        follow_redirects=True,
        headers={"User-Agent": _USER_AGENT},
    )


def _article_text(html: str) -> str | None:
    """Заголовок и тело статьи со страницы; пусто — статьи на ней нет.

    Пусто бывает не только от перевёрстки: по адресу статьи может лежать
    весть о том, что её снесли, и тела у неё нет.

    Заголовок вынимается из статьи до того, как та сводится к тексту: он
    лежит внутри неё же, и без этого «есть ли что-то кроме заголовка» не
    спросить. А спросить надо: статья из одного заголовка — та же пустота,
    он и так стоит в посте, а разбор примет повтор за второе название.

    Подпись автора с датой в счёт тела не идёт: Telegraph отдаёт её пустым
    тегом и наполняет уже в браузере. Начни он присылать её со страницей — и
    статья из одного заголовка перестала бы читаться как пустая.
    """
    soup = BeautifulSoup(html, "html.parser")
    article = soup.find("article")
    if article is None:
        return None
    headline = article.find("h1")
    head_text = ""
    if headline is not None:
        head_text = headline.get_text(" ", strip=True)
        headline.extract()
    body_text = article.get_text("\n", strip=True)
    if not body_text:
        return None
    return f"{head_text}\n\n{body_text}" if head_text else body_text


# Отказы, после которых страница не появится: её нет (404), она удалена
# навсегда (410), её закрыли по требованию закона (451).
#
# Перечнем, а не диапазоном 4xx, и это дороже буквы плана. Ошибиться здесь
# можно в две стороны, и цены у них разные. Принять вечное за временное стоит
# ровно вчерашнего поведения: текст вакансии не обновится, пока человек не
# нажмёт ещё раз. Принять временное за вечное — потеря без возврата: прогон
# заново сочтёт сбор полным и затрёт сохранённый текст со статьёй голой шапкой
# поста, а приём с разрешением на удаление снесёт вакансию как мусор. Включи
# сайт защиту от ботов — и 403 прилетит разом по всем статьям.
_GONE_FOR_GOOD = frozenset({404, 410, 451})


async def fetch_article(client: httpx.AsyncClient, url: str) -> str | None:
    """Текст статьи по адресу; пусто — статьи там нет. Не отдали — беда наружу.

    Два исхода разведены нарочно, и разница у них во времени. «Статьи там
    нет» — навсегда: её снесли, страницу закрыли. «Не отдали» — на час: сайт
    лежит, сеть оборвалась, нас попросили подождать. Зовущему это решает
    разное — переписывать ли сохранённый текст вакансии тем, что вышло
    собрать сейчас.

    Поэтому код ответа читается, а не сводится к одной беде: снесённая статья,
    прочитанная как «сайт лежит», навсегда запрещала бы прогону заново
    обновлять текст такой вакансии.
    """
    response = await client.get(url)
    if response.status_code in _GONE_FOR_GOOD:
        logger.info(
            "telegraph: страница %s не вернётся (%d)", url, response.status_code
        )
        return None
    response.raise_for_status()
    text = _article_text(response.text)
    if text is None:
        logger.info("telegraph: на странице %s статьи не нашлось", url)
    return text
