"""Разбор того, что ответила модель, и жалоба, когда разбор не удался."""


import json
import logging

ONLY_JSON = (
    "Никакого текста вне JSON. Никакого markdown. "
    "Никаких code-fence заборчиков. Никаких комментариев."
)
"""Хвост наставления: чем модель обязана ответить и чем не должна.

Шесть наставлений писали его своими словами, и разница была не только в
словах: у одного не было запрета на markdown, у другого — на комментарии, и
разбор спотыкался ровно там, где запрет забыли. Живёт рядом с разбором
ответа: это правило о форме ответа, а не о предмете самого наставления.
"""

QUOTE_TRANSLATION = str.maketrans({
    "“": '"',
    "”": '"',
    "‘": "'",
    "’": "'",
})


def _last_object_in(text: str) -> tuple[int, int, str] | None:
    """Последний разбираемый объект верхнего уровня и оба его края.

    Края нужны выбору между двумя прочтениями ответа: сравниваются они по
    концу, а при равном конце — по началу.

    Разбирает сам `json`, а не выражение по скобкам: скобка внутри значения —
    обычный знак строки, и ответ с шаблонизатором в перечне навыков выражение
    рвало бы пополам. Вложенный объект по той же причине отдельно не
    выхватывается: разобрав внешний, идём дальше от его конца.

    Неудача на открывающей скобке — обычный исход, а не беда: рассуждение
    модели полно скобок, за которыми объекта нет.
    """
    decoder = json.JSONDecoder()
    last: tuple[int, int, str] | None = None
    at = 0
    while (start := text.find("{", at)) != -1:
        try:
            value, end = decoder.raw_decode(text, start)
        except ValueError:
            at = start + 1
            continue
        if isinstance(value, dict):
            last = (start, end, text[start:end])
        at = end
    return last


def extract_last_json(answer: str) -> str | None:
    """Последний объект JSON из ответа модели.

    Объект ищется дважды: в тексте как есть и в нём же с выпрямленными
    кавычками. Выпрямление заведено ради моделей, ставящих ёлочки вместо
    кавычек JSON, но те же ёлочки встречаются и внутри значений по-русски, где
    выпрямление ломает годный ответ, — поэтому один из двух надо выбрать.

    Выбирается тот, чей объект **кончается позже**: ответ модель дописывает
    последним, и кончается он позже всего, что было до него. Ёлочка на месте
    кавычки JSON рвёт ответ снаружи, и в тексте как есть последним читается
    черновик из размышления — кончается он раньше, и выпрямленный ответ его
    обходит. Ёлочки внутри значения, наоборот, ломает выпрямление, и позже
    кончается текст как есть.

    При равном конце побеждает начавшийся раньше — он и есть более внешний;
    при равенстве обоих краёв — текст как есть.

    Сравнивать места можно потому, что выпрямление меняет знаки один к одному
    и длин не двигает.

    Если не разбирается ничто, отдаётся огрызок от последней открывающей
    скобки до последней закрывающей: зовущий сообщит о неразбираемом ответе
    так же, как и прежде, и в записи будет видно, обо что споткнулись.
    """
    straightened = answer.translate(QUOTE_TRANSLATION)
    best: tuple[int, int, str] | None = None
    for text in (answer, straightened):
        found = _last_object_in(text)
        if found is None:
            continue
        if best is None or (found[1], -found[0]) > (best[1], -best[0]):
            best = found
    if best is not None:
        return best[2]
    start, end = straightened.rfind("{"), straightened.rfind("}")
    return straightened[start : end + 1] if -1 < start < end else None


def json_object(answer: str, log: logging.Logger, purpose: str) -> dict | None:
    """Объект JSON из ответа модели, а неразбираемое — как отсутствие.

    Ответ модели превращают в словарь шестеро, и различаются они не разбором,
    а тем, что делают с неудачей: у одного откат `None`, у другого пара с
    причиной, у третьего «не поймали — пропускаем». Поэтому здесь только
    разбор; откат остаётся делом зовущего.

    Пишет логгером зовущего: в окне журнала у строки виден источник, и шесть
    обращений иначе схлопнулись бы под одним именем. Уровень отладочный,
    потому что о самой неудаче зовущие говорят громко и сами — общей записью
    `log_unparseable`. Здесь остаётся то, чего нет у неё: что именно не
    разобралось.
    """
    raw = extract_last_json(answer)
    if raw is None:
        log.debug("%s: в ответе модели нет объекта JSON (%r)", purpose, answer[:200])
        return None
    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        log.debug("%s: объект не разбирается (%r)", purpose, raw[:200], exc_info=True)
        return None


def log_unparseable(answer: str, log: logging.Logger, purpose: str) -> None:
    """Пожаловаться, что ответ модели не разобрался.

    Одно место на всех, кто спрашивает модель: жалоба, написанная руками,
    расходится и словами, и обрезкой — а обрезка у неё несущая, потому что
    без неё в журнал уезжает весь ответ модели целиком.

    Показываются **оба края**: у рассуждающей модели начало занято
    размышлением, а объект, из-за которого разбор и сломался, лежит в конце —
    обрезка по началу оставила бы в журнале ровно то, что не нужно.

    Сводится **место** записи, а не решение о ней: жаловаться ли и что
    вернуть, по-прежнему решает зовущий. Тем же она отличается от
    `json_object` рядом — тот говорит вполголоса и о другом: что именно не
    разобралось.
    """
    shown = answer if len(answer) <= 600 else f"{answer[:200]}…{answer[-400:]}"
    log.warning("%s: ответ модели не разобрался (%r)", purpose, shown)


def truncation_trouble(finish_reason: str | None) -> str | None:
    """Слово о том, что ответ не разобрался из-за обрыва; иначе ничего.

    Неразобранный ответ бывает двух родов, и последствия у них разные: модель
    сказала несуразицу — это отказ, модель не договорила — это «спросить не
    вышло», и вакансия ждёт следующего захода. Различают их одинаково двое
    спрашивающих, и слово у них тоже одно.
    """
    return "truncated" if finish_reason == "length" else None


def str_or_none(value) -> str | None:
    """Строка из ответа модели, а пустая и не-строка — как отсутствие.

    Модель на «нет значения» отвечает то пропуском поля, то пустой
    строкой, то пробелами, то числом; зовущим все четыре случая значат
    одно.
    """
    if not isinstance(value, str):
        return None
    return value.strip() or None


def normalize_enum(value, allowed: tuple[str, ...]) -> str | None:
    """Значение из ответа модели, сведённое к справочнику, а чужое — как
    отсутствие.

    Модель отвечает свободным текстом: то с заглавной, то с пробелами по
    краям, то словом, которого в справочнике нет вовсе. Приговор, уровень и
    формат работы после этого либо ложатся в колонку из закрытого набора,
    либо не ложатся никак — третьего колонки не принимают.
    """
    if not isinstance(value, str):
        return None
    v = value.strip().lower()
    if v in allowed:
        return v
    return None
