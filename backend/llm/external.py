"""Внешний текст в виде, пригодном для вставки в промпт."""


def wrap_external(text: str) -> str:
    """Обернуть внешний текст в ограничители блока, вырезав их из него.

    Автор текста может вставить `<<<` или `>>>` сам — тогда блок данных
    закроется досрочно, и всё, что идёт дальше, модель прочтёт как наши
    указания.

    Вырезается до неизменности, а не одним проходом: обрывки соседних
    последовательностей складываются в новый ограничитель уже после того,
    как замена по нему прошла — из `<<>>><` одним проходом выходит `<<<`.
    """
    stripped = text
    while "<<<" in stripped or ">>>" in stripped:
        stripped = stripped.replace("<<<", "").replace(">>>", "")
    return f"<<<\n{stripped}\n>>>"
