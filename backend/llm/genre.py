"""Жанр поста: зовёт ли автор на работу или предлагает себя.

Своим обращением, а не половиной вердикта о пригодности. Тот отвечает сразу на
два вопроса — «вакансия ли это» и «подходит ли она кандидату», — и они спорят:
на резюме, похожем на анкету кандидата, второй перебивает первый, и пост
получает «годится». Промахивается оценщик именно на похожих, то есть на самых
опасных: по такому посту уходит отклик с приложенным CV.

Здесь анкеты нет вовсе, и взяться похожести неоткуда: спрашивают об одном.
"""

import logging

import httpx

from adapters.lm_chat import ChatRequest, chat
from backend.llm.answers import (
    ONLY_JSON,
    json_object,
    read_with_a_second_try,
    str_or_none,
)
from backend.llm.external import external_block
from backend.llm.rules import RESUME_MARK_LINE, VACANCY_TEXT_CHARS
from backend.payloads import PostGenre

logger = logging.getLogger(__name__)

# Бюджет токенов на вердикт о жанре — тот же, что у соседей. Вопрос проще
# ихнего, но тратит их рассуждающая модель одинаково: на размышление до
# ответа. Упёршийся в предел ответ означает не «не вакансия», а «не
# спросилось», и урезанный бюджет отдавал бы человеку то, что разобралось бы.
MAX_GENRE_TOKENS = 1200
ROOMIER_GENRE_TOKENS = 2400


CLASSIFY_POST_GENRE_PROMPT = """Ты определяешь ЖАНР телеграм-поста из канала с вакансиями. Вопрос ровно один: этот пост написал НАНИМАТЕЛЬ, который зовёт кого-то на открытую роль?

О том, кому и насколько пост подходит, тебя НЕ спрашивают. Ни стек, ни грейд, ни локация, ни язык поста на ответ не влияют. Совпадение технологий с чем угодно не доказывает ничего.

РЕШАЕТ НАПРАВЛЕНИЕ, и только оно:
- ВАКАНСИЯ (is_vacancy=true): автор НАНИМАЕТ. В тексте есть обязанности будущего работника, требования К КАНДИДАТУ, условия работы, слова «мы ищем», «в команду», «требуется», «предлагаем», «зарплата от».
- НЕ ВАКАНСИЯ (is_vacancy=false): всё остальное. Прежде всего — ПОСТ СОИСКАТЕЛЯ: автор предлагает СЕБЯ, перечисляет СВОЙ опыт («у меня N лет опыта», «работал в», «умею», «I have», «I worked at»), прилагает СВОЁ резюме или портфолио, просит писать ему. Хэштеги """ + RESUME_MARK_LINE + """ — прямая примета такого поста. Сюда же реклама курса или продукта, дайджест из нескольких вакансий, новость, мем, опрос, анонс митапа, обрывок без описания работы.

ОСТОРОЖНО: пост соискателя структурно почти неотличим от вакансии — роль названа, стек перечислен, контакт есть, формат и локация бывают тоже. Именно поэтому смотреть надо не на состав полей, а на то, КТО КОМУ предлагает работу.

Верни ТОЛЬКО JSON-объект:
{"is_vacancy": true | false, "reason": "..."}

reason обязателен при любом ответе: 1 предложение с цитатой из присланного текста, доказывающей направление. Для true — слова нанимателя («ищем в команду», «обязанности», «требования»); для false — слова автора о себе или примета жанра («#cv», «ищу работу», «дайджест»). Язык reason — тот же, что у поста. Не можешь процитировать слова нанимателя — ответ false.

Примеры:

Текст: "Ищем Python-разработчика в продуктовую команду. Обязанности: разработка сервисов, код-ревью. Требования: 3+ года. Резюме @hr_anna"
Ответ: {"is_vacancy": true, "reason": "Пост от нанимателя: «Ищем Python-разработчика в продуктовую команду», перечислены обязанности и требования."}

Текст: "#cv #python #django\\n\\nПозиция: Python Developer\\nФормат: только удалённо\\nЧто могу: Django, DRF, PostgreSQL. Опыт 4 года.\\nКонтакты: @nnekojiru"
Ответ: {"is_vacancy": false, "reason": "Пост соискателя: хэштег «#cv», автор пишет «Что могу» о себе и предлагает свои контакты."}

Текст: "Ищу работу QA-инженером. 5 лет в мобильном тестировании, Appium, Postman. Резюме вышлю в личку — @tester_ann"
Ответ: {"is_vacancy": false, "reason": "Пост соискателя: «Ищу работу QA-инженером», автор перечисляет свой опыт и предлагает своё резюме."}

Текст: "Senior Product Designer at Acme Berlin. Hybrid, 2 days in the office. Tools: Figma, Sketch. CV to jobs@acme.de"
Ответ: {"is_vacancy": true, "reason": "Employer's post: an open role at Acme Berlin with working conditions and an address to send a CV to."}

Текст: "Дайджест вакансий недели. Подборка лучших предложений в IT и дизайне."
Ответ: {"is_vacancy": false, "reason": "Это дайджест-подборка, а не конкретная открытая роль: «Дайджест вакансий недели»."}
""" + ONLY_JSON


def _parse_genre(answer: str) -> PostGenre | None:
    """Жанр из ответа модели; пусто — ответ не разобрался.

    Ответ без обоснования не берётся: приговор без слов не проверить, а по
    нему удаляют строку. Вердикт без слов — самый дешёвый ответ модели, и
    именно им она пропускает резюме.
    """
    data = json_object(answer, logger, "classify_post_genre")
    if data is None:
        return None
    is_vacancy = data.get("is_vacancy")
    reason = str_or_none(data.get("reason"))
    if not isinstance(is_vacancy, bool) or reason is None:
        logger.warning(
            "classify_post_genre: ответ без жанра или без обоснования: %r", data
        )
        return None
    return PostGenre(is_vacancy=is_vacancy, reason=reason)


def _genre_request(text: str, max_tokens: int) -> ChatRequest:
    """Что спросить у модели: только сам пост, без единого слова о кандидате."""
    return ChatRequest(
        purpose="classify_post_genre",
        messages=[
            {"role": "system", "content": CLASSIFY_POST_GENRE_PROMPT},
            {
                "role": "user",
                "content": external_block(
                    text[:VACANCY_TEXT_CHARS],
                    "пост из телеграм-канала (настоящий, не пример из промпта)",
                    'Верни JSON {"is_vacancy": ..., "reason": ...}.',
                ),
            },
        ],
        max_tokens=max_tokens,
    )


async def classify_post_genre(
    text: str, client: httpx.AsyncClient, model: str
) -> tuple[PostGenre | None, str | None]:
    """Жанр поста либо причина, по которой спросить не вышло.

    Различие то же, что у соседей: «модель ответила» — приговор, «спросить не
    вышло» — не приговор ничему. Второе зовущий обязан отличать, потому что по
    первому строку удаляют.

    Неразобранный ответ причиной не считается и жанром тоже: пустота в обоих
    значениях означает «не знаем», и зовущий пропускает пост дальше — к
    вердикту о пригодности. Закрытая дверь тут была бы дороже открытой:
    удалять по неразобранному ответу нельзя.
    """
    if not text:
        return None, None
    return await read_with_a_second_try(
        lambda room: chat(client, model, _genre_request(text, room), logger),
        _parse_genre,
        (MAX_GENRE_TOKENS, ROOMIER_GENRE_TOKENS),
        (logger, "classify_post_genre"),
    )
