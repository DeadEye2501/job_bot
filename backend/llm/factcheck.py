"""Сверка письма-отклика с тем, что о кандидате известно."""


import logging
import time

import httpx

from adapters.lm_chat import CUT_BY_LIMIT, ChatRequest, chat
from backend.incoming import normalize_enum
from backend.llm.answers import ONLY_JSON, json_object, log_unparseable
from backend.llm.external import external_block
from backend.llm.rules import FACT_KINDS, NOT_IN_THE_PROFILE
from backend.incoming import str_list

logger = logging.getLogger(__name__)


# Бюджет токенов на сверку письма. Четырёхсот мало по той же причине, по какой
# их мало самому письму (`MAX_COVER_LETTER_TOKENS`): размышление съедает их
# целиком, а после него нужны ещё вердикт и до трёх замечаний словами.
MAX_FACTCHECK_TOKENS = 1500


FACT_CHECK_COVER_LETTER_PROMPT = """Ты — фактчекер сопроводительных писем. Тебе дают (1) блок «Информация о кандидате» (это единственный источник правды) и (2) текст письма. Ты должен проверить, что КАЖДЫЙ фактический claim в письме подтверждён блоком кандидата.

Что считается claim'ом и подлежит проверке:
""" + FACT_KINDS + """

Что НЕ считается claim'ом:
- Название вакансии и канал, названные в поле «О вакансии»: они пришли из самого объявления, а не от кандидата, и в блоке кандидата их нет и не должно быть.
- Общие вежливые фразы («заинтересовала позиция», «готов обсудить детали», «здравствуйте»).
- Указание на интерес к задаче без конкретики о собственном опыте.
- Всё, что письмо говорит о работодателе и вакансии (название компании, её тип и отрасль, задачи, формат): это сведения о вакансии, а не о кандидате.

Правила вердикта:
- Если в письме есть claim, которого """ + NOT_IN_THE_PROFILE + """ — verdict: "reject".
- Если claim в письме привязан к НЕ ТОЙ компании / роли / периоду или проекту, чем в блоке (например, в блоке достижение у текущей компании, а письмо приписывает его «прошлому стартапу»; в блоке пункт у проекта, а письмо приписывает его работе в компании) — verdict: "reject".
- Если тип компании, где работал кандидат («стартап», «сеть» и т.п.), не подтверждён блоком — verdict: "reject".
- Если все claim'ы корректно подтверждены блоком — verdict: "ok".

КРИТИЧЕСКИ ВАЖНО — не over-reject'и за парафраз/синоним/обобщение:
- Парафраз и синоним = ОК: «повар» ↔ «работал на кухне»; «вёл бухучёт в учётной программе A» ↔ «опыт бухгалтерского учёта»; «бэкенд-разработчик» ↔ «серверная разработка».
- Обобщение = ОК: конкретное в блоке покрывает общее в письме («станок модели A» ↔ «работа на станках с ЧПУ»; «кассовая система B» ↔ «работа на кассе»).
- Оценочное слово при факте из блока = ОК: «сильный», «глубокий» фактом не являются.
- Утверждение об опыте без названного факта, привязанное к вакансии («есть опыт по вашему стеку», «делал похожее»), — claim о совпадении с вакансией; блок его не подтверждает — reject.
- Зацепки за вакансию без претензии на собственный опыт («заинтересовала задача», «близка предметная область») = ОК. Это не claim о кандидате.
- Если сомневаешься, подтверждено или нет — выбирай "ok". Reject — только когда явно видишь выдуманный факт или неправильную атрибуцию.
- Перевод = ОК. Письмо может быть на другом языке, чем блок кандидата: тот же факт другими словами на другом языке — пересказ, а не выдумка. Имя латиницей — то же имя.

Возвращай ТОЛЬКО JSON-объект:
{"verdict": "ok" | "reject", "issues": ["краткое описание проблемы 1", ...]}

Поле issues:
- При verdict="ok" — пустой массив [].
- При verdict="reject" — список 1-3 коротких описаний проблем (что именно неправильно). Не цитируй много, пиши тезисом.

Примеры (для калибровки, реальные блоки и письма будут другими):

Пример 1 — ok:
Блок: "Роль: прораб. Опыт работы: - Компания X (прораб, 03.2019 — настоящее время): сдача жилого объекта на два месяца раньше срока."
Письмо: "Здравствуйте! Руковожу строительными объектами, сдавал объект досрочно. Давайте обсудим детали."
Ответ: {"verdict": "ok", "issues": []}
Пояснение (не включай в ответ): «руковожу объектами» — пересказ роли прораба, «сдавал досрочно» подтверждено явно.

Пример 2 — reject (выдуманный инструмент и обязанность):
Блок: "Навыки: кассовая система A. Опыт работы: - Магазин Y (продавец-кассир, 05.2021 — 08.2023)."
Письмо: "Здравствуйте! Работал с кассовой системой B и вёл инвентаризацию склада."
Ответ: {"verdict": "reject", "issues": ["кассовой системы B нет в блоке кандидата", "инвентаризации склада нет в блоке кандидата"]}

Пример 3 — reject (неправильная атрибуция):
Блок: "Опыт работы: - Компания Z (диспетчер, 02.2022 — настоящее время): перестроил маршруты доставки. - Компания W (водитель-экспедитор, 2018 — 01.2022)."
Письмо: "На прошлой работе перестроил маршруты доставки."
Ответ: {"verdict": "reject", "issues": ["перестройка маршрутов в блоке относится к текущему месту (Компания Z), а не к прошлому (Компания W)"]}

""" + ONLY_JSON


def _factcheck_request(profile_text: str, letter: str, about: str) -> ChatRequest:
    """Что спросить у модели: анкета как источник правды, вакансия и письмо.

    Вакансия названа отдельным полем нарочно: её название и канал письмо
    поминает всегда, а в анкете кандидата их нет и быть не может — сверка
    принимала их за выдумку и браковала годное письмо.
    """
    user_msg = external_block(
        "Информация о кандидате (источник правды):\n"
        f"{profile_text}\n\n"
        f"О вакансии (заведомо не claim о кандидате):\n{about or '—'}\n\n"
        f"Текст письма:\n{letter}",
        "данные для сверки",
        'Верни JSON {"verdict": ..., "issues": [...]}.',
    )
    return ChatRequest(
        purpose="factcheck_cover_letter",
        messages=[
            {"role": "system", "content": FACT_CHECK_COVER_LETTER_PROMPT},
            {"role": "user", "content": user_msg},
        ],
        max_tokens=MAX_FACTCHECK_TOKENS,
    )


def _verdict_of(obj: dict, elapsed: float) -> tuple[bool, list[str]]:
    """Разобрать ответ сверки: пускать ли письмо и с какими замечаниями.

    Незнакомый вердикт пропускает письмо: сверка — второй слой поверх уже
    усиленного наставления, и глушить отправку из-за её невнятного ответа
    хуже, чем пропустить письмо, которое первый слой счёл годным. Замечаний
    берётся не больше трёх — их читает человек, а не машина.
    """
    raw = obj.get("verdict")
    verdict = normalize_enum(raw, ("ok", "reject"))
    # Общим приведением, а не обходом: ответь модель одной строкой вместо
    # списка, обход рассыпал бы её по буквам и показал человеку три знака
    # вместо трёх замечаний.
    issues = str_list(obj.get("issues"))[:3]
    if verdict == "reject":
        logger.debug("factcheck_cover_letter: reject in %.2fs", elapsed)
        return False, issues
    if verdict == "ok":
        logger.debug("factcheck_cover_letter: ok in %.2fs", elapsed)
        return True, []
    # В журнал идёт сырое написание, а не сведённое: сведённое здесь всегда
    # пусто, и три разных беды — поля нет, пришло число, пришло незнакомое
    # слово — слились бы в одну запись. Чем именно отвечает модель, видно
    # только отсюда.
    logger.warning(
        "factcheck_cover_letter: unknown verdict %r — fail-open (%.2fs)",
        raw, elapsed,
    )
    return True, []


async def factcheck_cover_letter(
    profile_text: str,
    letter: str,
    client: httpx.AsyncClient,
    model: str,
    *,
    about: str = "",
) -> tuple[bool, list[str]]:
    """Возвращает (ok, issues). ok=True, если все факты в письме покрыты
    анкетой `profile_text`.

    Открывается наружу при **любой** беде — сетевой ошибке, невалидном JSON,
    оборванном ответе, — чтобы временный сбой модели не блокировал отправку:
    первичное наставление уже усилено запретами на выдумывание, а сверка это
    второй слой поверх него.

    ``about`` — чем письмо вызвано (название вакансии, канал). Уходит модели
    отдельным полем и заведомо не считается утверждением о кандидате: иначе
    сверка ловила бы в нём «непокрытые профилем факты» и отбивала годные
    письма.
    """
    request = _factcheck_request(profile_text, letter, about)
    # Время засекается после сборки запроса: в отладочной строке ниже
    # называется срок ответа модели, а не наша склейка текста.
    t0 = time.monotonic()
    reply = await chat(client, model, request, logger)
    if reply.text is None:
        return True, []
    if reply.finish_reason == CUT_BY_LIMIT:
        # Обрыв — та же беда, что и молчание провайдера: модель не
        # договорила, и её незаконченный отказ остановил бы отклик, который
        # первый слой наставления счёл годным.
        logger.warning("factcheck_cover_letter: ответ оборван, письмо пропускаю")
        return True, []
    obj = json_object(reply.text, logger, "factcheck_cover_letter")
    if obj is None:
        log_unparseable(reply.text, logger, "factcheck_cover_letter")
        return True, []
    return _verdict_of(obj, time.monotonic() - t0)
