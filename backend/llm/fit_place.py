"""Один вопрос о вакансии: может ли кандидат работать там, где она требует.

Мерки две — где кандидат живёт и его гражданство. Своим зовом, а не мерой в предпочтениях: в общем зове запрет одного критерия
переносится на другой (`flows/fit_refusal`). Предпочтения сюда приходят только
затем, чтобы узнать, разрешён ли переезд: без этих слов кандидат к переезду не
готов.

Правила записаны через слот, а не через его содержимое: ни страны, ни города
здесь не появляется — у человека они бывают любые.
"""


import logging

import httpx

from backend.payloads import FitValidation, ParsedVacancy

from backend.llm.candidate import CandidateProfile, format_text
from backend.llm.fit import ANSWER_RULES, VERDICT_SCOPE, FitQuestion, ask_fit, vacancy_text

logger = logging.getLogger(__name__)

PURPOSE = "validate_place_fit"

PLACE_FIT_PROMPT = """Ты проверяешь объявление о вакансии по ОДНОМУ критерию: может ли кандидат работать там, где требует вакансия, — по месту, где он живёт, и по гражданству.

""" + VERDICT_SCOPE + """

КАНДИДАТ:
- Где живёт: {CANDIDATE_LOCATION}
- Гражданство: {CANDIDATE_CITIZENSHIP}
- Предпочтения (отсюда берётся только сказанное о местах: куда кандидат готов переехать или ездить и где бывать или работать не готов): {FREE_PREFERENCES}

Каждое правило ниже применяется, только если у кандидата есть его данные; «—» значит данных нет.

МЕСТО. Вакансия требует присутствия, когда каждый её вариант работы привязан к месту: офис или гибрид в названном городе, регионе или стране; удалённая работа только для тех, кто находится в названной стране или регионе; разрешение на работу или налоговое резидентство в названной стране. Место компании, её команды или юрлица требованием не является, пока вакансия не говорит, что работать нужно там; часы работы и часовой пояс — тоже не требование места.
Место требования сравнивается с тем, где кандидат живёт, на том уровне, который назвала вакансия. Место кандидата входит во все большие места, которые его содержат: город — в свою страну, страна — в регион или союз стран. Место кандидата названо крупнее требования (только страна, а вакансия называет город в ней) — по месту не отказывай. Разрешение на работу и резидентство кандидат выполняет, если живёт в этой стране или имеет её гражданство.
Кандидат живёт не там — работа требует переезда, и вердикт reject, пока предпочтения прямо не разрешают переезд туда; разрешение без названного места действует на любое место.
Где кандидат по предпочтениям не готов бывать или работать — вакансия, которая прямо требует там бывать или работать (офис, командировки, выезды), получает reject.

ГРАЖДАНСТВО. Вакансия требует определённого гражданства и не предлагает ему замены — reject, если у кандидата гражданство другое. Вакансия исключает названные места или гражданства — reject, если кандидат живёт там или у него это гражданство.

reject ставится только по прямому указанию в тексте вакансии.

""" + ANSWER_RULES + """

--- ПРИМЕРЫ ФОРМАТА (НЕ КОПИРУЙ reason ДОСЛОВНО; данные в примерах выдуманы) ---

Пример 1 (reject — гибрид в другом городе):
Где живёт: страна B, город B1. Гражданство: страна B. Предпочтения: —. Текст: "Гибрид, два дня в неделю в офисе в городе B2."
Ответ: {"reason": "Нужно бывать в офисе в городе B2 два дня в неделю.", "verdict": "reject"}

Пример 2 (reject — удалёнка только из другой страны):
Где живёт: страна B, город B1. Гражданство: страна B. Предпочтения: —. Текст: "Удалённо, только для находящихся в стране A."
Ответ: {"reason": "Удалённая работа только для находящихся в стране A.", "verdict": "reject"}

Пример 3 (reject — гражданство без замены):
Где живёт: страна B, город B1. Гражданство: страна B. Предпочтения: —. Текст: "Удалённо. Обязательно гражданство страны A."
Ответ: {"reason": "Требуется гражданство страны A.", "verdict": "reject"}

Пример 4 (reject — переезд оплачивают, но предпочтения о нём молчат):
Где живёт: страна B, город B1. Гражданство: страна B. Предпочтения: —. Текст: "Офис в городе A1, релокация за счёт компании."
Ответ: {"reason": "Работа в офисе в городе A1, с переездом.", "verdict": "reject"}

Пример 5 (reject — оба варианта привязаны к одной стране):
Где живёт: страна B, город B1. Гражданство: страна B. Предпочтения: —. Текст: "Офис в городе A1 или удалённо из страны A."
Ответ: {"reason": "Оба варианта требуют находиться в стране A: офис в A1 или удалёнка только из страны A.", "verdict": "reject"}

Пример 6 (reject — выезды туда, где кандидат бывать не готов):
Где живёт: страна B, город B1. Гражданство: страна B. Предпочтения: не готов бывать в стране A. Текст: "Удалённо, раз в квартал выезд в офис в стране A."
Ответ: {"reason": "Требуются выезды в офис в стране A раз в квартал.", "verdict": "reject"}

Пример 7 (fit — офис как вариант к удалёнке):
Где живёт: страна B, город B1. Гражданство: страна B. Предпочтения: —. Текст: "Удалённо или гибрид, офис в городе A1."
Ответ: {"reason": "Работа без присутствия возможна: офис в A1 предложен как вариант.", "verdict": "fit"}

Пример 8 (fit — переезд разрешён предпочтениями):
Где живёт: страна B, город B1. Гражданство: страна B. Предпочтения: готов к переезду в страну C. Текст: "Офис в городе C1 страны C, помогаем с переездом."
Ответ: {"reason": "Офис в стране C, переезд туда разрешён.", "verdict": "fit"}

Пример 9 (fit — офис в стране кандидата, город не назван):
Где живёт: страна B, город B1. Гражданство: —. Предпочтения: —. Текст: "Офис в стране B."
Ответ: {"reason": "Вакансия называет только страну B.", "verdict": "fit"}

Пример 10 (fit — удалёнка без ограничений по месту):
Где живёт: страна B, город B1. Гражданство: страна B. Предпочтения: —. Текст: "Полностью удалённо, из любой страны."
Ответ: {"reason": "Удалённая работа из любой страны.", "verdict": "fit"}

--- КОНЕЦ ПРИМЕРОВ ---"""


def _prompt_for(profile: CandidateProfile) -> str:
    """Наставление с подставленными местом, гражданством и предпочтениями."""
    return (
        PLACE_FIT_PROMPT
        .replace("{CANDIDATE_LOCATION}", format_text(profile.location))
        .replace("{CANDIDATE_CITIZENSHIP}", format_text(profile.citizenship))
        .replace("{FREE_PREFERENCES}", format_text(profile.free_preferences))
    )


async def validate_place_fit(
    parsed: ParsedVacancy, raw_text: str, client: httpx.AsyncClient, model: str,
    *, profile: CandidateProfile,
) -> tuple[FitValidation | None, str | None]:
    """Может ли кандидат работать там, где требует вакансия, и, если не спросилось, почему."""
    logger.debug("%s: title=%r", PURPOSE, parsed.title)
    return await ask_fit(
        FitQuestion(purpose=PURPOSE, prompt=_prompt_for(profile)),
        vacancy_text(raw_text),
        client,
        model,
    )
