"""Один вопрос о вакансии: та ли это профессия.

Кандидат приходит сюда двумя строками — профессия и навыки, — и больше ничем.
Ни локации, ни языков, ни предпочтений, ни грейда с форматом зов не видит:
о том, чего ему не давали, он не ошибётся.
"""


from backend.llm.candidate import CandidateProfile, format_known_skills, format_text
from backend.llm.fit import ANSWER_RULES, VERDICT_SCOPE, fit_question, vacancy_block

PURPOSE = "validate_role_fit"

ROLE_FIT_PROMPT = """Ты проверяешь объявление о вакансии по ОДНОМУ критерию: совпадает ли профессия (основная роль) вакансии с профессией кандидата.

""" + VERDICT_SCOPE + """

КАНДИДАТ (это и только это — мерка):
- Профессия / основная роль: {CANDIDATE_TITLE}
- Навыки (формат: каноническое_имя — алиасы):
{CANDIDATE_SKILLS}

ПРИНЦИП ОЦЕНКИ:
- Сравнение симметричное: с одной стороны — то, что РЕАЛЬНО НАПИСАНО в посте; с другой — две строки выше. Никаких допущений ни про того, ни про другого.
- Профессию кандидата задают обе строки вместе: должность и навыки. Обе «—» — ставь fit.

reject ставится ТОЛЬКО когда основная работа вакансии принадлежит другой профессиональной области и с работой кандидата не пересекается по сути (повар vs официант; бухгалтер vs юрист; дизайнер vs маркетолог; водитель vs кладовщик; медсестра vs администратор клиники и т. п.).

НЕ блокер:
- другое название той же работы: решает описание работы, а не заголовок;
- смежная профессия, чья работа частично совпадает с работой кандидата;
- инструменты, программы, оборудование или технологии вакансии, которых нет в навыках кандидата: профессию задаёт работа, а не набор инструментов;
- вариативная роль (универсал, «многостаночник»), где часть работы — работа кандидата.

Всё остальное — не твой критерий. Размер компании, зарплата, формат работы, язык общения, страна офиса, требуемый опыт, отсутствие описания компании — ни одно из этого не повод для reject здесь, и в reason им не место.

""" + ANSWER_RULES + """

--- ПРИМЕРЫ ФОРМАТА (НЕ КОПИРУЙ reason ДОСЛОВНО; примеры намеренно из разных профессий — логика не зависит от домена) ---

Пример 1 (reject — другая профессиональная область):
CANDIDATE_TITLE: UX/UI-дизайнер. Текст: "Ищем SMM-менеджера: ведение соцсетей, контент-план, работа с блогерами."
Ответ: {"reason": "Основная роль вакансии — SMM-менеджер: ведение соцсетей и контент-план.", "verdict": "reject"}

Пример 2 (fit — та же работа, программа кандидату незнакома):
CANDIDATE_TITLE: Бухгалтер. CANDIDATE_SKILLS: 1С. Текст: "Нужен бухгалтер на первичную документацию, работа в SAP."
Ответ: {"reason": "Роль вакансии — бухгалтер: «Нужен бухгалтер на первичную документацию».", "verdict": "fit"}

Пример 3 (fit — смежная профессия с общей работой):
CANDIDATE_TITLE: Кондитер. Текст: "В пекарню нужен пекарь: замес теста, выпечка хлеба и сдобы."
Ответ: {"reason": "Роль вакансии — пекарь: замес теста и выпечка сдобы входят и в работу кондитера.", "verdict": "fit"}

Пример 4 (fit — роль названа, критерий не нарушен):
CANDIDATE_TITLE: Флорист. Текст: "Ищем флориста в студию, пишите @hr_anna"
Ответ: {"reason": "Роль вакансии — флорист: «Ищем флориста в студию».", "verdict": "fit"}

--- КОНЕЦ ПРИМЕРОВ ---

Напоминание: единственный твой вопрос — профессия. Не видишь в тексте другой профессиональной области — ставь fit."""


def _prompt_for(profile: CandidateProfile) -> str:
    """Наставление с подставленными мерками кандидата."""
    return (
        ROLE_FIT_PROMPT
        .replace("{CANDIDATE_TITLE}", format_text(profile.title))
        .replace("{CANDIDATE_SKILLS}", format_known_skills(profile.known_skills))
    )


validate_role_fit = fit_question(PURPOSE, _prompt_for, vacancy_block)
"""Та ли это профессия и, если не спросилось, почему."""
