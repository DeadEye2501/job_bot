"""Один вопрос о вакансии: нарушает ли она то, что кандидат написал словами.

Свободный текст предпочтений — единственная мерка этого зова. Где кандидат
живёт и его гражданство сюда не приходят: о месте судит соседний зов
(`fit_place`), и двое судящих об одном разошлись бы.

Правила наставления записаны через слот, а не через его содержимое: ни
страны, ни города, ни отрасли здесь не появляется — настройки у человека
бывают любые, и привязывать к ним общий шаблон нельзя.
"""


from backend.llm.candidate import CandidateProfile, format_text
from backend.llm.fit import ANSWER_RULES, VERDICT_SCOPE, fit_question

PURPOSE = "validate_preferences_fit"

PREFERENCES_FIT_PROMPT = """Ты проверяешь объявление о вакансии по ОДНОМУ критерию: нарушает ли она личные предпочтения кандидата, записанные им свободным текстом.

""" + VERDICT_SCOPE + """

КАНДИДАТ:
- Личные предпочтения (свободный текст; любой записанный в нём запрет — жёсткий блокер, кроме сказанного о месте, гражданстве, переезде и формате работы — это судят другие): {FREE_PREFERENCES}

Если предпочтения — «—», блокера нет вовсе, ставь fit.

ГРАНИЦЫ ОГРАНИЧЕНИЯ (главное правило этого зова):
- Ограничение из свободного текста действует ровно в тех границах, в которых записано. Названо для конкретных компаний или отраслей — на другие не распространяется. Расширять его запрещено.
- Требование, о котором в предпочтениях не сказано ни слова, блокером не является. Молчание — не запрет.

reject ставится ТОЛЬКО когда в тексте вакансии есть ПРЯМОЕ указание, нарушающее конкретный записанный блокер. Триггер обязан быть в тексте: домысел о том, что «скорее всего подразумевается», запрещён.

Совпадение профессии и навыков, уровень языка, грейд, формат работы, место работы, гражданство и переезд судят другие зовы — в reason им не место. Записанный в предпочтениях запрет о чём угодно другом (деньги, размер или тип компании, инструмент, график, вид оформления, командировки вообще) — твой критерий.

""" + ANSWER_RULES + """

--- ПРИМЕРЫ ФОРМАТА (НЕ КОПИРУЙ reason ДОСЛОВНО; предпочтения в примерах выдуманы и к настоящим отношения не имеют) ---

Пример 1 (reject — прямое нарушение записанного блокера):
FREE_PREFERENCES: не работаю с гемблингом. Текст: "Продуктовая команда онлайн-казино, ставки и слоты."
Ответ: {"reason": "Вакансия в гемблинге: онлайн-казино, ставки и слоты.", "verdict": "reject"}

Пример 2 (fit — предпочтения молчат об этом требовании):
FREE_PREFERENCES: не работаю в табачной отрасли. Текст: "Сеть кофеен ищет бариста в утренние смены."
Ответ: {"reason": "Вакансия в сети кофеен — записанных блокеров текст не нарушает.", "verdict": "fit"}

--- КОНЕЦ ПРИМЕРОВ ---

Напоминание: единственная твоя мерка — записанный свободным текстом блокер, взятый ровно в тех границах, в которых он записан. Нет в тексте прямого нарушения — fit."""


def _prompt_for(profile: CandidateProfile) -> str:
    """Наставление с подставленными предпочтениями."""
    return PREFERENCES_FIT_PROMPT.replace("{FREE_PREFERENCES}", format_text(profile.free_preferences))


validate_preferences_fit = fit_question(PURPOSE, _prompt_for)
"""Нарушены ли записанные словами предпочтения и, если не спросилось, почему."""
