"""Один вопрос о вакансии: нарушает ли она то, что кандидат написал словами.

Свободный текст предпочтений — единственная мерка этого зова; локация стоит
рядом справкой, потому что без неё «не готов к переезду» не с чем сопоставить.
Отдельным критерием локация не является: где стоит офис, неважно, пока формат
работы человека устраивает, а куда он готов ехать — он пишет словами, и это
уже предпочтение.

Два правила наставления записаны через слот, а не через его содержимое: ни
страны, ни города, ни отрасли здесь не появляется — настройки у человека
бывают любые, и привязывать к ним общий шаблон нельзя.
"""


import logging

import httpx

from backend.payloads import FitValidation, ParsedVacancy

from backend.llm.candidate import CandidateProfile, format_text
from backend.llm.fit import ANSWER_RULES, VERDICT_SCOPE, FitQuestion, ask_fit, vacancy_text

logger = logging.getLogger(__name__)

PURPOSE = "validate_preferences_fit"

PREFERENCES_FIT_PROMPT = """Ты проверяешь Telegram-пост о вакансии по ОДНОМУ критерию: нарушает ли она личные предпочтения кандидата, записанные им свободным текстом.

""" + VERDICT_SCOPE + """

КАНДИДАТ:
- Личные предпочтения (свободный текст; относись как к жёстким блокерам, если написано «не готов / не рассматриваю / только …»): {FREE_PREFERENCES}
- Где кандидат находится (СПРАВКА, а не критерий — нужна только чтобы понять, о чём говорят его предпочтения): {CANDIDATE_LOCATION}

Если {FREE_PREFERENCES} = «—» — блокера нет вовсе, ставь fit.

ГРАНИЦЫ ОГРАНИЧЕНИЯ (главное правило этого зова):
- Ограничение из свободного текста действует ровно в тех границах, в которых записано. Названо для конкретных стран, компаний или отраслей — на другие не распространяется. Расширять его запрещено.
- Место, совпадающее с локацией кандидата, поводом для отказа не бывает — кандидат уже там.
- Требование, о котором в предпочтениях не сказано ни слова, блокером не является. Молчание — не запрет.

reject ставится ТОЛЬКО когда в тексте вакансии есть ПРЯМОЕ указание, нарушающее конкретный записанный блокер. Триггер обязан быть в тексте: домысел о том, что «скорее всего подразумевается», запрещён.

Всё остальное — не твой критерий: профессия, стек, языки, грейд, формат работы, зарплата, размер компании. В reason им не место. Сам по себе город офиса тоже не твой критерий: он становится им, только если предпочтения прямо говорят о таких местах.

""" + ANSWER_RULES + """

--- ПРИМЕРЫ ФОРМАТА (НЕ КОПИРУЙ reason ДОСЛОВНО; предпочтения в примерах выдуманы и к настоящим отношения не имеют) ---

Пример 1 (reject — прямое нарушение записанного блокера):
FREE_PREFERENCES: не работаю с гемблингом. Текст: "Продуктовая команда онлайн-казино, ставки и слоты."
Ответ: {"verdict": "reject", "reason": "Вакансия в гемблинге: онлайн-казино, ставки и слоты."}

Пример 2 (reject — запрет назван для конкретных стран, и вакансия попадает ровно в них):
FREE_PREFERENCES: не готов присутствовать на территории страны A. CANDIDATE_LOCATION: страна B, город B1. Текст: "Офис в стране A, присутствие обязательно 3 дня в неделю."
Ответ: {"verdict": "reject", "reason": "Требуется присутствие в офисе в стране A три дня в неделю."}

Пример 3 (fit — офис в городе, где кандидат и живёт):
FREE_PREFERENCES: не готов присутствовать на территории страны A — никакого офиса, релокации или присутствия в этих странах. CANDIDATE_LOCATION: страна B, город B1. Текст: "Гибрид, офис в городе B1, возможны перемещения между офисами."
Ответ: {"verdict": "fit", "reason": "Офис назван в городе B1 — там же, где кандидат; запрет предпочтений про другие страны."}
Пояснение (НЕ возвращай его в JSON): ограничение записано для страны A, и на город B1 оно не распространяется. Расширять запрет на другие места запрещено.

Пример 4 (fit — предпочтения молчат об этом требовании):
FREE_PREFERENCES: не работаю с криптой. Текст: "Финтех-продукт для банков, работа с платёжными шлюзами."
Ответ: {"verdict": "fit", "reason": "Продукт назван финтехом для банков — записанных блокеров текст не нарушает."}

--- КОНЕЦ ПРИМЕРОВ ---

Напоминание: единственная твоя мерка — записанный свободным текстом блокер, взятый ровно в тех границах, в которых он записан. Нет в тексте прямого нарушения — fit."""


def _prompt_for(profile: CandidateProfile) -> str:
    """Наставление с подставленными предпочтениями и справкой о локации."""
    return (
        PREFERENCES_FIT_PROMPT
        .replace("{FREE_PREFERENCES}", format_text(profile.free_preferences))
        .replace("{CANDIDATE_LOCATION}", format_text(profile.location))
    )


async def validate_preferences_fit(
    parsed: ParsedVacancy, raw_text: str, client: httpx.AsyncClient, model: str,
    *, profile: CandidateProfile,
) -> tuple[FitValidation | None, str | None]:
    """Нарушены ли записанные словами предпочтения и, если не спросилось, почему."""
    logger.debug("%s: title=%r", PURPOSE, parsed.title)
    return await ask_fit(
        FitQuestion(purpose=PURPOSE, prompt=_prompt_for(profile)),
        vacancy_text(raw_text),
        client,
        model,
    )
