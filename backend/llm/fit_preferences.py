"""Один вопрос о вакансии: нарушает ли она запреты кандидата.

Запреты — строки предпочтений анкеты вида «запрет»; пожеланий и сведений этот
зов не видит вовсе: увидев их, он принимает за запрет и пожелание для
откликов. Запретов нет — зов не нужен, и зовущий его не зовёт.

Правила наставления записаны через слот, а не через его содержимое: ни
страны, ни города, ни отрасли здесь не появляется — запреты у человека бывают
любые, и привязывать к ним общий шаблон нельзя.
"""


from backend.llm.candidate import CandidateProfile
from backend.llm.fit import ANSWER_RULES, VERDICT_SCOPE, fit_question

PURPOSE = "validate_preferences_fit"

PREFERENCES_FIT_PROMPT = """Ты проверяешь объявление о вакансии по ОДНОМУ критерию: нарушает ли оно запреты кандидата.

""" + VERDICT_SCOPE + """

ЗАПРЕТЫ КАНДИДАТА (каждый — то, чего он не примет в работе ни при каких условиях):
{BANS}

КАК СВЕРЯТЬ:
- reject ставится ТОЛЬКО когда в тексте вакансии ЯВНО есть то, что запрещено. Триггер обязан быть в тексте: домысел о том, что «скорее всего подразумевается», запрещён.
- Запрет действует ровно в тех границах, в которых записан. Назван для конкретных компаний, отраслей или мест — на другие не распространяется. Расширять его запрещено.
- Требование вакансии, о котором запреты молчат, нарушением не является.
- Запрет на присутствие в стране или городе нарушает только вакансия, которая требует там находиться: офис, гибрид, выезды, удалённая работа только для находящихся там. Откуда компания, где её офис или юрлицо — с присутствием кандидата никак не связано: удалённая работа на компанию из этой страны запрет не нарушает.

Совпадение профессии и навыков, уровень языка и грейд судят другие зовы — в reason им не место.

""" + ANSWER_RULES + """

--- ПРИМЕРЫ ФОРМАТА (НЕ КОПИРУЙ reason ДОСЛОВНО; запреты в примерах выдуманы и к настоящим отношения не имеют) ---

Пример 1 (reject — прямое нарушение запрета):
ЗАПРЕТЫ: - не работаю с гемблингом. Текст: "Продуктовая команда онлайн-казино, ставки и слоты."
Ответ: {"reason": "Вакансия в гемблинге: онлайн-казино, ставки и слоты.", "verdict": "reject"}

Пример 2 (fit — запреты молчат об этом требовании):
ЗАПРЕТЫ: - не работаю в табачной отрасли. Текст: "Сеть кофеен ищет бариста в утренние смены."
Ответ: {"reason": "Вакансия в сети кофеен — запретов текст не нарушает.", "verdict": "fit"}

Пример 3 (fit — компания из страны, где кандидат быть не готов, но работа удалённая):
ЗАПРЕТЫ: - не готов физически находиться в стране A. Текст: "Крупный банк страны A ищет разработчика, формат работы: удалённо."
Ответ: {"reason": "Работа удалённая — находиться в стране A не требуется; откуда банк, к присутствию не относится.", "verdict": "fit"}

Пример 4 (reject — работа требует находиться там, где кандидат быть не готов):
ЗАПРЕТЫ: - не готов физически находиться в стране A. Текст: "Гибрид: три дня в неделю в офисе в городе A1 страны A."
Ответ: {"reason": "Нужно три дня в неделю работать в офисе в городе A1 страны A.", "verdict": "reject"}

--- КОНЕЦ ПРИМЕРОВ ---

Напоминание: единственная твоя мерка — запреты выше, взятые ровно в тех границах, в которых записаны. Нет в тексте явного нарушения или сомневаешься — fit."""


def _prompt_for(profile: CandidateProfile) -> str:
    """Наставление с подставленными запретами — по одному на строку."""
    return PREFERENCES_FIT_PROMPT.replace("{BANS}", "\n".join(f"- {ban}" for ban in profile.bans))


validate_preferences_fit = fit_question(PURPOSE, _prompt_for)
"""Нарушены ли запреты кандидата и, если не спросилось, почему."""
