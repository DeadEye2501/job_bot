def seeker_task(host: str, last_run: datetime | None, limit: int, today: date) -> str:
    """Стартовое задание искателя на агрегаторе."""
    return "\n".join([f"Сайт агрегатора: https://{host}/", *_bounds(last_run, limit, today)])


def web_seeker_task(
    aggregator_hosts: list[str], last_run: datetime | None, limit: int, today: date
) -> str:
    """Стартовое задание искателя по сети."""
    return "\n".join([
        "Агрегаторы, которые обходить стороной: " + (", ".join(aggregator_hosts) or "нет"),
        *_bounds(last_run, limit, today),
    ])


def blacklisted_sites(hosts: list[str]) -> str:
    """Строка задания искателя по сети: сайты, отсеянные человеком."""
    return "Сайты в чёрном списке: " + (", ".join(hosts) or "нет")


def _bounds(last_run: datetime | None, limit: int, today: date) -> list[str]:
    """Рамки обхода, общие обоим искателям: с какого времени, сколько, какое сегодня."""
    return [
        _since(last_run),
        f"Можно передать вакансий, новых для приложения: {limit}",
        f"Сегодня: {today.isoformat()}",
    ]


def _since(last_run: datetime | None) -> str:
    if last_run is None:
        return "Прошлый обход: не было, это первый обход"
    return f"Прошлый обход начался: {last_run.strftime('%Y-%m-%d %H:%M')} UTC"
