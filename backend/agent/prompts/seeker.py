@dataclass(frozen=True)
class SeekBounds:
    """Рамки обхода, общие обоим искателям: с какого времени, сколько вакансий
    передать, какое сегодня и на каких языках составлять запросы — языки решает
    `domain/language_choice`."""

    last_run: datetime | None
    limit: int
    today: date
    languages: list[str]


def seeker_task(host: str, bounds: SeekBounds) -> str:
    """Стартовое задание искателя на агрегаторе."""
    return "\n".join([f"Сайт агрегатора: https://{host}/", *_bounds(bounds)])


def web_seeker_task(aggregator_hosts: list[str], barred_hosts: list[str], bounds: SeekBounds) -> str:
    """Стартовое задание искателя по сети; `barred_hosts` — сайты, отсеянные
    человеком."""
    return "\n".join([
        "Агрегаторы, которые обходить стороной: " + (", ".join(aggregator_hosts) or "нет"),
        *_bounds(bounds),
        "Сайты в чёрном списке: " + (", ".join(barred_hosts) or "нет"),
    ])


def _bounds(bounds: SeekBounds) -> list[str]:
    return [
        _since(bounds.last_run),
        f"Можно передать вакансий, новых для приложения: {bounds.limit}",
        f"Сегодня: {bounds.today.isoformat()}",
        "Языки запросов: " + ", ".join(bounds.languages),
    ]


def _since(last_run: datetime | None) -> str:
    if last_run is None:
        return "Прошлый обход: не было, это первый обход"
    return f"Прошлый обход начался: {last_run.strftime('%Y-%m-%d %H:%M')} UTC"
