"""Проверка входа: вошёл ли человек на сайт агрегатора."""

from backend.agent.prompts.site_guides import guide_lines

LOGIN_PROMPT = """Твоя задача — понять, вошёл ли человек на этот сайт под своей учётной записью.

Открой главную страницу сайта и сними её. «Вошёл» — если видны признаки входа: ссылка или меню профиля, подпись аватара, кнопка «Выйти» вместо «Войти», имя человека в шапке. Признаков нет или сомневаешься — «не вошёл»: ложное «не вошёл» стоит человеку лишнего входа, а ложное «вошёл» — остановки посреди обхода.

Капча или страница проверки вместо сайта — признаков входа не видно, итог тот же: report_login с logged_in=false. Человек уже закрыл окно и снова войдёт сам.

Итог сообщи инструментом report_login (logged_in=true — вошёл, false — нет), затем заверши работу: finish с result="done".
"""


def login_task(host: str) -> str:
    """Стартовое задание проверки входа."""
    return "\n".join([f"Сайт: https://{host}/", "Проверь, вошёл ли человек на этот сайт.", *guide_lines(host)])
