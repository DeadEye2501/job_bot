def fill_task(host: str, resume_url: str | None, language: str) -> str:
    """Стартовое задание заполнения: перезаписать резюме с этой страницей или
    завести новое — на языке человека, а не сайта. Чего не делать, задание
    говорит прямо: правка не того резюме хуже любой ошибки, а привязать её
    проверку в коде не к чему."""
    return "\n".join([f"Сайт: https://{host}/", _overwrite(resume_url) if resume_url else _CREATE,
                      _SECTIONS, f"Язык резюме: {language}.", *guide_lines(host)])


_SECTIONS = (
    "Резюме бывает разложено на несколько разделов и страниц — опыт, личные данные, контакты, навыки:"
    " переходи между ними свободно, это одно резюме. Данные, которые сайт держит одним экземпляром"
    " на весь аккаунт, — не другое резюме: их приведи к анкете, как сказано в наставлении."
)
"""Что правка одного резюме — не одна страница. Общее у обоих режимов: запрет
трогать другое резюме иначе прочитался бы как запрет уходить со страницы."""

_CREATE_BUTTONS = "«Создать резюме», «Новое резюме», «Добавить резюме» и подобные"
_COPY_BUTTONS = "«Дублировать», «Создать копию», «Сохранить как новое» и подобные"

_CREATE = (
    f"Заведи новое резюме кнопкой или ссылкой создания ({_CREATE_BUTTONS}) и заполни все его разделы;"
    " название резюме — «Должность» из анкеты.\n"
    f"Нельзя: открывать правку уже заведённых резюме и заводить резюме копированием ({_COPY_BUTTONS}).\n"
    "Кнопки создания нет, или она открывает уже заведённое резюме — с его названием и опытом, — сайт не"
    " даёт завести ещё одно: report_no_new_resume, ничего не заполняя. Имя и контакты, которые сайт"
    " сам подставил в новое резюме из аккаунта, этим признаком не считаются."
)


def _overwrite(resume_url: str) -> str:
    """Перезапись: правка идёт от главной страницы резюме, и агент помнит путь.
    Подстраница правки бывает с любым адресом, хоть общим на все резюме, —
    поэтому своё резюме узнаётся по пути от главной страницы, а чужое — по
    главной странице с другим адресом или по пути через создание, копирование
    или список резюме."""
    return (
        f"Главная страница этого резюме — {resume_url}. Начни с неё и войди в правку кнопкой или ссылкой"
        " правки на ней («Редактировать», «Изменить» и подобные) или значками правки у её разделов.\n"
        "Помни путь, которым идёшь. Страница, куда ты пришёл с главной страницы или из уже открытой"
        " правки этого резюме — кнопками правки, разделов, «Далее», «Назад», — часть этого резюме,"
        " какой бы ни был у неё адрес. Оказался на главной странице какого-то резюме, а её адрес не"
        f" {resume_url}, или пришёл туда, где ты сейчас, через создание, копирование или список резюме —"
        f" ты в другом резюме: ничего не меняй и вернись на {resume_url}.\n"
        f"Нельзя: нажимать кнопки создания ({_CREATE_BUTTONS}) и копирования ({_COPY_BUTTONS}) и"
        " открывать правку другого резюме из списка резюме. Сайт спрашивает, обновить резюме или"
        " сохранить как новое, — выбирай обновить.\n"
        "На главной странице нет входа в правку, или вернуться в это резюме не выходит, — заверши"
        " работу: finish с result=\"failed\" и причиной."
    )
