def fill_task(host: str, resume_url: str | None) -> str:
    """Стартовое задание заполнения: перезаписать названное резюме или завести новое."""
    what = (f"Перезапиши резюме по ссылке {resume_url}: приведи его к анкете целиком."
            if resume_url else
            "Заведи на сайте новое резюме и заполни его; название резюме — желаемая должность из анкеты.")
    return f"Сайт: https://{host}/\n{what}"
