"""Беды, которые снимают всю работу с агентом, а не один её шаг.

Лист без ввозов нарочно: ловят их и сессии агента, и приём каналов, а приём
лежит под конвейером, который ввозят сами сессии.
"""


class HumanTimeout(Exception):
    """Человек не справился с капчей или входом за час — работа снимается."""


class LimitExhausted(Exception):
    """Исчерпан лимит подписки водителя — следующий шаг упёрся бы в то же."""


RUN_STOPPERS = (HumanTimeout, LimitExhausted)
"""Общий `except Exception` шага пропускает их наверх, к `bot/work.agent_work`."""
