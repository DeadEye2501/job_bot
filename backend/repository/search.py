"""Отсев списка по строке поиска — тот, что идёт на стороне питона.

Списки HR, компаний и каналов невелики (десятки, редко сотни), и отбирать их
после выборки дешевле, чем городить условие в запросе на каждое искомое поле.
Список вакансий устроен иначе: он отбирается запросом, потому что там тысячи
строк и постраничность.

Регистр здесь складывается через `casefold`, а не `lower`: он единственный
верно поступает с «ß» и конечной сигмой. В запросах так нельзя — там обе
стороны обязаны складываться одинаково, а на стороне базы стоит `lower`,
и подмена в `adapters/db.py` реализует именно его.
"""


def matches_search(search: str | None, *values: object) -> bool:
    """Подходит ли строка образцу хотя бы одним из своих значений.

    Пустой образец подходит всему: отсутствие поиска — это не отсев.
    Не-строки среди значений пропускаются молча: зовущие разворачивают сюда
    списки звёздочкой, и одно негодное значение иначе роняло бы весь перечень
    — даже когда искать не просили.

    Ведущая собачка с образца снимается: ники и у канала, и у человека лежат
    голыми (`normalize_username`), а списки рисуют их как `@ник` — списанный с
    экрана образец не совпадал бы ни с чем. Одна собачка после этого равна
    пустому образцу, и это верно: её набирают первой, ещё не набрав ника.
    """
    needle = (search or "").strip().lstrip("@").strip().casefold()
    if not needle:
        return True
    return any(isinstance(v, str) and needle in v.casefold() for v in values)
