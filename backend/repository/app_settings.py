"""Строка общего словаря настроек: записать значение по ключу.

Писателей у неё двое, и разными путями: настройки правит окно через
`RuntimeSettings`, своей сделкой, а запись разобранного резюме — внутри чужой,
вместе с самой анкетой. Общее у них ровно это тело, и порознь оно уже стояло
дважды.

Память `RuntimeSettings` тут не трогается: у неё своя, и обновляет её
владелец. Зовущий из сделки обязан позаботиться о ней сам, иначе свойство
настройки отдаёт прежнее значение до перезагрузки.
"""

from sqlalchemy.ext.asyncio import AsyncSession

from backend.models import AppSetting

CV_PATH_KEY = "cv_path"
"""Ключ, под которым помнят путь к файлу резюме.

Пишут его двое — окно при выборе файла и запись разобранной анкеты, — и
разойдись написание, второй писал бы мимо первого.
"""


async def put_app_setting(session: AsyncSession, key: str, value: str) -> None:
    """Записать значение по ключу; сделку открывает и закрывает зовущий."""
    row = await session.get(AppSetting, key)
    if row is None:
        session.add(AppSetting(key=key, value=value))
    else:
        row.value = value
