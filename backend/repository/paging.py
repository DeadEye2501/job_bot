"""Страница ответа репозитория и признак продолжения, который знает режущий.

Полная страница значит «есть ещё» и «ровно столько и было» одинаково часто, и
различить их по её длине нельзя. Различает лишняя строка, взятая сверх
запрошенного.

Чем отличается от соседей. `client/bridge/page.py` читает **запрос** окна —
сколько строк просят и с какого места, — а здесь **ответ**: что из найденного
уехало и осталось ли за ним ещё. Соседний `search.py` решает, какие строки в
найденное попадут; страница отрезается после него.

Объявления два, потому что запас берётся по-разному: запрос просит у базы
лишнюю строку, а отбор в памяти видит всё найденное сразу, и второго прохода
ему не нужно. Третье — над вторым: оно принимает правило отбора доводом и
держит порядок двух шагов, «сперва отбор, потом страница», за оба перечня,
которые режут страницу в памяти.
"""

from __future__ import annotations


def trim_page[T](rows: list[T], limit: int | None) -> tuple[list[T], bool]:
    """Страница из строк, взятых с запасом в одну, и есть ли за ней ещё.

    Зовущий обязан был попросить у базы `limit + 1`: лишняя строка и есть
    ответ. Без предела страницы нет вовсе — тогда показано всё, и просить
    больше нечего.
    """
    if limit is None:
        return rows, False
    if len(rows) > limit:
        return rows[:limit], True
    return rows, False


def searched_page[T](
    rows: list[T], matches, limit: int | None, offset: int
) -> tuple[list[T], bool]:
    """Подходящие под искомое строки, из них страница и есть ли за ней ещё.

    Правило отбора приходит доводом: у людей ищут по имени и нику, у компаний
    по имени, сайту и написаниям, и сводить сами правила нельзя. А порядок
    двух шагов общий — сперва отбор, потом страница, — и порознь один из
    перечней однажды отрезал бы страницу до отбора.
    """
    return slice_page([row for row in rows if matches(row)], limit, offset)


def slice_page[T](rows: list[T], limit: int | None, offset: int) -> tuple[list[T], bool]:
    """Страница из всего найденного и есть ли за ней ещё.

    Для тех, кто отбирает в памяти. Страница отрезается **после** отбора,
    иначе бесконечная прокрутка считала бы страницы по одному множеству, а
    показывала другое.

    Запас берётся тем же движением, что у запроса, — на строку больше, — и
    сравнение остаётся одно на оба объявления.
    """
    if limit is None:
        return rows, False
    return trim_page(rows[offset : offset + limit + 1], limit)
