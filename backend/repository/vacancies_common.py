"""Чтение вакансий, общее для всех экранов."""

from sqlalchemy import and_, func, select
from sqlalchemy.ext.asyncio import AsyncSession

from backend.models import Vacancy, VacancyStatus

PARSED_ONLY = Vacancy.is_parsed.is_(True)
"""Отбор «вакансия разобрана до конца».

Недоразобранная строка существует только потому, что конвейер делит заведение
и разбор на два шага; человеку она не показывается нигде. Зовут отбор список,
мини-списки карточек, статистика, счётчик и числа канала и поиск последней
вакансии человека, и забудь его кто-то один, недоразобранная строка вылезла бы
на экран или числа разошлись бы между экранами, причём молча.

**Канал зовёт отбор с 15.08.2026, и это решение человека.** Прежде его
счётчик, воронка и мини-список брали все строки подряд — ради того, чтобы
число в пилюле сходилось со списком под ним. Сходилось оно не с тем: пилюля
показывала «1» на вакансии, ещё не прошедшей разбор, а воронка добавляла ей
«New» и сто процентов подошедших. Сходиться эти числа должны с выдачей — с
тем, что человек увидит, открыв канал.
"""


def by_vacancy_count(label):
    """Порядок «кто принёс больше вакансий», а при равенстве — по подписи.

    Разрешитель по подписи не украшение: у предметов без вакансий счёт один и
    тот же, и без него порядок списка менялся бы от прогона к прогону.
    Подпись приходит доводом: у человека и компании это имя, у канала —
    заголовок, а без него ник, и NULL-заголовки всплыли бы наверх.

    Порознь от запроса ниже, потому что зовут его и те, кто счёт собирает
    своим запросом: люди одной компании берутся присоединением, а не внешним
    присоединением всех подряд.
    """
    return (func.count(Vacancy.id).desc(), label.asc())


def with_vacancy_counts(subject, link, label):
    """Предметы со счётом разобранных вакансий, плодовитые сверху.

    Один запрос на три перечня — людей, компаний и каналов: спрашивают они
    одно и то же, а разойдись формы, у одного из них счёт однажды перестал бы
    совпадать с тем, что показывают соседи.

    Отбор стоит в условии присоединения, а не в ``where``: в ``where`` он
    выбросил бы из списка предмет без единой разобранной вакансии, а тот
    обязан остаться в нём с нулём.
    """
    return (
        select(subject, func.count(Vacancy.id).label("cnt"))
        .outerjoin(Vacancy, and_(link == subject.id, PARSED_ONLY))
        .group_by(subject.id)
        .order_by(*by_vacancy_count(label))
    )


VACANCY_APPEARED_AT = func.coalesce(Vacancy.posted_at, Vacancy.created_at)
"""Когда вакансия появилась: время поста, а без него — время заведения.

Первое непустое, а **не** наибольшее из меток времени. Наибольшее считает
соседний `vacancies_activity.activity_ts`, но отвечает он на другой вопрос —
«последняя активность», — и ответы у них систематически разные: пост почти
всегда старше заведения. Имя здесь заведено ровно для того, чтобы эти два
вопроса не путались.

Третий вопрос о свежести — `hr_card.LAST_VACANCY_ORDER`, «что мы завели
последним»; он смотрит на одно `created_at` и с этой шкалой не сходится: пост
мог выйти в понедельник, а завестись в пятницу. Порядок карточки человека и
его мини-списков берут оттуда, атрибуцию ответа HR и мини-список канала —
отсюда.
"""


async def count_by_status(
    session: AsyncSession, *conditions
) -> dict[VacancyStatus, int]:
    """Сколько вакансий в каждом статусе среди отобранных условиями.

    В ответе присутствуют **все** статусы: которого не было ни у одной
    строки — нулём, а не пропуском. Этот договор и есть предмет объявления:
    по разбивке считают доли и рисуют воронку, и пропуск вместо нуля дал бы
    то дыру в таблице, то поломку на делении.
    """
    rows = (
        await session.execute(
            select(Vacancy.status, func.count(Vacancy.id))
            .where(*conditions)
            .group_by(Vacancy.status)
        )
    ).all()
    counts = {status: 0 for status in VacancyStatus}
    for status, cnt in rows:
        counts[status] = int(cnt or 0)
    return counts
