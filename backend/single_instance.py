"""Замок, которым запущенная копия приложения не пускает вторую."""

import logging
import os
from contextlib import nullcontext
from pathlib import Path

logger = logging.getLogger(__name__)


def _take_the_lock(fd: int) -> bool:
    """Занять открытый файл — или сказать, что он уже занят.

    Способа, общего для всех, нет, и берут они разное: на Windows замок
    ложится на диапазон байтов, и берётся самый короткий — один; на остальных
    `flock` диапазонов не знает и запирает файл целиком. Наружу разница не
    выходит: файл этот больше ни для чего не нужен, в него ничего не пишется.

    Оба вызова живут в модулях, которых на чужой системе не существует, —
    поэтому ввозятся здесь, а не наверху.
    """
    try:
        if os.name == "nt":
            import msvcrt

            msvcrt.locking(fd, msvcrt.LK_NBLCK, 1)
        else:
            import fcntl

            fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError:
        return False
    return True


def hold_the_only_copy(lock_path: Path | str):
    """Взять замок на всё время работы — или вернуть `None`, если он занят.

    Возвращается открытый файл, и его надо держать: замок живёт, пока жив
    дескриптор. Закрытый — снимается, и следующая копия войдёт.

    Двум копиям тесно по двум местам сразу. Файл журнала ротируется
    переименованием, и второй копии, держащей его открытым, после первой же
    ротации писать становится некуда: она пишет в переименованный файл, а тот
    очередная ротация сотрёт. База ещё хуже: два конвейера, независимо
    обходящие одни каналы, разбирают одни посты дважды и платят за это
    обращениями к модели.

    Замок файловый, а не отметкой с номером процесса: снимает его сама
    операционная система при закрытии дескриптора, чем бы копия ни кончилась.
    Отметку убитая копия оставила бы за собой навсегда.

    Не открывшийся файл запуска не отменяет: снятый атрибутом «только чтение»
    или занятый чужой программой, он говорит лишь о том, что сторожить нечем.
    Отказать здесь значило бы превратить осечку сторожа в неработающее
    приложение — а без него теряется журнал второй копии, и то лишь если её
    запустят.
    """
    try:
        fd = os.open(str(lock_path), os.O_CREAT | os.O_RDWR)
    except OSError:
        logger.exception("single instance: no lock at %s, starting unguarded", lock_path)
        return nullcontext()
    if _take_the_lock(fd):
        return os.fdopen(fd, "r+b")
    os.close(fd)
    # Записи здесь нет нарочно: файл журнала — ровно то, что замок сторожит, и
    # у предела размера одна эта строка запустила бы поворот, то есть саму беду.
    # Что делать второй копии дальше — дело зовущего; сегодня он просит открытую
    # копию показать окно (`client/raise_window`), а не сообщает человеку.
    return None
