"""Замок, которым запущенная копия приложения не пускает вторую."""

import errno
import logging
import os
from contextlib import nullcontext
from pathlib import Path

logger = logging.getLogger(__name__)


_held = None
"""Открытый файл замка, пока копия работает.

Помнится здесь, а не только у зовущего, потому что отпустить замок надо и
изнутри: снос данных удаляет сам файл замка, а Windows занятый файл удалить не
даёт.
"""


def release_the_lock() -> None:
    """Отпустить замок и забыть его.

    Зовёт снос данных — ему нужно удалить файл, который мы же и держим. После
    этого вторая копия войдёт беспрепятственно, и это верно: данных, ради
    которых копии не пускали друг к другу, сейчас не станет.
    """
    global _held
    if _held is None:
        return
    try:
        _held.close()
    except OSError:
        logger.exception("single instance: lock release failed")
    _held = None


_BUSY = frozenset(
    {errno.EACCES, errno.EAGAIN, errno.EWOULDBLOCK, getattr(errno, "EDEADLOCK", errno.EDEADLK)}
)
"""Номера бед, означающие «замок держит кто-то другой», а не осечку сторожа.

`EDEADLOCK` есть не везде: на маке у того же номера только имя `EDEADLK`.
"""


def _take_the_lock(fd: int) -> bool | None:
    """Занять открытый файл; сказать, занят ли он или замков тут нет вовсе.

    Три исхода, а не два: правда — взяли, ложь — держит другая копия, пустота —
    замок не дался по постороннему поводу. Схлопнутые в два, последние
    означали одно и то же: каталог данных на файловой системе без замков —
    сетевой профиль, перенаправленный `%APPDATA%` — превращал приложение в
    неоткрывающееся навсегда, и причина в коде числилась «не бедой».

    «Занято» узнаётся по номеру беды: `msvcrt.locking` под `LK_NBLCK` отвечает
    `EACCES`, а на длинном ожидании `EDEADLOCK`; `flock` под `LOCK_NB` —
    `EAGAIN` (он же `EWOULDBLOCK`).

    Способа, общего для всех, нет, и берут они разное: на Windows замок
    ложится на диапазон байтов, и берётся самый короткий — один; на остальных
    `flock` диапазонов не знает и запирает файл целиком. Наружу разница не
    выходит: файл этот больше ни для чего не нужен, в него ничего не пишется.

    Оба вызова живут в модулях, которых на чужой системе не существует, —
    поэтому ввозятся здесь, а не наверху.
    """
    try:
        if os.name == "nt":
            import msvcrt

            msvcrt.locking(fd, msvcrt.LK_NBLCK, 1)
        else:
            import fcntl

            fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError as e:
        if e.errno in _BUSY:
            return False
        logger.exception("single instance: замок не дался, сторожить нечем")
        return None
    return True


def hold_the_only_copy(lock_path: Path | str):
    """Взять замок на всё время работы; `None` — держит другая копия.

    Исходов три, и третий — «сторожить нечем»: файл не открылся или замков на
    этой файловой системе нет. Тогда работа идёт без сторожа, а не отменяется;
    почему — сказано ниже.

    Возвращается открытый файл, и его надо держать: замок живёт, пока жив
    дескриптор. Закрытый — снимается, и следующая копия войдёт.

    Двум копиям тесно по двум местам сразу. Файл журнала ротируется
    переименованием, и второй копии, держащей его открытым, после первой же
    ротации писать становится некуда: она пишет в переименованный файл, а тот
    очередная ротация сотрёт. База ещё хуже: два конвейера, независимо
    обходящие одни каналы, разбирают одни посты дважды и платят за это
    обращениями к модели.

    Замок файловый, а не отметкой с номером процесса: снимает его сама
    операционная система при закрытии дескриптора, чем бы копия ни кончилась.
    Отметку убитая копия оставила бы за собой навсегда.

    Не открывшийся файл запуска не отменяет: снятый атрибутом «только чтение»
    или занятый чужой программой, он говорит лишь о том, что сторожить нечем.
    Отказать здесь значило бы превратить осечку сторожа в неработающее
    приложение — а без него теряется журнал второй копии, и то лишь если её
    запустят.
    """
    try:
        fd = os.open(str(lock_path), os.O_CREAT | os.O_RDWR)
    except OSError:
        logger.exception("single instance: no lock at %s, starting unguarded", lock_path)
        return nullcontext()
    taken = _take_the_lock(fd)
    if taken:
        global _held
        _held = os.fdopen(fd, "r+b")
        return _held
    os.close(fd)
    if taken is None:
        # Замков тут нет — не то же, что «уже запущено»: второй копии не
        # существует, просить её показать окно бессмысленно. Работаем без
        # сторожа, как и при неоткрывшемся файле.
        return nullcontext()
    # Записи здесь нет нарочно: файл журнала — ровно то, что замок сторожит, и
    # у предела размера одна эта строка запустила бы поворот, то есть саму беду.
    # Что делать второй копии дальше — дело зовущего; сегодня он просит открытую
    # копию показать окно (`client/raise_window`), а не сообщает человеку.
    return None
