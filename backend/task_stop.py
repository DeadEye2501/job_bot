"""Погасить задачу и дождаться её конца."""

import asyncio


async def put_out(task: asyncio.Task) -> None:
    """Отменить задачу и вернуться, только когда она кончилась.

    Отмена — просьба: задача уходит со своего `await`, а не в миг зова.
    Вернись зовущий раньше — погашенная ещё жила бы: разбор дописал бы
    строку, агент записал бы отклик уже после остановки. Её исход не нужен
    никому: свою беду она пишет в журнал сама.
    """
    task.cancel()
    await asyncio.gather(task, return_exceptions=True)
