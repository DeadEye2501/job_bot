"""Разбор исходов работы, пущенной по людям разом."""

import logging

logger = logging.getLogger(__name__)


def report_failures(hr_ids: list[int], results: list, what: str) -> None:
    """Пожаловаться на тех, чья работа в пачке сорвалась.

    Пачка собирается с `return_exceptions=True` нарочно: сорвавшийся человек
    не должен уносить соседей — работу по каждому пускают один раз, и потерять
    из-за одного всех значило бы оставить человека с половиной сделанного.
    Беда поэтому приходит сюда значением, а не исключением, и разбирается
    после того, как пачка дошла целиком.

    Отмена приходит тем же путём, но `Exception` её не ловит — она
    `BaseException`, — и прежде уход по отмене выглядел ровно как удачный
    проход. Теперь о ней говорят вслух, а наружу не пробрасывают: своей
    отменой пачка сюда не доходит вовсе (`gather` бросает её сам, минуя
    разбор), а отменённый изнутри один человек не повод гасить бота — а
    именно этим проброс и кончился бы: у обоих зовущих отмены никто не ждёт.
    """
    for hr_id, result in zip(hr_ids, results):
        if isinstance(result, BaseException):
            logger.exception("%s failed for hr %d", what, hr_id, exc_info=result)
