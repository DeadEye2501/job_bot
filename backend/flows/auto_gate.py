"""Заслон автоматики: двигает ли она эту вакансию вообще.

Отдельным модулем, а не в приёме письма и не в отложенном разборе: спрашивают
его оба, и знать друг о друге им незачем. Планировщик разбора приходит в приём
письма доводом ровно затем, чтобы эти двое не были связаны, — и общий заслон
эту развязку ломать не должен.
"""

from sqlalchemy import select

from backend.domain.transitions import is_terminal_for_auto
from backend.models import Vacancy, VacancyStatus


async def status_open_for_auto(
    session_factory, vacancy_id: int
) -> tuple[bool, VacancyStatus | None]:
    """Открыт ли статус вакансии для автоматической смены; и сам статус.

    Спрашивают об этом дважды и нарочно: на приёме письма — чтобы не заводить
    отложенный разбор, и перед самим разбором — потому что за минуту ожидания
    статус мог уйти в терминальный (человек выставил отказ руками). Двойная
    проверка задумана, а вот читать её двумя телами незачем: разойдись они, и
    один путь тратил бы обращение к модели там, где второй уже отбивает.

    Статус отдаётся вместе с ответом: разбору он нужен как подсказка модели,
    обоим — для записи в журнал. Пропавшую вакансию (пустой статус) заслон
    закрывает наравне с терминальной: вакансию могли удалить, пока письмо
    шло, и разбирать ответ по тому, чего нет, не о чем. Разбирать пропажу
    самим зовущим было бы дороже: их двое, и оба ушли бы отсюда той же
    дорогой, что и от терминального статуса, — записью в журнал и выходом.
    """
    async with session_factory() as session:
        status = await session.scalar(
            select(Vacancy.status).where(Vacancy.id == vacancy_id)
        )
    return (status is not None and not is_terminal_for_auto(status)), status
