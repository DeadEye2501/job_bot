"""Статья, на которую ссылается объявление, дописанная к его тексту.

Живёт отдельно от приёма поста потому, что нужна двоим: и приёму, и прогону
заново. Прогон обязан читать объявление тем же чтением, что и приём, — иначе
разобранное кнопкой расходится с разобранным на обходе.

Статья дописывается в сам текст объявления, а не хранится рядом: это его
продолжение со всеми вытекающими — она уходит в разбор, ложится в сохранённый
текст и участвует в отпечатке, по которому отсеиваются повторы.
"""

import logging

import httpx

from adapters import teletype

logger = logging.getLogger(__name__)

# Сколько статей тянут с одного объявления. Пост-дайджест «десять вакансий
# недели» ссылается на статью у каждой, и десять походов в сеть подряд держат
# на себе весь обход канала. Разбирать такой пост как одну вакансию всё равно
# нечего, и первых трёх статей хватает, чтобы это стало видно разбору.
_MAX_ARTICLES = 3


def _article_urls(text: str) -> list[str]:
    """Адреса статей из текста объявления, по разу каждый, в порядке встречи.

    Один и тот же адрес попадается в посте дважды: словами и подписью кнопки.
    Скачивать его дважды незачем, а дописывать дважды — тем более.
    """
    seen: list[str] = []
    for url in teletype.ARTICLE_URL_RE.findall(text):
        if url not in seen:
            seen.append(url)
    return seen


async def with_linked_articles(text: str) -> tuple[str, bool]:
    """Текст объявления со статьями, на которые он ссылается, и целиком ли он.

    Ссылок нет — ни клиента, ни обращения в сеть: у подавляющего большинства
    объявлений всё сказано в самом посте, и там текст всегда целый.

    «Целиком» значит, что ни одна статья не пропала по причине, которая к утру
    пройдёт. Знать это нужно прогону заново: у него на руках уже есть
    сохранённый текст, и переписать его недобравшим — значит потерять
    требования из статьи, которую в эту минуту не отдали. Приёму поста терять
    нечего, и он берёт что дали.

    Адрес, за которым статьи нет вовсе, недобором не считается: её снесли или
    адрес ведёт на страницу автора, и второй раз лучше не станет. Считай это
    недобором — и прогон заново у такой вакансии перестал бы обновлять текст
    навсегда.
    """
    urls = _article_urls(text)
    if not urls:
        return text, True
    parts = [text]
    whole = len(urls) <= _MAX_ARTICLES
    async with teletype.make_client() as client:
        for url in urls[:_MAX_ARTICLES]:
            try:
                article = await teletype.fetch_article(client, url)
            except httpx.HTTPError as e:
                logger.warning("teletype: %s не отдал страницу (%s)", url, e)
                whole = False
                continue
            if article:
                parts.append(article)
    logger.info(
        "teletype: статей у объявления %d, дописано %d", len(urls), len(parts) - 1
    )
    return "\n\n".join(parts), whole
