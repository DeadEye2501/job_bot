"""Приметы поста соискателя: метки, по которым он опознаётся без модели.

Своим модулем, а не в отсеве (`domain/blacklist`): там список ведёт человек из
окна, и он про то, с кем мы не работаем; здесь — постоянное свойство жанра
поста, и меняется оно правкой кода, а не настройкой.

Дом один на всех, и это здесь главное. Метки читают четверо: жёсткая
отсечка, стоящая раньше разбора, и три наставления модели — через
`llm/rules.RESUME_MARK_LINE`. Переписанные порознь, перечни расходятся молча.
"""

import re

# Метки, по которым пост признаётся резюме без всякой модели.
RESUME_MARKS = frozenset({
    "#cv",
    "#resume",
    "#резюме",
    "#ищуработу",
    "#ищу_работу",
    "#opentowork",
    "#open_to_work",
    "#openforwork",
    "#openforhire",
    "#hireme",
    "#hire_me",
})

# Метки, которые в наставлении модели названы приметой резюме, а в жёсткую
# отсечку не входят. `#available` двусмыслен — доступен бывает и человек, и
# место; `#cv_` не метка, а начало метки, и целым словом не ищется вовсе.
#
# `#ищу` не входит и сюда. Правило, которому эта строка достаётся, велит
# отвечать «мусор» вне зависимости ни от чего, а «ищу» одинаково значит «ищу
# работу» и «ищу сотрудника» — и стоит в постах о найме рядом с `#вакансия`,
# `#hiring`, `#требуется`. Место такой примете — там, где взвешивают
# направление поста целиком, а не там, где приговор безусловен.
AMBIGUOUS_MARKS = frozenset({"#available", "#cv_"})

# Метка целиком, от решётки до первого чужого знака.
#
# Перед решёткой обязан быть пробел или начало текста: без этого «якорь»
# внутри адреса — `https://acme.com/careers#resume` — читался бы меткой, а с
# пункта 1 в текст объявления дописываются ещё и статьи по ссылкам, где таких
# адресов вдоволь. Цена ошибки здесь — удалённая живая вакансия.
_MARK = re.compile(r"(?<!\S)#\w+")


def resume_mark(text: str) -> str | None:
    """Первая метка резюме, найденная в тексте; пусто — таких меток нет.

    Ищется по всему тексту, а не в первой строке: подпись ставят и в конце.

    Отдаётся сама метка, а не «да»: она уходит в причину отказа, и человек,
    открывший список мусора, видит, по чему пост опознан.
    """
    for found in _MARK.findall(text or ""):
        mark = found.lower()
        if mark in RESUME_MARKS:
            return mark
    return None
