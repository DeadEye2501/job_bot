"""Приметы поста соискателя: метки, по которым он опознаётся без модели.

Своим модулем, а не в отсеве (`domain/blacklist`): там список ведёт человек из
окна, и он про то, с кем мы не работаем; здесь — постоянное свойство жанра
поста, и меняется оно правкой кода, а не настройкой.

Дом один на двоих, и это здесь главное. Метки читают и жёсткая отсечка перед
оценщиком, и само наставление оценщика (`llm/rules.RESUME_MARK_LINE`), а
переписанные порознь перечни расходятся молча: к 21.08.2026 наставление знало
`#openforwork` и `#hireme`, которых не было в коде, а код знал `#resume`,
которого не было в наставлении.
"""

import re

# Метки, по которым пост признаётся резюме без всякой модели. Сверено по
# собранному за август: набор ловит 23 поста из 224, и все 23 — резюме, ни
# одной вакансии. Часть меток в тех постах не встретилась ни разу
# (`#ищу_работу`, `#open_to_work`, `#openforhire`, `#hireme`, `#hire_me`) —
# они пришли из наставления оценщика, которое до этого вело свой перечень.
RESUME_MARKS = frozenset({
    "#cv",
    "#resume",
    "#резюме",
    "#ищуработу",
    "#ищу_работу",
    "#opentowork",
    "#open_to_work",
    "#openforwork",
    "#openforhire",
    "#hireme",
    "#hire_me",
})

# Метки, которые говорят о резюме, но не только о нём. Модели они годятся —
# она читает их вместе со всем постом; жёсткой отсечке нет, потому что
# удаление необратимо.
#
# `#ищу` в собранном за август стоит и в постах о найме, рядом с `#вакансия`,
# `#hiring` и `#требуется`: «ищу» одинаково значит «ищу работу» и «ищу
# сотрудника». `#available` двусмыслен так же — доступен бывает и человек, и
# место. `#cv_` — не метка, а начало метки, и целым словом не ищется вовсе.
AMBIGUOUS_MARKS = frozenset({"#ищу", "#available", "#cv_"})

# Метка целиком, от решётки до первого чужого знака.
#
# Перед решёткой обязан быть пробел или начало текста: без этого «якорь»
# внутри адреса — `https://acme.com/careers#resume` — читался бы меткой, а с
# пункта 1 в текст объявления дописываются ещё и статьи по ссылкам, где таких
# адресов вдоволь. Цена ошибки здесь — удалённая живая вакансия.
_MARK = re.compile(r"(?<!\S)#\w+")


def resume_mark(text: str) -> str | None:
    """Первая метка резюме, найденная в тексте; пусто — таких меток нет.

    Ищется по всему тексту, а не в первой строке: соискатели ставят подпись и
    в конце — из двадцати трёх пойманных постов августа у двух метка стояла
    ниже заголовка, и оба были резюме.

    Отдаётся сама метка, а не «да»: она уходит в причину отказа, и человек,
    открывший список мусора, видит, по чему пост опознан.
    """
    for found in _MARK.findall(text or ""):
        mark = found.lower()
        if mark in RESUME_MARKS:
            return mark
    return None
