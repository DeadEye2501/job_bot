"""Стек вакансии: что делают с его половинами, прежде чем показать человеку.

Половин две, потому что весят они по-разному, — но это дело подсчёта
(`domain/scoring.py`), и там же решается, что одно умение анкеты оплачивается
единожды. Здесь речь только о написаниях: одинаковые сводятся, остальные
складываются в колонку. Заводят вакансию двое — разбор поста и форма окна, —
и оба зовут отсюда: разойдись эти правила, карточка показала бы один и тот же
стек по-разному, смотря кем вакансия заведена.
"""

from backend.domain.skill_names import skill_key
from backend.domain.spellings import dedupe_first_wins


def joined_stack(required: list[str], preferred: list[str]) -> list[str]:
    """Колонка стека: обязательные, за ними желательные.

    Порядок нагружен, а не декоративен: карточка показывает первые несколько
    пилюль, остальные сворачивает в «+N», — и вперёд идёт то, без чего
    вакансия не берёт.
    """
    return list(required) + list(preferred)


def deduped_halves(
    required: list[str], preferred: list[str]
) -> tuple[list[str], list[str]]:
    """Половины без повторов: одинаковое написание остаётся в обязательных.

    Сводятся **написания**, а не умения анкеты: «Python» и «python» — одна
    строка, а «Photoshop» и «Illustrator» останутся двумя, даже когда в
    анкете это один навык. Умение оплачивается единожды у подсчёта
    (`domain/scoring.score_stack`), и повторять то же правило здесь значило
    бы прятать из карточки инструмент, который вакансия правда называет.

    Отсев идёт сквозь обе половины одним набором занятых ключей — тем же
    правилом, каким его ведёт разбор ответа модели (`llm/skills`). Уцелевает
    обязательная сторона, потому что она строже: сомнение разрешают в её
    пользу и наставление модели, и человек, набравший одно и то же в оба
    ряда. Порядок зовов здесь и есть это правило — потому они и написаны
    двумя строками, а не одним кортежем.
    """
    seen: set[str] = set()
    kept_required = dedupe_first_wins(required, skill_key, seen)
    kept_preferred = dedupe_first_wins(preferred, skill_key, seen)
    return kept_required, kept_preferred
