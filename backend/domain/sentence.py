"""Законченная фраза: свой знак конца или точка.

Строки, стоящие списком — пункты записи анкеты, пояснения в ленте статусов, —
приходят то с точкой, то без, и без общего окончания соседние выглядели бы
по-разному. Правило одно на всех, кто их пишет; на фронте его зеркало —
`ended` в `client/web/state/vacancy_card.js`.
"""

import re

# Знак конца фразы, в том числе спрятанный за закрывающей кавычкой или скобкой:
# «Работал в «Директе».» уже закончена, и вторая точка после кавычки лишняя.
_ENDED_RE = re.compile(r"[.!?…:][»\"')\]]*$")


def closed_sentence(text: str) -> str:
    """Фраза как есть, если она кончается своим знаком, иначе — с точкой."""
    return text if _ENDED_RE.search(text) else text + "."
