"""Разбор свободной строки зарплаты: число, как записано, и валюта."""

import re

from backend.domain.currency import CURRENCY_WRITINGS

# Число вместе со своими разрядами, дробной частью и собственной пометкой
# масштаба. Пометка ищется не по всей строке, а вплотную к числу и только
# целым словом: иначе «k» в «KPI», «к» в «Краснодаре» и «m» в «month»
# умножают зарплату на тысячу или на миллион.
_AMOUNT_RE = re.compile(
    r"(?P<num>\d+(?:[    ,.]\d{3})*(?:[.,]\d{1,2})?)(?!\d)(?!\s*%)"
    r"(?:\s*(?P<scale>(?:тысяч[аи]?|тыс|миллион[а-яё]*|млн|million|k|к|m)"
    r"(?![a-zа-яё0-9])))?",
    re.IGNORECASE,
)
# Написания валют приходят картой (`domain/currency.py`): по ним и
# склеиваются числа вилки, и опознаётся валюта строки, и разойдись эти два
# перечня, «$3000-$5000» склеилось бы валютой, которой у строки нет.
_CURRENCY_WORD = "|".join(word for _, word in CURRENCY_WRITINGS)
# Числа одной вилки склеены между собой только пробелами, тире, «до» — и
# знаком валюты, но лишь вместе с тире или «до»: его пишут у каждой границы.
# Стоять он может с любой стороны разделителя и с обеих сразу: у рубля пишут
# «150 000 ₽ до 250 000 ₽», у доллара и евро — «$3000-$5000». Одной валюты
# для склейки мало, иначе «200 000 руб 2 года» слиплось бы в одну связку и
# годы пошли бы в вилку. Дальше склейки пометка не идёт: в «300к, опыт от 5
# лет» пять — это годы.
_RANGE_GLUE_RE = re.compile(
    rf"\s*(?:(?:{_CURRENCY_WORD})\s*)?(?:до|[\-–—])[\s\-–—]*"
    rf"(?:(?:{_CURRENCY_WORD})\s*)?|\s*"
)
_THOUSAND = ("k", "к", "тыс")
_FRACTION_RE = re.compile(r"[.,]\d{1,2}$")
# Предел колонки: не влезшее в неё уронило бы запись вакансии на коммите, и
# она осталась бы неразобранной навсегда.
_MAX_AMOUNT = 2**63 - 1
# «Зарплата обсуждается / по договорённости» — тексты, где случайные числа
# («график 5/2», «10 минут от метро») зарплатой не являются. Голое «договор»
# сюда не годится: «трудовой договор» и «договор ГПХ» стоят рядом с прямо
# названной суммой.
_NEGOTIABLE_RE = re.compile(r"собесед|договорённ|договоренн|договорн|обсужд|negotia")
# Слова, которыми число вводят: стоят перед ним и говорят, что это не
# зарплата, а стаж или надбавка. Ищутся вплотную к связке, а не по всей
# строке: в «оклад 100 000 ₽ + KPI» между числом и словом стоит знак валюты,
# и связка остаётся зарплатой.
_LEADING_NOT_MONEY_RE = re.compile(r"опыт\w*|стаж\w*|бонус\w*|преми\w*|kpi|bonus\w*")
# Слова, которыми число заканчивают. Врозь с предыдущими они потому, что
# сторона у примет разная: «бонус» вводит следующее число и предыдущему —
# окладу — ничего не говорит, а «лет» относится к своему.
#
# Приметой служит счётная форма, а не именительный падеж: «3 месяца» — срок,
# «150 000 месяц» — зарплата за месяц. Отсюда «года», но не «год»; «месяца»
# и «месяцев», но не «месяц»; `years`, но не `year`. Различение того же
# рода, что у числительных: срок пишут при числе, период — при сумме.
_TRAILING_NOT_MONEY_RE = re.compile(
    r"лет|года|раза?|дней|дня|день|месяца|месяцев|недели|недель|years|months|days"
)
# Предлоги, которыми вводят число. Перечень один на два правила: слово перед
# предлогом им не заслоняется, а сам предлог говорит, какая граница названа.
_PREPOSITIONS = r"от|до|с"
# Предлог вилки стоит между словом и её первым числом и слова не заслоняет:
# в «опыт от 5 лет» приметой служит «опыт», а не «от». А вот знак валюты
# заслоняет нарочно: за ним слово перечисляет саму сумму, а не соседнюю.
# «оклад и бонусы $4000» — это одна зарплата, названная двумя словами.
_WORD_BEFORE_RE = re.compile(rf"([a-zа-яё]+)(?:\s+(?:{_PREPOSITIONS}))?\s*$")
# Предлог вплотную перед числом. Стоит ли он там, решает, названа одна
# граница или обе; слово перед предлогом на это не влияет.
_PREPOSITION_RE = re.compile(rf"(?<![а-яё])({_PREPOSITIONS})\s*$")
# Валюта вплотную к связке — с любой её стороны: «$3000» и «250 000 ₽».
_CURRENCY_BEFORE_RE = re.compile(rf"(?:{_CURRENCY_WORD})\s*$")
_CURRENCY_AFTER_RE = re.compile(rf"^\s*(?:{_CURRENCY_WORD})")
# Наращение при числе своё слово не заслоняет: «от 3-х лет» — тот же срок.
_WORD_AFTER_RE = re.compile(r"^(?:-[а-яё]{1,2})?\s*([a-zа-яё]+)")
_CURRENCIES: tuple[tuple[str, re.Pattern[str]], ...] = tuple(
    (sign, re.compile(word)) for sign, word in CURRENCY_WRITINGS
)


def parse_salary(
    salary: str | None,
) -> tuple[int | None, int | None, str | None]:
    """Достать из строки диапазон и валюту, не пересчитывая их.

    Число остаётся тем, что записано в объявлении, — раскрывается только
    пометка тысяч и миллионов, без которой «300к» не сравнить с «300000».
    Отдаёт ``(None, None, None)``, когда числа в строке нет вовсе или она
    вообще не о деньгах. Одно число даёт равные границы. Валюта, не названная
    в строке, остаётся неизвестной: догадка «раз без знака, то рубли»
    отправила бы долларовую вакансию в рублёвую выдачу.
    """
    if not salary:
        return (None, None, None)
    s = salary.strip().lower()
    low, high = _money_bounds(s)
    if low is None and high is None:
        return (None, None, None)
    return (low, high, currency_sign(s))


def salary_text(low: int | None, high: int | None, currency: str | None) -> str | None:
    """Собрать строку зарплаты из чисел — обратная дорога `parse_salary`.

    Нужна там, где вилку называет человек, а не объявление: колонка `salary`
    хранит написанное автором поста, и у заведённой руками вакансии автор —
    он сам. Пустая, когда чисел нет вовсе: строка из одного знака валюты
    ничего не говорит.

    Живёт рядом с разбором нарочно: написание вилки читают и пишут одно и то
    же, и разъедься эти два объявления, разобранное перестало бы совпадать с
    записанным.
    """
    if low is None and high is None:
        return None
    if low is not None and high is not None:
        span = f"{low}" if low == high else f"{low}-{high}"
    else:
        span = f"от {low}" if low is not None else f"до {high}"
    return f"{span} {currency}" if currency else span


def _named_outright(s: str, part: list[re.Match]) -> bool:
    """Названа ли сумма прямо — знаком валюты у связки или пометкой масштаба.

    Этим и различаются два соседства с «по договорённости»: «от 250 000 ₽,
    точная сумма по итогам собеседования» — честная вилка с оговоркой, а
    «зарплата по договорённости, график 5/2» — не сумма вовсе. Прежде примета
    стирала оба случая, и вакансия с названной вилкой уходила в список без
    зарплаты, мимо любого отбора по деньгам.

    **Признак взят такой, потому что примету снять нельзя, а верить всем
    числам подряд — тем более.** Рядом с «по договорённости» числа в
    объявлении есть почти всегда: дни недели, минуты до метро, годы опыта.
    Знак валюты и пометка масштаба — единственное, чем сумма в такой строке
    отличается от них, и оба пишут при деньгах нарочно.

    Цена признака известна с обеих сторон, и обе приняты. В одну: «по
    договорённости, оклад 250 000» без валюты и без «к» зарплатой здесь не
    станет. В другую: чужая сумма со знаком валюты ею станет — «по
    договорённости, ставка 500 ₽/час» ляжет в поля как 500, и вакансия
    попадёт в отбор «до 1000», где ей делать нечего. Размен выбран по
    частоте: вилка с оговоркой встречается на порядок чаще, чем почасовая
    ставка или суточные рядом с «по договорённости».

    Валюта спрашивается вплотную к связке, а не по всей строке: «зарплата по
    договорённости (в рублях), график 5/2» назвала бы деньгами пятёрку.
    """
    if any(hit["scale"] for hit in part):
        return True
    return bool(
        _CURRENCY_BEFORE_RE.search(s[: part[0].start()])
        or _CURRENCY_AFTER_RE.match(s[part[-1].end() :])
    )


def _money_bounds(s: str) -> tuple[int | None, int | None]:
    """Границы первой связки, в которой речь о деньгах.

    Вилка в объявлении одна, а чисел вокруг неё бывает много: срок работы,
    требуемый стаж, надбавка. Пока границами служили крайние числа всей
    строки, «300к, опыт от 5 лет» давало вилку от пяти рублей, а
    «фикс 150 000 ₽, бонус 50 000 ₽» — от пятидесяти тысяч.
    """
    negotiable = bool(_NEGOTIABLE_RE.search(s))
    for run in _runs(s):
        part = _money_part(s, run)
        kept = _values(part)
        if not kept:
            continue
        if negotiable and not _named_outright(s, part):
            continue
        if len(kept) == 1:
            return _one_bound(s, part, kept[0])
        return (kept[0][1], kept[-1][1])
    return (None, None)


def _one_bound(
    s: str, part: list[re.Match], kept: tuple[re.Match, int]
) -> tuple[int | None, int | None]:
    """Границы, когда числом осталось одно.

    Пришло оно одно — решает предлог перед ним. Осталось одно от вилки —
    вторую сторону отсеяли как бессмысленную («от 0 до 300 000»), и
    известной остаётся та, что уцелела: ноль внизу говорит не «платят ровно
    триста тысяч», а «не больше трёхсот».
    """
    hit, value = kept
    if len(part) == 1:
        return _one_sided(s, hit, value)
    return (None, value) if hit is part[-1] else (value, None)


def _money_part(s: str, run: list[re.Match]) -> list[re.Match]:
    """Часть связки, в которой речь о деньгах.

    Чужим слово бывает по-разному, и различает это склейка. Приклеенное
    пробелом число стоит само по себе: в «150 000 2 года» годы относятся к
    двойке, и отбрасывать вместе с ней зарплату незачем. А склеенные тире или
    «до» — одна вилка, и слово говорит про неё целиком: срежь у «от 1 до 3
    лет опыта» одну сторону, и оставшийся рубль станет зарплатой, спрятав
    настоящую сумму, стоящую следом.
    """
    before = _WORD_BEFORE_RE.search(s[: run[0].start()])
    if before and _LEADING_NOT_MONEY_RE.fullmatch(before.group(1)):
        if not _spaced(s, run[:2]):
            return []
        run = run[1:]
    after = _WORD_AFTER_RE.match(s[run[-1].end() :])
    if after and _TRAILING_NOT_MONEY_RE.fullmatch(after.group(1)):
        if not _spaced(s, run[-2:]):
            return []
        run = run[:-1]
    return run


def _spaced(s: str, pair: list[re.Match]) -> bool:
    """Стоят ли два соседних числа связки через один пробел.

    Пара короче двух — это одинокое число, и отделять в нём нечего.
    """
    if len(pair) < 2:
        return False
    return not s[pair[0].end() : pair[1].start()].strip()


def _one_sided(
    s: str, hit: re.Match, value: int
) -> tuple[int | None, int | None]:
    """Границы одного числа: предлог перед ним говорит, какая из них названа.

    «до 120 000» — верхняя граница, и нижней у неё нет: вакансия, готовая
    платить восемьдесят тысяч, отсеивалась отбором «не дороже ста».
    Зеркально «от 300 000» пряталось от отбора «от 400 000», потому что
    верхней границей ему ставили те же триста тысяч. Без предлога число
    остаётся обеими границами разом — так пишут точный оклад.
    """
    said = _PREPOSITION_RE.search(s[: hit.start()])
    preposition = said.group(1) if said else ""
    if preposition == "до":
        return (None, value)
    if preposition:
        return (value, None)
    return (value, value)


def _values(run: list[re.Match]) -> list[tuple[re.Match, int]]:
    """Числа связки со своими местами, раскрытые по её пометке.

    Ноль отбрасывается: нулевой зарплаты не бывает, а нижней границей он
    отсёк бы вакансию от любого осмысленного отбора. Место числа едет рядом
    со значением: по нему видно, какую сторону вилки отсеяли.

    Порядок — по возрастанию значения, а не по написанному: «250-150» вилка
    та же, что «150-250», и границы у неё те же.
    """
    marker = next((h["scale"] for h in reversed(run) if h["scale"]), None)
    found: list[tuple[re.Match, int]] = []
    for hit in run:
        value = _amount(hit["num"], hit["scale"] or marker)
        if 0 < value <= _MAX_AMOUNT:
            found.append((hit, value))
    return sorted(found, key=lambda pair: pair[1])


def _runs(s: str) -> list[list[re.Match]]:
    """Числа строки, разбитые на вилки.

    Пометку пишут в конце вилки, а относится она ко всей: «150-200 тыс» — это
    сто пятьдесят и двести тысяч. Чтобы раздать её своим и не задеть чужих,
    числа собираются в связки по тому, что стоит между ними.
    """
    runs: list[list[re.Match]] = []
    for hit in _AMOUNT_RE.finditer(s):
        glued = runs and _RANGE_GLUE_RE.fullmatch(s[runs[-1][-1].end() : hit.start()])
        if glued:
            runs[-1].append(hit)
        else:
            runs.append([hit])
    return runs


def _amount(num: str, scale: str | None) -> int:
    """Одно число: разряды склеены, дробная часть учтена, пометка раскрыта.

    Разделитель разрядов и десятичный знак пишут одними и теми же символами,
    и различает их длина хвоста: «3,000» — три тысячи, «3,5» — три с
    половиной.
    """
    fraction = _FRACTION_RE.search(num)
    whole = num[: fraction.start()] if fraction else num
    value: float = int(re.sub(r"\D", "", whole))
    if fraction:
        value += float("0" + fraction.group().replace(",", "."))
    return int(value * _scale(scale))


def _scale(marker: str | None) -> int:
    """Во сколько раз пометка раскрывает число."""
    if not marker:
        return 1
    return 1000 if marker.lower().startswith(_THOUSAND) else 10**6


def currency_sign(s: str | None) -> str | None:
    """Знак валюты строки — только если валюта в ней одна.

    Названы две — диапазон не имеет смысла ни в одной из них, и выбор первой
    попавшейся спрятал бы вакансию от отбора по второй.

    Зовут двое: разбор зарплаты из объявления и форма заведения вакансии, где
    валюту набирают словом — «usd», «руб», «долларов». Приведение у них одно
    нарочно: разойдись оно, набранное руками не совпало бы с найденным ботом,
    и одна валюта считалась бы двумя.

    Регистр снимается здесь, а не у зовущего: написания в карте набраны
    строчными и собраны без оглядки на регистр, и «USD» с «Руб» иначе не
    находятся вовсе — валюта пропадает молча.
    """
    if not s:
        return None
    s = s.lower()
    named = [sign for sign, pattern in _CURRENCIES if pattern.search(s)]
    return named[0] if len(named) == 1 else None
