"""Сведение написаний названия навыка по общему ключу."""

import re
from typing import Iterable, TypeVar

T = TypeVar("T")

_SEPARATORS_RE = re.compile(r"[\s\-_./]+")


def skill_key(name: str) -> str:
    """Название навыка, приведённое к сравнимому виду.

    Регистр не различается, пробелы по краям срезаются, а разделители
    внутри сводятся к одному пробелу: одно и то же пишут «Docker-Compose»
    и «docker compose», «Node.js» и «node js», «CI/CD» и «ci cd».

    Правило одно на весь проект: по нему считаются баллы вакансии, экран
    статистики решает, свой ли тег, разбор резюме связывает стек места
    работы с навыками анкеты, а разбор ответа модели выбрасывает из стека
    повторы. Разойдись они — один и тот же навык был бы своим в одном
    месте и чужим в другом.
    """
    return _SEPARATORS_RE.sub(" ", name.casefold()).strip()


def index_by_key(
    lookup: dict[str, T], names: Iterable[object], value: T
) -> list[tuple[str, str, T]]:
    """Разложить написания навыка по ключам; при столкновении выигрывает первое.

    Первое, а не последнее, потому что порядок выдачи базы ничем не задан:
    побеждай последний, и один и тот же навык отдавал бы то один ответ, то
    другой — от запроса к запросу.

    Отдаёт непринятые написания вместе с тем, что уже лежит под их ключом.
    **Жаловаться ли на них, решает зовущий:** у привязки опыта это спор двух
    строк анкеты, о котором надо предупредить громко, у баллов — два уровня
    одного навыка, что бывает и в порядке вещей. Сводится место правила, а не
    решение о жалобе.

    Пустые ключи и не-строки пропускаются молча. Пустой ключ не просто
    бесполезен: запишись он, любая пробельная строка в стеке вакансии
    находила бы его как знакомый навык.
    """
    collisions: list[tuple[str, str, T]] = []
    for name in names:
        if not isinstance(name, str):
            continue
        key = skill_key(name)
        if not key:
            continue
        if key in lookup:
            collisions.append((name, key, lookup[key]))
            continue
        lookup[key] = value
    return collisions


def dedupe_by_key(names: Iterable[str], seen: set[str]) -> list[str]:
    """Отсеять повторы написаний по ключу; первое написание выигрывает.

    Набор виденных ключей приходит доводом и пополняется — так зовущий либо
    засевает его тем, что уже занято, либо продолжает отсев между двумя
    вызовами. Отдаётся исходное написание: сравнивается ключ, а показывается
    то, что написали.

    Написание с пустым ключом («///», «-») не идёт в ответ вовсе: сравнить
    его не с чем, а ляг оно в набор — второе такое молча потерялось бы.
    """
    out: list[str] = []
    for name in names:
        key = skill_key(name)
        if not key or key in seen:
            continue
        seen.add(key)
        out.append(name)
    return out
