"""Карта валют: чем их называют в объявлении, каким знаком печатают и каким кодом
ISO зовут.

Соседний `salary.py` — про другое: там из строки достают числа, а отсюда
берут перечень написаний. Живёт он своим файлом потому, что кормит несколько
вещей разом — опознание валюты строки, склейку вилки, курсы и перечень валют
для разбора, — и второй такой же перечень рядом разошёлся бы с первым молча.

Знак, а не код: пилюля в окне печатает валюту единицей после числа, и «1500 ֏»
читается там, где «1500 AMD» пришлось бы разбирать.

Написание берётся целым словом: «евро» внутри «Европы» и «eur» внутри «europe»
превращали рублёвую вакансию в валютную, а «руб» внутри «рубрики» — долларовую
в вакансию с двумя валютами разом, то есть без валюты вовсе. По той же причине
«драм» не продолжается буквой: иначе «драматург» назвал бы вакансию армянской.
"""

# Знак, код ISO и написания. Код — для источника курсов: тот зовёт валюты кодами.
CURRENCY_WRITINGS: tuple[tuple[str, str, str], ...] = (
    ("$", "USD", r"\$|(?<![a-z])usd(?![a-z])|долл[а-яё.]*"),
    ("€", "EUR", r"€|(?<![a-z])eur(?![a-z])|евро(?![а-яё])"),
    ("₽", "RUB", r"₽|(?<![a-z])rub(?![a-z])|руб\.?(?![а-яё])|рубл[а-яё]*"),
    ("֏", "AMD", r"֏|(?<![a-z])amd(?![a-z])|(?<![a-z])dram[s]?(?![a-z])|драм(?:ов|ами|ах)?(?![а-яё])"),
    ("₸", "KZT", r"₸|(?<![a-z])kzt(?![a-z])|тенге(?![а-яё])"),
    ("₾", "GEL", r"₾|(?<![a-z])gel(?![a-z])|лари(?![а-яё])"),
)
