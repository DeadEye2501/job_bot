"""Замкнутые перечни значений, которыми описывают вакансию и анкету.

От `models/enums.py` отличается тем, что там перечисление объявлено типом
колонки и чужое значение не пустит сама база. Здесь значение хранится обычной
строкой — в JSON-колонках анкеты и в `profile_language.level`, — и отсеять
чужое может только код.

Порядок значим везде. У грейдов и форматов работы — потому что окно
выкладывает отобранное именно в нём. У уровней языка — потому что последний из
них достаётся языку, чей уровень в резюме не назван внятно.
"""

GRADES: tuple[str, ...] = ("junior", "middle", "senior", "lead")
WORK_FORMATS: tuple[str, ...] = ("office", "remote", "hybrid")

GRADE_SPELLINGS: dict[str, tuple[str, ...]] = {
    "junior": ("стажёр", "intern", "джун"),
    "middle": ("мидл",),
    "senior": ("сеньор",),
    "lead": ("тимлид", "team lead"),
}
"""Какими ещё словами звание называют в тексте, кроме самого значения.

Рядом со значениями по тому же доводу, что и подписи форматов работы: набор
званий и их написания меняются вместе. Читают отсюда двое — наставление модели
о том, что считать грейдом, и сверка разобранного резюме с его текстом, — и
порознь эти списки уже расходились.
"""

WORK_FORMAT_SPELLINGS: dict[str, tuple[str, ...]] = {
    "office": ("офис", "onsite", "on-site", "on site"),
    "remote": (
        "удалён", "дистанционно", "remote", "distributed",
        "из дома", "work from home", "wfh",
    ),
    "hybrid": ("гибрид", "hybrid"),
}
"""Какими словами формат работы назван в тексте.

Корни, а не слова целиком: «удалён» покрывает и «удалённо», и «удалёнку», а
«офис» — «в офисе». Пара к `GRADE_SPELLINGS` и по той же надобности — сверить
разобранное с резюме, где формат назван по-человечески.

Само значение к перечню не добавляется: английское «office» сидит внутри
«MS Office», самой ходовой строки в разделе навыков, и работа из офиса
приписывалась бы каждому, кто владеет Экселем. У «remote» и «hybrid» такой
беды нет, и они в перечне стоят.

Второго написания через «е» вместо «ё» не нужно: сверка сводит эти буквы с
обеих сторон.
"""

WORK_FORMAT_LABELS_RU: dict[str, str] = {
    "remote": "удалёнка",
    "hybrid": "гибрид",
    "office": "офис",
}
"""Как формат работы называют по-русски.

Рядом со значениями, а не у того, кто печатает: набор значений и их подписи
меняются вместе, и разъехаться порознь им дороже, чем лежать вместе.
"""

CEFR_LEVELS: tuple[str, ...] = ("A1", "A2", "B1", "B2", "C1", "C2")

NATIVE_LEVEL = "native"
"""Уровень родного языка. Шкала CEFR его не знает, а анкете он нужен."""

LEVEL_SPELLINGS: dict[str, tuple[str, ...]] = {
    "C2": ("в совершенстве", "proficient", "proficiency", "bilingual"),
    "C1": ("свободно", "свободный", "свободное", "fluent", "advanced", "продвинутый"),
    "B2": ("upper-intermediate", "выше среднего"),
    "B1": ("разговорный", "разговорное", "conversational", "intermediate", "средний"),
    "A2": ("pre-intermediate", "ниже среднего", "elementary"),
    "A1": ("базовый", "базовое", "начальный", "beginner", "basic", "со словарём"),
}
"""Какими словами вместо шкалы называют владение языком.

Рядом со шкалой по тому же доводу, что и написания званий: читают отсюда двое —
разбор ответа модели и сверка разобранного с текстом резюме, — и порознь такие
перечни расходятся.

Слово, шкале не отвечающее вовсе («технический», «письменный»), сюда не входит:
это не уровень, а свойство владения, и переводить его нечем.
"""

LEVELS_BY_SPELLING: tuple[tuple[str, str], ...] = tuple(
    sorted(
        (
            (spelling.replace("-", " "), level)
            for level, spellings in LEVEL_SPELLINGS.items()
            for spelling in spellings
        ),
        key=lambda pair: len(pair[0]),
        reverse=True,
    )
)
"""Те же написания разом, от длинного к короткому.

Порядок несущий: «intermediate» сидит внутри «upper intermediate», и короткое,
спрошенное первым, отобрало бы у длинного его собственный уровень. Дефис
сведён к пробелу — «Upper-Intermediate» и «Upper Intermediate» одно и то же.
"""

LEVEL_WHEN_UNTOLD: str = CEFR_LEVELS[-1]
"""Уровень языка, названного без уровня, при разборе резюме.

Высший, и это не поблажка: уровня не называет тот, кто в языке уверен, —
неуверенный как раз уточняет. Низший на его месте отрезал бы такому человеку
все вакансии, где язык нужен, а высший не отрезает ничего.

У окна умолчание своё и другое (`client/bridge/choices`): там человек сам
набирает строку языка в форме, и уровень у неё выбирается списком.
"""

LANGUAGE_LEVELS: tuple[str, ...] = CEFR_LEVELS + (NATIVE_LEVEL,)
