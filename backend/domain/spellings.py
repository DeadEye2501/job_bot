"""Отсев повторов среди написаний: первое встреченное выигрывает.

Соседний `dedup.py` — про другое: там косинусная близость векторов ищет,
не присылали ли эту вакансию уже. Здесь сравниваются строки, и правило
сравнения приносит зовущий.
"""

from typing import Callable, Iterable, TypeVar

T = TypeVar("T")


def dedupe_first_wins(
    items: Iterable[T], key: Callable[[T], str], seen: set[str] | None = None
) -> list[T]:
    """Написания без повторов; из двух одинаковых остаётся встреченное первым.

    Первое, а не последнее, потому что порядок выдачи базы ничем не задан:
    побеждай последний, и один и тот же список менялся бы от запроса к
    запросу.

    **Правило сравнения приходит доводом, и оно здесь главное.** У навыка
    ключ схлопывает разделители — «Node.js» и «node js» одна технология; у
    компании не схлопывает — «Сбер-Тех» и «Сбер Тех» разные; у вариантов
    отбора это плоский нижний регистр. Обход один на всех, правило у
    каждого своё, и сводить сами правила нельзя.

    Набор занятых ключей можно передать — и тогда он **пополняется**: так
    разбор стека вакансии продолжает отсев между обязательной и желательной
    группами, а слияние компаний засевает набор названием выжившей.

    Пустое отсеивается **дважды, и оба раза нужны**. До ключа — потому что в
    списках, пришедших из базы и от модели, лежит и `None`, а ключа из него
    не вывести. После ключа — потому что написание бывает непустым, а ключ
    из него выходит пустой: «///» и «-» у навыка схлопываются в ничто.
    Пропусти второй сторож, и первое такое написание осталось бы, а второе
    молча потерялось бы как повтор пустоты.
    """
    if seen is None:
        seen = set()
    out: list[T] = []
    for item in items:
        if not item:
            continue
        item_key = key(item)
        if not item_key or item_key in seen:
            continue
        seen.add(item_key)
        out.append(item)
    return out
