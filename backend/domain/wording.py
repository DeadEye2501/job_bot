"""Как узнать написание в тексте: словом, а не куском чужого слова.

Спрашивают об этом двое — разбор ответа модели и сверка разобранного с текстом
резюме, — и правило у них одно. Написанное порознь, оно уже стояло дважды
разными механиками, а довод под ним один: «intermediate» сидит внутри
«upper-intermediate», и короткое, спрошенное первым, отбирает у длинного его
собственный уровень.
"""

import re


def spelled_alone(text: str, word: str) -> bool:
    """Написание стоит в тексте само, а не внутри другого слова.

    Дефис по краям запрещён наравне с буквой и цифрой. Между словами, наоборот,
    дефис и пробел равнозначны: «Upper-Intermediate» и «Upper Intermediate» —
    одно написание.
    """
    loose = r"[\s-]+".join(re.escape(part) for part in re.split(r"[\s-]+", word))
    return re.search(rf"(?<![-\w]){loose}(?![-\w])", text) is not None
