"""Время в той шкале, в какой приложение пишет всё остальное.

Своим объявлением, а не по месту: меток от Telegram пять — время поста, время
входящего письма, время эха своего письма и две отправки из окна, — и
разъехаться им нельзя. В одной колонке `message.sent_at` встречаются обе
стороны переписки, и одно и то же исходящее письмо пишут двое: сама отправка и
пришедшее следом эхо. Разойдись у них шкала — какая строка ляжет, решал бы тот,
кто успел первым.

Отличается от `telegram_lookup` и `telegram_login` тем, что не ходит в Telegram
вовсе: здесь чистое правило, и Pyrogram сюда не ввозится.
"""

from datetime import datetime, timezone


def tg_moment(dt: datetime | None) -> datetime | None:
    """Метка в нашей шкале: наивная, по UTC.

    Pyrogram отдаёт время сообщения через `datetime.fromtimestamp` без пояса,
    то есть **по местным часам**. Всё остальное приложение пишет в UTC:
    `server_default=func.now()` у SQLite это `CURRENT_TIMESTAMP`, а отправка
    берёт `datetime.now(timezone.utc)`. Драйвер SQLite пояс на записи срезает,
    и наивная местная метка ложится в ту же колонку, что наивная UTC, отличаясь
    от неё на смещение машины.

    Пояс снимается после приведения, а не вместо него: снять его сразу было бы
    верно только на машине, живущей в UTC. У наивного времени `astimezone`
    считает пояс местным — ровно то, чем оно и является у Pyrogram.
    """
    return dt.astimezone(timezone.utc).replace(tzinfo=None) if dt else None


def utc_now() -> datetime:
    """Сейчас в нашей шкале: наивное, по UTC.

    Своим объявлением, а не по месту: сравнивают с ним отметки, пришедшие из
    базы, а SQLite отдаёт их без пояса даже у колонки с поясом. Написанное
    руками, приведение разъезжается молча — пояс, забытый в одном из мест,
    даёт разницу в часы, и сроки молчания и ожидания начинают считаться
    по-разному.
    """
    return datetime.now(timezone.utc).replace(tzinfo=None)
