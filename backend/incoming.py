"""Приведение внешнего ввода к значениям, годным для записи.

Нагрузку составляет не наш код: она приходит из формы окна, из ответа модели
и из ответа Telegram, и приходит в ней что угодно — не тот тип, пустота трёх
видов, пробелы по краям. Каждому зовущему все эти случаи значат одно: взять
то, что годится, и не уронить разбор. Исключение — дата, выбранная человеком
в календаре: негодная отбивает запись, а не стирается молча.

Чем отличается от соседей. `payloads.py` объявляет **свёртки** — из чего
состоит вакансия, письмо, карточка; здесь **чтение** отдельного значения, из
которого их собирают. Разошлись эти два предмета потому, что свёртки читает
весь проект, а приведение — только те, кто принимает чужое.
"""

import enum
from datetime import date, datetime

_HOMOGLYPHS = str.maketrans("авсеАВСЕ", "abceABCE")


def fold_homoglyphs(text: str) -> str:
    """Кириллические двойники латинских букв сведены к латинским.

    В русской раскладке набирают и обозначения, которые по замыслу латинские:
    «А1» уровня языка, «В2», «С1». На вид их не отличить, и всякий, кто ищет
    такое обозначение в тексте резюме, не нашёл бы его вовсе.

    Сводятся только четыре пары, у которых начертание общее. Русский текст
    от этого портится, поэтому свёрнутая строка годится лишь для поиска
    латинских обозначений, а не для чтения.
    """
    return text.translate(_HOMOGLYPHS)


_SAME_SIGNS = str.maketrans({
    "ё": "е", "Ё": "Е", "—": "-", "–": "-", "‑": "-", "−": "-", "…": "...",
    "’": "'", "‘": "'", "«": '"', "»": '"', "“": '"', "”": '"', "„": '"',
    "­": None, "•": " ",
})


def fold_signs(text: str) -> str:
    """Текст с одним написанием для знаков, которые пишут по-разному, не меняя
    слов: буква ё, тире и дефисы, многоточие, апостроф, кавычки, мягкий
    перенос и маркер списка.

    Нужно всякому, кто ищет чужие слова в исходном тексте: цитату модели в
    посте, звание из ответа в резюме. Без сведения «стажер» не нашёлся бы в
    «стажёр», а цитата с прямым апострофом — в посте с кривым.
    """
    return text.translate(_SAME_SIGNS)


def text_or_none(value) -> str | None:
    """Текстовое поле нагрузки: обрезанное по краям, а пустое — как отсутствие.

    Пустую строку, одни пробелы и пропуск поля окно шлёт вперемешку, а в
    колонке все три значат одно, и хранится там `NULL`.

    Не-строка приводится, а не отбрасывается. Сегодня окно её не шлёт, так что
    выбор виден только на стенде, — но отброшенное значило бы стёртую колонку,
    которую человек не трогал, а приведённое видно и поправимо.

    ``None`` здесь — «стереть». «Не трогать» зовущие метят своим часовым до
    вызова: сюда оба доезжают пустотой и отличить их отсюда нечем.
    """
    if value is None:
        return None
    return str(value).strip() or None


def int_or_none(value) -> int | None:
    """Целое поле нагрузки: пропуск, пустота и негодное значат отсутствие."""
    return _number_or_none(value, int)


def amount_or_none(value) -> int | None:
    """Сумма — целое больше нуля; ноль и меньше значат «не названо».

    Ноль в поле зарплаты пишут вместо пустоты и модель, и человек, а
    записанный суммой он затёр бы настоящую.
    """
    amount = int_or_none(value)
    return amount if amount is not None and amount > 0 else None


def float_or_none(value) -> float | None:
    """Дробное поле нагрузки: пропуск, пустота и негодное значат отсутствие."""
    return _number_or_none(value, float)


def _number_or_none(value, kind):
    """Число нагрузки названного вида; всё, что им не стало, — отсутствие.

    Окно шлёт числа строками — из полей ввода они приходят только так, — а
    пропущенное поле и очищенное человеком поле приходят вперемешку `None` и
    пустой строкой. Всем трём случаям у зовущих один смысл: этой границы не
    задавали.

    Негодное не роняет разбор, а читается как отсутствие: одно испорченное
    поле отбора иначе отняло бы у человека весь список, а не одну границу.
    Целое и дробное читаются одним договором: границы вилки зарплаты и
    границы счёта приходят из тех же полей ввода.
    """
    if value in (None, ""):
        return None
    try:
        return kind(value)
    except (TypeError, ValueError):
        return None


def moment_or_none(value) -> datetime | None:
    """Момент времени из нагрузки, записанный по ISO.

    Написание с хвостом «Z» — то, которым окно и шлёт границы отбора
    (`Date.toISOString`), — разбирается наравне с «+00:00»: с версии 3.11
    `fromisoformat` берёт оба, а проект требует 3.13.

    Негодное читается как отсутствие по тому же доводу, что и у целого:
    испорченная граница отбора не должна отнимать список целиком.
    """
    if not value:
        return None
    try:
        return datetime.fromisoformat(str(value))
    except ValueError:
        return None


def date_or_refusal(value, label: str) -> date | None:
    """Дата из поля окна по ISO; пусто — даты нет, негодная — отказ с её названием.

    В отличие от соседей негодное не читается отсутствием: дату человек
    выбирал в календаре, и запись без неё молча стёрла бы выбранное.
    """
    iso = (value or "").strip()
    if not iso:
        return None
    try:
        return date.fromisoformat(iso)
    except ValueError:
        raise ValueError(f"неверная дата {label}: {iso!r}")


def str_list(value) -> list[str]:
    """Непустые строки нагрузки, обрезанные по краям.

    Нагрузку составляет не наш код: список приходит то от модели, то из
    формы окна, и приходит в нём что угодно — не список вовсе, числа
    вперемешку со строками, пробелы по краям. Зовущим все эти случаи
    значат одно: взять то, что годится, и не уронить разбор.
    """
    if not isinstance(value, list):
        return []
    return [s.strip() for s in value if isinstance(s, str) and s.strip()]


def normalize_enum(value, allowed: tuple[str, ...]) -> str | None:
    """Значение из ответа модели, сведённое к справочнику, а чужое — как
    отсутствие.

    Зовут двое, и оба приводят пришедшее снаружи. Модель отвечает свободным
    текстом: то с заглавной, то с пробелами по краям, то словом, которого в
    справочнике нет вовсе. Нагрузку формы пишет страница, и негодное значение
    приезжает оттуда так же. Приговор, грейд и формат работы после этого либо
    ложатся в колонку из закрытого набора, либо не ложатся никак — третьего
    колонки не принимают.

    Дом здесь, а не у разбора ответов модели: колонку из закрытого набора
    держат оба пути, и второе такое же приведение рядом разошлось бы с первым
    молча — набранное руками принималось бы не тем правилом, что найденное
    ботом.
    """
    if not isinstance(value, str):
        return None
    v = value.strip().lower()
    if v in allowed:
        return v
    return None


def enum_member_or_none(value, kind: type[enum.Enum]):
    """Член перечисления по значению из ответа модели или формы; чужое — отсутствие.

    Приводится тем же правилом, что `normalize_enum`: колонку с перечислением
    наполняют оба пути, и правило у них одно.
    """
    known = normalize_enum(value, tuple(member.value for member in kind))
    return kind(known) if known is not None else None


def normalize_enum_list(values, allowed: tuple[str, ...]) -> list[str]:
    """Список, сведённый к закрытому набору: без чужого, без повторов.

    Дом общий с одиночным приведением и по тому же доводу: колонку из
    закрытого набора наполняют оба пути — разбор ответа модели и нагрузка
    формы, — и два таких приведения порознь расходятся молча, отвечая на одну
    и ту же строку по-разному.

    Порядок берётся у справочника, а не у входа: окно выкладывает отобранное
    именно в нём (см. `domain/taxonomy`).
    """
    if not isinstance(values, list):
        return []
    named = {normalize_enum(one, allowed) for one in values}
    return [one for one in allowed if one in named]
