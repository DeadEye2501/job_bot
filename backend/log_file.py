"""Файл журнала, переживающий сорванный переход на новый файл."""

from __future__ import annotations

import logging
from logging.handlers import RotatingFileHandler

from backend.log_secrets import report_own_failure

class LogFileHandler(RotatingFileHandler):
    """Обработчик файла журнала, переживающий сорванный переход на новый файл.

    Беда у него одна: пока файл открыт кем-то ещё — второй копией приложения,
    — Windows не даёт его ни переименовать, ни удалить, и переход отвечает
    отказом. Штатный `doRollover` в этом случае бросает, оставив поток
    закрытым, и в ту же ротацию упирается каждая следующая запись: разросшийся
    файл никуда не делся. Журнал замолкает до перезапуска.

    Отсюда обе половины ответа. Первая — деградация: предел размера снимается,
    и обработчик пишет в текущий файл дальше. Пробовать снова незачем — отказ
    повторится, а каждая попытка успевает снести старую копию, и за несколько
    записей от архива не осталось бы ничего.

    Вторая — засов на жалобу. Сказать о беде надо, но однажды: повторяющаяся
    трассировка растила бы ровно тот файл, которому уже нечем поворачиваться.
    """

    _complained = False

    def _complain_once(self, what: str, record: logging.LogRecord | None) -> None:
        """Пожаловаться однажды за всё время работы обработчика.

        Общий засов `report_own_failure_once` держит отметку на самой записи,
        а здесь жалоба бывает и без неё — переход на новый файл случается
        между записями, — и помнить приходится самому обработчику.
        """
        if self._complained:
            return
        self._complained = True
        report_own_failure(what, record)

    def doRollover(self) -> None:
        """Перейти на новый файл, а не сумев — писать в текущий без предела.

        Перехвачен весь переход, а не одно переименование: копии он
        перекладывает четырьмя обращениями к файловой системе, и упереться в
        занятый файл может любое из них.

        Поток здесь заново не открывают: следующая запись открывает его сама
        (`FileHandler.emit`), а в боевой сборке обработчик отложенный, и до
        открытия штатный переход не дошёл бы и без отказа.
        """
        try:
            super().doRollover()
        except OSError:
            self._complain_once("файл журнала не повернуть", None)
            self.maxBytes = 0

    def handleError(self, record: logging.LogRecord) -> None:
        self._complain_once("файл журнала не принял запись", record)
